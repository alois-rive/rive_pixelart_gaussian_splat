# Writes the cat's hedra command files from the spec's numbers (cat.spec.md, 452 px per metre off the
# RIGHT panel): p1_blockout.txt (every named part, scale applied), p2_form.txt (bevels, materials,
# the export of the gated hero cat.glb) and p3_parts.txt (run with --no-save: the game's parts
# cat_body.glb, cat_tail.glb with its origin at the tail's root, cat_leg.glb with its origin at the hip).
# Up Z, facing -Y, origin on the ground under the body's centre. Run from models/cat:
# /usr/bin/python3 make_cat.py
C = {"plum": "0.255 0.114 0.192", "wine": "0.388 0.106 0.204", "slate": "0.196 0.325 0.373",
     "mint": "0.188 0.882 0.725"}

# part: (x0, x1, y0, y1, z0, z1)  hedra metres
TORSO = (-0.225, 0.225, -0.26, 0.50, 0.25, 0.58)
HEAD = (-0.205, 0.205, -0.445, -0.08, 0.43, 0.70)
LEGX, LEGW = 0.13, 0.15           # legs at x +-0.13, 0.15 square
LEGY = (-0.13, 0.37)              # front and back legs' y
HIP = 0.34                        # the legs' top (the hip/shoulder pivot), reaching into the torso
TAIL_ROOT = (0.0, 0.44, 0.55)

def box(name, b, mat=None):
    x0, x1, y0, y1, z0, z1 = b
    L = [f"add mesh cube --name {name} --size 1 --location {(x0 + x1) / 2:.4f} {(y0 + y1) / 2:.4f} {(z0 + z1) / 2:.4f}",
         f"scale {x1 - x0:.4f} {y1 - y0:.4f} {z1 - z0:.4f}", "apply --scale"]
    return L

p1 = ["# Cat, phase 1: blockout of every named part at the spec's sizes (cat.spec.md). Up Z, facing -Y,",
      "# origin on the ground under the body. Generated by make_cat.py.", "new"]
p1 += box("Torso", TORSO)
p1 += box("Head", HEAD)
# muzzle: a 4-sided frustum pointing forward from the head's lower front
p1 += ["add mesh cone --name Muzzle --vertices 4 --radius1 0.115 --radius2 0.035 --depth 0.12 "
       "--location 0 -0.46 0.475 --rotation 90 0 45", "apply --rotation", "scale 1 1 0.8", "apply --scale"]
for s, n in ((-1, "L"), (1, "R")):
    # ears: 4-sided pyramids, base 0.15 x 0.15 at the head's top, tips at z 0.84, leaning out a little
    p1 += [f"add mesh cone --name Ear{n} --vertices 4 --radius1 0.105 --radius2 0.0 --depth 0.17 "
           f"--location {s * 0.14:.3f} -0.24 0.775 --rotation 0 {s * 8} 45", "apply --rotation"]
    # eyes: flat almonds (6-sided discs, squashed) just proud of the head's front
    p1 += [f"add mesh cylinder --name Eye{n} --vertices 6 --radius 0.065 --depth 0.04 "
           f"--location {s * 0.095:.3f} -0.455 0.585 --rotation 90 0 0", "apply --rotation",
           "scale 1 1 0.62", "apply --scale"]
legs = []
for i, (lx, ly) in enumerate(((-LEGX, LEGY[0]), (LEGX, LEGY[0]), (-LEGX, LEGY[1]), (LEGX, LEGY[1]))):
    p1 += box(f"Leg{i}", (lx - LEGW / 2, lx + LEGW / 2, ly - LEGW / 2, ly + LEGW / 2, 0.05, HIP))
    p1 += box(f"Paw{i}", (lx - 0.085, lx + 0.085, ly - 0.115, ly + 0.085, 0.0, 0.07))
# tail: a column up from the rump, a bar curling forward over it, the tip hanging down
p1 += ["add mesh cube --name TailA --size 1 --location 0 0 0", "scale 0.11 0.11 0.43", "apply --scale",
       "set rotation -12 0 0", "set location 0 0.475 0.735"]          # leaning back as it rises
p1 += box("TailB", (-0.055, 0.055, 0.33, 0.585, 0.89, 1.0))
p1 += box("TailC", (-0.055, 0.055, 0.31, 0.40, 0.80, 0.93))
p1 += ["inspect stats"]
open("p1_blockout.txt", "w").write("\n".join(p1) + "\n")

p2 = ["# Cat, phase 2: chamfers that make it faceted, materials (Cyclope6 colours, exact), flat shading,",
      "# the export of the gated hero. Run after p1_blockout.txt. Generated by make_cat.py.",
      f"material new Fur --base-color {C['wine']} --no-slot",
      f"material new Slate --base-color {C['slate']} --no-slot",
      f"material new Eye --base-color {C['mint']} --emission {C['mint']} --no-slot"]
for name, amt in (("Torso", 0.07), ("Head", 0.06), ("TailA", 0.025), ("TailB", 0.025), ("TailC", 0.025)):
    p2 += [f"select {name}", f"active {name}", "mode edit", "select all", f"bevel {amt} --segments 1", "mode object"]
# the torso's chest: pull its lower front edge in, so the chest slopes back under the head
p2 += ["select Torso", "active Torso", "mode edit", 'select vert where "pos.y < -0.1 && pos.z < 0.36"',
       "translate 0 0.05 0", "mode object"]
fur = ["Torso", "Head", "EarL", "EarR", "TailA", "TailB", "TailC"] + [f"Leg{i}" for i in range(4)]
p2 += ["select " + " ".join(fur), "material assign Fur",
       "select Muzzle " + " ".join(f"Paw{i}" for i in range(4)), "material assign Slate",
       "select EyeL EyeR", "material assign Eye",
       "select all", "shade flat", "export cat.glb"]
open("p2_form.txt", "w").write("\n".join(p2) + "\n")

# p3: the splat fit. Splats grow about one radius (one spacing, 0.0565 m on the bench) past every
# silhouette, so the widths seen from the front, back and top come out 25 % too wide; this phase only
# narrows parts (each about its own centre) and lengthens the ear tips that erode. Run with
# `--no-save --to cat_fit.rmdl` so cat.rmdl stays the gated form. The bake uses cat_fit.glb.
FIT = {"Torso": (0.80, 1, 1), "Head": (0.82, 1, 1), "Muzzle": (0.85, 1, 1), "EarL": (0.85, 1, 1.15),
       "EarR": (0.85, 1, 1.15), **{f"Leg{i}": (0.75, 0.9, 1) for i in range(4)},
       **{f"Paw{i}": (0.8, 0.9, 1) for i in range(4)}}
p3 = ["# Cat, phase 3: the splat fit (see make_cat.py). Run with --no-save --to cat_fit.rmdl after p2.",
      "# Generated by make_cat.py."]
for name, (sx, sy, sz) in FIT.items():
    p3 += [f"select {name}", f"scale {sx} {sy} {sz}", "apply --scale"]
p3 += ["select EarL", "translate 0 0 0.012", "select EarR", "translate 0 0 0.012",
       "select all", "export cat_fit.glb"]
open("p3_splat_fit.txt", "w").write("\n".join(p3) + "\n")

# p4: the game's parts from the fitted model (run on cat_fit.rmdl with --no-save)
p4 = ["# Cat, phase 4 (run with --no-save on cat_fit.rmdl): the game's parts. The body (torso, head,",
      "# ears, eyes, muzzle), the tail with its origin at its root (the game sways it) and one leg with",
      "# its paw with its origin at the hip (four copies in the scene, swung by the game); each part's",
      "# pivot moved to the world origin so the bake entry's position is the pivot. Generated by make_cat.py.",
      "select TailA TailB TailC", "active TailA", "join", "rename TailA Tail",
      f"cursor set {TAIL_ROOT[0]} {TAIL_ROOT[1]} {TAIL_ROOT[2]}", "origin set --to cursor", "set location 0 0 0",
      "select Leg0 Paw0", "active Leg0", "join",
      f"cursor set {-LEGX} {LEGY[0]} {HIP}", "origin set --to cursor", "set location 0 0 0",
      "select Tail", "export cat_tail.glb --selection",
      "select Leg0", "export cat_leg.glb --selection",
      "select Torso Head Muzzle EarL EarR EyeL EyeR", "export cat_body.glb --selection"]
open("p4_parts.txt", "w").write("\n".join(p4) + "\n")
print("wrote p1_blockout.txt, p2_form.txt, p3_splat_fit.txt, p4_parts.txt")
