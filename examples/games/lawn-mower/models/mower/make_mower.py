# Writes the mower's hedra command files from the spec (mower.spec.md): p1_blockout.txt (one primitive
# per part at the spec's sizes, materials in the final Endesga 16 colours) and p2_form.txt (the hood's
# slope, hubs inset into the wheels, flat shading, the export). Run from models/mower:
# /usr/bin/python3 make_mower.py. hedra: up Z, front -Y; origin on the ground under the body's centre
# (the game turns the mower about it).
C = {"Red": "0.898 0.231 0.267", "Tyre": "0.247 0.157 0.196", "Hub": "0.686 0.749 0.824",
     "Deck": "0.310 0.404 0.506", "Seat": "0.455 0.247 0.224", "Shirt": "0.016 0.518 0.820",
     "Skin": "0.894 0.651 0.447", "Hat": "1.000 0.906 0.384"}

def box(name, x0, x1, y0, y1, z0, z1, mat):
    return [f"add mesh cube --name {name} --size 1 --location {(x0 + x1) / 2:.4f} {(y0 + y1) / 2:.4f} {(z0 + z1) / 2:.4f}",
            f"scale {x1 - x0:.4f} {y1 - y0:.4f} {z1 - z0:.4f}", "apply --scale", f"material assign {mat}"]

p1 = ["# Mower, phase 1: blockout at the spec's sizes (generated by make_mower.py).", "new"]
p1 += [f"material new {k} --base-color {v} --no-slot" for k, v in C.items()]
p1 += box("Chassis", -0.315, 0.315, -0.71, 0.71, 0.14, 0.43, "Red")
p1 += box("Hood", -0.30, 0.30, -0.71, -0.09, 0.40, 0.61, "Red")
p1 += box("Rear", -0.315, 0.315, 0.20, 0.71, 0.40, 0.53, "Red")
p1 += box("Deck", -0.40, 0.40, -0.37, 0.33, 0.045, 0.14, "Deck")
p1 += box("Chute", -0.65, -0.38, -0.29, 0.055, 0.08, 0.22, "Deck")
for side, sx in (("L", -1), ("R", 1)):
    p1 += [f"add mesh cylinder --name Rear{side} --vertices 10 --radius 0.25 --depth 0.17 --location {sx * 0.40} 0.56 0.25 --rotation 0 90 0",
           "material assign Tyre",
           f"add mesh cylinder --name Front{side} --vertices 8 --radius 0.16 --depth 0.14 --location {sx * 0.385} -0.56 0.16 --rotation 0 90 0",
           "material assign Tyre"]
p1 += box("Cushion", -0.22, 0.22, 0.25, 0.60, 0.53, 0.60, "Seat")
p1 += box("Backrest", -0.22, 0.22, 0.58, 0.72, 0.53, 0.91, "Seat")
p1 += box("Column", -0.03, 0.03, -0.12, -0.06, 0.50, 0.82, "Seat")
p1 += ["add mesh cylinder --name Wheel --vertices 8 --radius 0.13 --depth 0.05 --location 0 -0.10 0.83 --rotation -35 0 0",
       "material assign Seat"]
# the gardener
p1 += box("Thighs", -0.15, 0.15, 0.09, 0.39, 0.55, 0.69, "Seat")
p1 += box("Shins", -0.14, 0.14, -0.01, 0.11, 0.43, 0.63, "Seat")
p1 += box("Torso", -0.18, 0.18, 0.265, 0.515, 0.63, 0.97, "Shirt")
p1 += box("ArmL", -0.27, -0.17, -0.05, 0.42, 0.82, 0.92, "Shirt")
p1 += box("ArmR", 0.17, 0.27, -0.05, 0.42, 0.82, 0.92, "Shirt")
p1 += box("HandL", -0.22, -0.12, -0.16, -0.05, 0.80, 0.90, "Skin")
p1 += box("HandR", 0.12, 0.22, -0.16, -0.05, 0.80, 0.90, "Skin")
p1 += box("Head", -0.10, 0.10, 0.29, 0.49, 0.97, 1.14, "Skin")
p1 += ["add mesh cylinder --name Brim --vertices 10 --radius 0.275 --depth 0.04 --location 0 0.39 1.155",
       "material assign Hat",
       "add mesh cone --name Crown --vertices 8 --radius1 0.13 --radius2 0.10 --depth 0.13 --location 0 0.39 1.235",
       "material assign Hat"]
open("p1_blockout.txt", "w").write("\n".join(p1) + "\n")

p2 = ["# Mower, phase 2: form (the hood slopes down to the nose, hubs inset into the wheels), flat shading,",
      "# hidden caps removed, export.",
      "select Hood", "active Hood", "mode edit", 'select vert where "pos.y < 0 && pos.z > 0"', "translate 0 0 -0.15",
      "mode object"]
for w in ("RearL", "RearR", "FrontL", "FrontR"):
    inset = 0.11 if w.startswith("Rear") else 0.07
    p2 += [f"select {w}", f"active {w}", "mode edit", 'select face where "abs(normal.z) > 0.9"',
           f"inset {inset}", "material assign Hub", "mode object"]
p2 += ["select all", "shade flat", "export mower.glb"]
open("p2_form.txt", "w").write("\n".join(p2) + "\n")
