# Writes the skater's hedra command files from the spec's numbers (skater.spec.md, 290 px per metre
# off the FRONT panel of art/skater/sheet.v1.png):
#   p1_blockout.txt  every named part at the spec's sizes, scale applied
#   p2_form.txt      chamfers, materials (AAP-64 colours, exact), flat shading, export skater.glb (gated)
#   p3_splat_fit.txt the splat fit (run --no-save --to skater_fit.rmdl): narrows parts the discs fatten
#   p4_parts.txt     the game's parts (run --no-save on skater_fit.rmdl): board, torso (with the head),
#                    one arm, one thigh, one shin, one shoe, each with its origin at its pivot moved to
#                    the world origin; limbs rebuilt straight down so their rest direction is -Z
# Up Z, facing -Y (the chest), the board's nose at +X; origin on the ground under the board's centre.
# Run from models/skater: /usr/bin/python3 make_skater.py
import math

def rgb(h):
    h = h.lstrip("#")
    return " ".join(f"{int(h[i:i + 2], 16) / 255:.4f}" for i in (0, 2, 4))

C = {"Hoodie": "#df3e23", "Beanie": "#ffd541", "Denim": "#285cc4", "Skin": "#dba463", "Shoe": "#dae0ea",
     "Deck": "#bc4a9b", "Grip": "#333941", "Steel": "#8b93af", "Wheel": "#fef3c0", "Eye": "#141013",
     "Hair": "#71413b"}

# ---- the spec (metres, hedra axes)
DECK_L, DECK_W, DECK_Z0, DECK_Z1 = 0.84, 0.38, 0.17, 0.22     # the flat middle of the deck
KICK_L, KICK_A = 0.17, 18.0                                    # nose and tail, kicked up 18 degrees
TRUCK_X, WHEEL_R, WHEEL_W, WHEEL_Y = 0.345, 0.06, 0.07, 0.15
FOOT_X, SHOE = 0.31, (0.29, 0.32, 0.15)                        # shoe w (x), l (y), h; sole on the deck top
HIP = (0.10, 0.70)                                             # hip joint x, z
ANKLE_Z = 0.34                                                 # the shin's lower end (inside the shoe)
KNEE_FWD = 0.035                                               # knees bent a little towards -Y
THIGH_W, SHIN_W = (0.15, 0.17), (0.17, 0.19)
CUFF = (0.22, 0.23, 0.07)
TORSO = (-0.18, 0.18, -0.155, 0.13, 0.68, 1.14)
SHOULDER = (0.195, 1.06)
WRIST = (0.335, 0.755)
SLEEVE_W = (0.13, 0.14)
HAND = 0.11
HEAD = (-0.20, 0.20, -0.18, 0.18, 1.13, 1.41)
BEANIE_R = 0.25

def box(name, b):
    x0, x1, y0, y1, z0, z1 = b
    return [f"add mesh cube --name {name} --size 1 --location {(x0 + x1) / 2:.4f} {(y0 + y1) / 2:.4f} {(z0 + z1) / 2:.4f}",
            f"scale {x1 - x0:.4f} {y1 - y0:.4f} {z1 - z0:.4f}", "apply --scale"]

def seg(name, p0, p1, w, d):
    """A box w (x) by d (y) from p0 to p1: scaled along Z, turned onto the segment (R = Ry . Rx)."""
    dx, dy, dz = (p1[i] - p0[i] for i in range(3))
    L = math.sqrt(dx * dx + dy * dy + dz * dz)
    a = math.degrees(math.asin(-dy / L))
    b = math.degrees(math.atan2(dx, dz))
    m = [(p0[i] + p1[i]) / 2 for i in range(3)]
    return [f"add mesh cube --name {name} --size 1 --location 0 0 0", f"scale {w:.4f} {d:.4f} {L:.4f}", "apply --scale",
            f"set rotation {a:.3f} {b:.3f} 0", "apply --rotation", f"set location {m[0]:.4f} {m[1]:.4f} {m[2]:.4f}",
            "apply --location"]

def leg_points(s):
    hip = (s * HIP[0], 0.0, HIP[1])
    ank = (s * (FOOT_X - 0.02), 0.0, ANKLE_Z)
    knee = ((hip[0] + ank[0]) / 2, -KNEE_FWD, (hip[2] + ank[2]) / 2)
    return hip, knee, ank

def arm_points(s):
    return (s * SHOULDER[0], 0.0, SHOULDER[1]), (s * WRIST[0], -0.01, WRIST[1])

p1 = ["# Skater, phase 1: blockout of every named part at the spec's sizes (skater.spec.md). Up Z, facing -Y,",
      "# the board's nose at +X, origin on the ground under the board. Generated by make_skater.py.", "new"]
# board: the flat middle, the two kicks, two trucks, four wheels
p1 += box("Deck", (-DECK_L / 2, DECK_L / 2, -DECK_W / 2, DECK_W / 2, DECK_Z0, DECK_Z1))
for s, n in ((1, "NoseKick"), (-1, "Tail")):
    ca, sa = math.cos(math.radians(KICK_A)), math.sin(math.radians(KICK_A))
    cx = s * (DECK_L / 2 + KICK_L / 2 * ca - 0.01)
    cz = (DECK_Z0 + DECK_Z1) / 2 + KICK_L / 2 * sa
    p1 += [f"add mesh cube --name {n} --size 1 --location 0 0 0", f"scale {KICK_L + 0.02:.4f} {DECK_W:.4f} {DECK_Z1 - DECK_Z0:.4f}",
           "apply --scale", f"set rotation 0 {-s * KICK_A:.2f} 0", "apply --rotation",
           f"set location {cx:.4f} 0 {cz:.4f}", "apply --location"]
for s, n in ((1, "F"), (-1, "B")):
    p1 += box(f"Truck{n}", (s * TRUCK_X - 0.05, s * TRUCK_X + 0.05, -0.13, 0.13, 0.115, DECK_Z0 + 0.005))
    for t, m in ((1, "L"), (-1, "R")):
        p1 += [f"add mesh cylinder --name Wheel{n}{m} --vertices 8 --radius {WHEEL_R} --depth {WHEEL_W} "
               f"--location {s * TRUCK_X:.4f} {t * WHEEL_Y:.4f} {WHEEL_R:.4f} --rotation 90 22.5 0", "apply --rotation"]
# shoes, legs (thigh, shin, cuff), torso, hood, arms, hands
for s, n in ((-1, "B"), (1, "F")):
    p1 += box(f"Shoe{n}", (s * FOOT_X - SHOE[0] / 2, s * FOOT_X + SHOE[0] / 2, -0.03 - SHOE[1] / 2, -0.03 + SHOE[1] / 2,
                           DECK_Z1, DECK_Z1 + SHOE[2]))
    hip, knee, ank = leg_points(s)
    p1 += seg(f"Thigh{n}", hip, knee, *THIGH_W)
    p1 += seg(f"Shin{n}", knee, ank, *SHIN_W)
    p1 += box(f"Cuff{n}", (ank[0] - CUFF[0] / 2, ank[0] + CUFF[0] / 2, -CUFF[1] / 2, CUFF[1] / 2, ank[2], ank[2] + CUFF[2]))
p1 += box("Torso", TORSO)
p1 += box("Hood", (-0.14, 0.14, 0.10, 0.20, 0.96, 1.16))
for s, n in ((-1, "B"), (1, "F")):
    sh, wr = arm_points(s)
    p1 += seg(f"Arm{n}", sh, wr, *SLEEVE_W)
    p1 += box(f"Hand{n}", (wr[0] - HAND / 2, wr[0] + HAND / 2, wr[1] - HAND / 2, wr[1] + HAND / 2, wr[2] - 0.12, wr[2] - 0.01))
# head: the block, the hair under the beanie, ears, nose, eyes; the beanie (rim and a two-step dome)
p1 += box("Head", HEAD)
p1 += box("Hair", (-0.21, 0.21, -0.15, 0.19, 1.29, 1.42))
p1 += box("EarB", (-0.245, -0.195, -0.055, 0.055, 1.205, 1.32))
p1 += box("EarF", (0.195, 0.245, -0.055, 0.055, 1.205, 1.32))
p1 += box("Nose", (-0.04, 0.04, -0.225, -0.17, 1.205, 1.295))
p1 += box("EyeB", (-0.105, -0.055, -0.195, -0.17, 1.29, 1.345))
p1 += box("EyeF", (0.055, 0.105, -0.195, -0.17, 1.29, 1.345))
p1 += [f"add mesh cylinder --name Rim --vertices 8 --radius {BEANIE_R} --depth 0.09 --location 0 0 1.425 --rotation 0 0 0",
       "apply --rotation",
       f"add mesh cone --name Dome --vertices 8 --radius1 {BEANIE_R - 0.01} --radius2 0.185 --depth 0.10 --location 0 0 1.52 --rotation 0 0 0",
       "apply --rotation",
       "add mesh cone --name Crown --vertices 8 --radius1 0.185 --radius2 0.06 --depth 0.10 --location 0 0 1.62 --rotation 0 0 0",
       "apply --rotation", "inspect stats"]
open("p1_blockout.txt", "w").write("\n".join(p1) + "\n")

p2 = ["# Skater, phase 2: chamfers, materials (AAP-64 colours, exact), flat shading, the export of the gated",
      "# hero. Run after p1_blockout.txt. Generated by make_skater.py."]
for m, hx in C.items():
    p2 += [f"material new {m} --base-color {rgb(hx)} --no-slot"]
for name, amt in (("Torso", 0.04), ("Head", 0.04), ("ShoeB", 0.035), ("ShoeF", 0.035), ("Hood", 0.03),
                  ("Hair", 0.03), ("ThighB", 0.02), ("ThighF", 0.02), ("ShinB", 0.02), ("ShinF", 0.02),
                  ("ArmB", 0.02), ("ArmF", 0.02), ("HandB", 0.025), ("HandF", 0.025), ("Deck", 0.012)):
    p2 += [f"select {name}", f"active {name}", "mode edit", "select all", f"bevel {amt} --segments 1", "mode object"]
groups = {"Hoodie": ["Torso", "Hood", "ArmB", "ArmF"], "Denim": ["ThighB", "ThighF", "ShinB", "ShinF", "CuffB", "CuffF"],
          "Skin": ["Head", "HandB", "HandF", "EarB", "EarF", "Nose"], "Shoe": ["ShoeB", "ShoeF"],
          "Beanie": ["Rim", "Dome", "Crown"], "Hair": ["Hair"], "Eye": ["EyeB", "EyeF"],
          "Deck": ["Deck", "NoseKick", "Tail"], "Steel": ["TruckF", "TruckB"],
          "Wheel": ["WheelFL", "WheelFR", "WheelBL", "WheelBR"]}
for m, objs in groups.items():
    p2 += ["select " + " ".join(objs), f"material assign {m}"]
# grip tape on every upward face of the deck and its kicks
for name in ("Deck", "NoseKick", "Tail"):
    p2 += [f"select {name}", f"active {name}", "mode edit", "select none", 'select face where "normal.z > 0.6"',
           "material assign Grip", "mode object"]
p2 += ["select all", "shade flat", "export skater.glb"]
open("p2_form.txt", "w").write("\n".join(p2) + "\n")

# p3: the splat fit. Discs reach about a radius (one spacing, 0.055 m) past every silhouette, so the
# beanie and the head come out deeper than drawn (right view too wide, top view too deep): this phase
# only narrows parts about their own centres. Run with `--no-save --to skater_fit.rmdl` so skater.rmdl
# stays the gated form; the bake uses skater_fit.glb.
FIT = {"Rim": (0.94, 0.84, 1), "Dome": (0.94, 0.84, 1), "Crown": (0.94, 0.84, 1), "Head": (0.94, 0.86, 1),
       "Hair": (0.94, 0.86, 1), "Deck": (1, 0.86, 1), "NoseKick": (1, 0.86, 1), "Tail": (1, 0.86, 1),
       "TruckF": (1, 0.86, 1), "TruckB": (1, 0.86, 1), "ShoeB": (0.9, 0.9, 1), "ShoeF": (0.9, 0.9, 1),
       "Torso": (0.92, 0.9, 1), "Hood": (0.9, 0.9, 1)}
p3 = ["# Skater, phase 3: the splat fit (see make_skater.py). Run with --no-save --to skater_fit.rmdl after p2.",
      "# Generated by make_skater.py."]
for name, (sx, sy, sz) in FIT.items():
    p3 += [f"select {name}", f"scale {sx} {sy} {sz}", "apply --scale"]
for n in ("FL", "BL"):
    p3 += [f"select Wheel{n}", "translate 0 -0.02 0"]
for n in ("FR", "BR"):
    p3 += [f"select Wheel{n}", "translate 0 0.02 0"]
p3 += ["select all", "export skater_fit.glb"]
open("p3_splat_fit.txt", "w").write("\n".join(p3) + "\n")

# p4: the game's parts from the fitted model (run on skater_fit.rmdl with --no-save). The board and the
# torso (with the head and beanie) keep their fitted geometry; the limbs are rebuilt straight down from
# their joint (the game turns them, so their rest direction must be simple): arm (shoulder -> hand),
# thigh (hip -> knee), shin (knee -> ankle, with the cuff), shoe (origin on the sole under the ankle).
# Each part's pivot is moved to the world origin, so a bake entry's "position" is its pivot.
def joint_len(a, b):
    return math.sqrt(sum((a[i] - b[i]) ** 2 for i in range(3)))

hip, knee, ank = leg_points(1)
sh, wr = arm_points(1)
L_THIGH, L_SHIN, L_ARM = joint_len(hip, knee), joint_len(knee, ank), joint_len(sh, wr)
BOARD_Z = (DECK_Z0 + DECK_Z1) / 2

def straight(name, w, d, z0, z1, mat, bev):
    return box(name, (-w / 2, w / 2, -d / 2, d / 2, z0, z1)) + [
        f"select {name}", f"active {name}", "mode edit", "select all", f"bevel {bev} --segments 1", "mode object",
        f"material assign {mat}"]

p4 = ["# Skater, phase 4 (run with --no-save on skater_fit.rmdl): the game's parts (see make_skater.py).",
      "# Generated by make_skater.py.",
      "select Deck NoseKick Tail TruckF TruckB WheelFL WheelFR WheelBL WheelBR", "active Deck", "join",
      f"cursor set 0 0 {BOARD_Z:.4f}", "origin set --to cursor", "set location 0 0 0",
      "select Deck", "export skater_board.glb --selection",
      "select Torso Hood Head Hair EarB EarF Nose EyeB EyeF Rim Dome Crown", "active Torso", "join",
      f"cursor set 0 0 {HIP[1]:.4f}", "origin set --to cursor", "set location 0 0 0",
      "select Torso", "export skater_torso.glb --selection",
      "select ShoeF", "active ShoeF", f"cursor set {FOOT_X:.4f} 0 {DECK_Z1:.4f}", "origin set --to cursor",
      "set location 0 0 0", "select ShoeF", "export skater_shoe.glb --selection",
      "select ArmB ArmF HandB HandF ThighB ThighF ShinB ShinF CuffB CuffF", "delete"]
p4 += straight("ArmS", SLEEVE_W[0], SLEEVE_W[1], -L_ARM, 0.0, "Hoodie", 0.02)
p4 += straight("HandS", HAND, HAND, -L_ARM - 0.10, -L_ARM + 0.01, "Skin", 0.025)
p4 += ["select ArmS HandS", "active ArmS", "join", "select ArmS", "export skater_arm.glb --selection"]
p4 += straight("ThighS", THIGH_W[0], THIGH_W[1], -L_THIGH - 0.01, 0.0, "Denim", 0.02)
p4 += ["select ThighS", "export skater_thigh.glb --selection"]
p4 += straight("ShinS", SHIN_W[0], SHIN_W[1], -L_SHIN, 0.0, "Denim", 0.02)
p4 += box("CuffS", (-CUFF[0] / 2, CUFF[0] / 2, -CUFF[1] / 2, CUFF[1] / 2, -L_SHIN, -L_SHIN + CUFF[2]))
p4 += ["select CuffS", "material assign Denim", "select ShinS CuffS", "active ShinS", "join",
       "select ShinS", "export skater_shin.glb --selection"]
open("p4_parts.txt", "w").write("\n".join(p4) + "\n")
print(f"wrote p1-p4; thigh {L_THIGH:.4f} shin {L_SHIN:.4f} arm {L_ARM:.4f} board z {BOARD_Z:.3f}")
