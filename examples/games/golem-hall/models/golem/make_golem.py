#!/usr/bin/env python3
"""Writes the golem's hedra command files from its spec (golem.spec.md, 195 px per metre in the sheet's
front panel). Up Z, facing -Y, origin on the ground between the feet. Every round part is an eight-sided
prism turned 22.5 degrees so a flat faces the front, as the sheet draws it.

  p1_blockout.txt   every named part at the spec's sizes (no materials)
  p2_form.txt       materials in exact URBEX 16 colours, joined into the five game parts with their
                    pivots (Body; ArmL/ArmR at the shoulders; LegL/LegR at the hips), export golem.glb
  p3_<part>.txt     one game part alone, its pivot moved to 0 0 0, export golem_<part>.glb

Run from this folder: /usr/bin/python3 make_golem.py (build.sh does)."""
import math

SH_X, SH_Z = 0.72, 1.78        # shoulder pivot
HIP_X, HIP_Z = 0.29, 0.62      # hip pivot

L = ["# Golem, phase 1: blockout of every named part at the spec's sizes (generated by make_golem.py).",
     "# Up Z, facing -Y, origin on the ground between the feet; 8-gons turned 22.5 deg (a flat in front).",
     "new"]


def prism(name, r, z0, z1, x=0.0, y=0.0, r2=None, sy=1.0):
    """an eight-sided prism (or frustum to r2) from z0 to z1, a flat facing front"""
    d = z1 - z0
    if r2 is None:
        L.append(f"add mesh cylinder --name {name} --vertices 8 --radius {r:.3f} --depth {d:.3f} --location {x:.3f} {y:.3f} {(z0 + z1) / 2:.3f}")
    else:
        L.append(f"add mesh cone --name {name} --vertices 8 --radius1 {r:.3f} --radius2 {r2:.3f} --depth {d:.3f} --location {x:.3f} {y:.3f} {(z0 + z1) / 2:.3f}")
    L.append("set rotation 0 0 22.5")   # hedra's 8-gon has a corner in front: turn a flat to the front
    L.append("apply --rotation")
    if sy != 1.0:
        L.append(f"scale 1 {sy:.3f} 1")
        L.append("apply --scale")


def box(name, cx, cy, cz, sx, sy, sz, rot_y=0.0):
    L.append(f"add mesh cube --name {name} --size 1 --location {cx:.3f} {cy:.3f} {cz:.3f}")
    L.append(f"scale {sx:.3f} {sy:.3f} {sz:.3f}")
    L.append("apply --scale")
    if rot_y:
        L.append(f"set rotation 0 {rot_y:.2f} 0")
        L.append("apply --rotation")


C8 = math.cos(math.radians(22.5))
for s, n in ((1, "L"), (-1, "R")):
    x = s * HIP_X
    prism(f"Foot{n}", 0.27, 0.0, 0.14, x, -0.08, sy=1.15)
    prism(f"Leg{n}", 0.23, 0.13, 0.60, x, -0.03, sy=1.1)
prism("Hips", 0.47, 0.57, 0.80)
prism("UrnLow", 0.41, 0.80, 1.45, r2=0.61)
prism("UrnTop", 0.61, 1.45, 1.70, r2=0.55)
prism("Band", 0.56, 1.03, 1.11)     # 6 cm proud of the urn: a splat spacing
prism("Rim", 0.62, 1.70, 1.85)
box("Yoke", 0, 0, 1.775, 1.5, 0.42, 0.15)
for s, n in ((1, "L"), (-1, "R")):
    prism(f"Knob{n}", 0.25, 1.70, 1.87, s * SH_X)
    prism(f"Moss{n}", 0.24, 1.86, 1.95, s * SH_X, r2=0.15)
prism("HeadBase", 0.39, 1.84, 2.05)
prism("HeadDome", 0.39, 2.05, 2.30, r2=0.16)
# the visor slit: a bar standing off the head's front flat
box("Visor", 0, -(0.39 * C8 + 0.04), 1.965, 0.40, 0.09, 0.07)
# the chest rune: a ring of eight bars (radius 0.15 about z 1.40) and one vertical bar, standing off the
# urn's sloped front (its front flat at each height) by about a splat spacing, so the urn's splats do
# not swallow it


def urn_r(z):
    if z <= 1.45:
        return 0.41 + 0.20 * (z - 0.80) / 0.65
    return 0.61 - 0.06 * (z - 1.45) / 0.25


RC, RR = 1.40, 0.15
seg = 2 * RR * math.tan(math.radians(22.5)) + 0.05
for k in range(8):
    a = math.radians(45 * k)
    cx, cz = RR * math.cos(a), RC + RR * math.sin(a)
    cy = -(urn_r(cz) * C8 + 0.04)
    box(f"Rune{k}", cx, cy, cz, seg, 0.09, 0.06)
    L.append(f"set rotation 0 {-(45 * k + 90):.1f} 0")
    L.append("apply --rotation")
box("RuneBar", 0, -(urn_r(RC) * C8 + 0.05), RC, 0.06, 0.09, 0.46)
# arms: upper arm, forearm, a big mitten fist, hanging from the shoulder knobs
for s, n in ((1, "L"), (-1, "R")):
    prism(f"Upper{n}", 0.17, 1.26, 1.74, s * 0.76)
    prism(f"Fore{n}", 0.245, 0.80, 1.30, s * 0.83, -0.08)
    prism(f"Fist{n}", 0.30, 0.42, 0.82, s * 0.83, -0.15, sy=0.93)
L += ["select all", "inspect stats"]
open("p1_blockout.txt", "w").write("\n".join(L) + "\n")

# ---------------------------------------------------------------- phase 2: materials, parts, pivots
COL = {"Clay": "0.663 0.192 0.188", "ClayDark": "0.478 0.075 0.220", "Band": "0.878 0.643 0.431",
       "Glow": "0.341 0.624 0.706", "Moss": "0.365 0.463 0.263"}
P = ["# Golem, phase 2: materials in exact URBEX 16 colours (sRGB 0..1), joined into the five game parts",
     "# with their pivots, flat shading, export (generated by make_golem.py). Clay #a93130 (clay step 2),",
     "# ClayDark #7a1338 (clay step 1), Band #e0a46e (clay step 3), Glow #579fb4 (rune step 3, unlit),",
     "# Moss #5d7643 (moss step 2)."]
for m, c in COL.items():
    P.append(f"material new {m} --base-color {c} --no-slot")
# caps that are buried in a neighbour, or face down below the eye and away from a standing player (the
# camera is at 1.6 m): they would only bake hidden splats
CAPS = {"top": ["FootL", "FootR", "LegL", "LegR", "Hips", "UrnLow", "UrnTop", "Band", "Rim", "Yoke", "KnobL",
                "KnobR", "HeadBase", "UpperL", "UpperR"],
        "bottom": ["FootL", "FootR", "LegL", "LegR", "Hips", "UrnLow", "UrnTop", "Band", "Rim", "MossL", "MossR",
                   "HeadBase", "HeadDome", "UpperL", "UpperR", "ForeL", "ForeR", "FistL", "FistR"]}
for obj in sorted(set(CAPS["top"]) | set(CAPS["bottom"])):
    q = []
    if obj in CAPS["top"]:
        q.append("normal.z > 0.9")
    if obj in CAPS["bottom"]:
        q.append("normal.z < -0.9")
    P += [f"select {obj}", f"active {obj}", "mode edit", f'select face where "{" || ".join(q)}"', "delete face", "mode object"]
runes = " ".join(f"Rune{k}" for k in range(8))
P += ["select LegL LegR UrnLow UrnTop HeadBase HeadDome UpperL UpperR ForeL ForeR", "material assign Clay",
      "select FootL FootR Hips Rim Yoke KnobL KnobR FistL FistR", "material assign ClayDark",
      "select Band", "material assign Band",
      f"select Visor RuneBar {runes}", "material assign Glow",
      "select MossL MossR", "material assign Moss"]
P += [f"select Hips UrnLow UrnTop Band Rim Yoke KnobL KnobR MossL MossR HeadBase HeadDome Visor RuneBar {runes}",
      "active UrnLow", "join", "rename UrnLow Body",
      "cursor set 0 0 0", "origin set --to cursor"]
for s, n in ((1, "L"), (-1, "R")):
    P += [f"select Upper{n} Fore{n} Fist{n}", f"active Upper{n}", "join", f"rename Upper{n} Arm{n}",
          f"cursor set {s * SH_X:.3f} 0 {SH_Z:.3f}", "origin set --to cursor",
          f"select Leg{n} Foot{n}", f"active Leg{n}", "join",
          f"cursor set {s * HIP_X:.3f} 0 {HIP_Z:.3f}", "origin set --to cursor"]
P += ["select all", "shade flat", "inspect stats", "export golem.glb"]
open("p2_form.txt", "w").write("\n".join(P) + "\n")

PARTS = ["Body", "ArmL", "ArmR", "LegL", "LegR"]
for part in PARTS:
    others = " ".join(p for p in PARTS if p != part)
    Q = [f"# Golem, phase 3: the game part {part} alone, its pivot moved to 0 0 0 (generated by make_golem.py).",
         f"select {others}", "delete", f"select {part}", "set location 0 0 0", f"export golem_{part.lower()}.glb"]
    open(f"p3_{part.lower()}.txt", "w").write("\n".join(Q) + "\n")
print("wrote p1_blockout.txt p2_form.txt p3_*.txt")
