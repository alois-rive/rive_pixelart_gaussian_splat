# Writes p1_blockout.txt for the bee from the spec's numbers (bee.spec.md): the abdomen as eight
# banded frustum rings along Y, the wings and antennae turned by computed Euler angles (hedra's
# extrinsic XYZ, R = Rz Ry Rx). Run from models/bee: /usr/bin/python3 make_bee.py
import math
import numpy as np

def euler_from(M):
    ry = -math.asin(max(-1, min(1, M[2, 0])))
    rx = math.atan2(M[2, 1], M[2, 2]); rz = math.atan2(M[1, 0], M[0, 0])
    return [math.degrees(a) for a in (rx, ry, rz)]

def align_z(d):
    """a rotation taking local +Z onto d (local X kept as horizontal as possible)"""
    d = np.asarray(d, float); d /= np.linalg.norm(d)
    x = np.cross([0, 0, 1.0], d) if abs(d[2]) < 0.99 else np.array([1.0, 0, 0])
    if np.linalg.norm(x) < 1e-6: x = np.array([1.0, 0, 0])
    x /= np.linalg.norm(x); y = np.cross(d, x)
    return euler_from(np.stack([x, y, d], 1))

L = ["# Bee, phase 1: blockout of every named part at the spec's sizes (bee.spec.md, 500 px per metre",
     "# off the RIGHT panel). Up Z, facing -Y, origin at the abdomen's centre. Generated by make_bee.py.",
     "new"]
# abdomen: ellipsoid profile (half length 0.33 along Y, radius 0.24 across), bands as rings
B = [-0.315, -0.276, -0.206, -0.116, -0.016, 0.084, 0.184, 0.264, 0.318]
r = lambda y: 0.285 * math.sqrt(max(0.0, 1 - (y / 0.335) ** 2))
for i in range(len(B) - 1):
    y0, y1 = B[i], B[i + 1]
    L.append(f"add mesh cone --name Seg{i} --vertices 8 --radius1 {r(y0):.4f} --radius2 {r(y1):.4f} "
             f"--depth {y1 - y0:.4f} --location 0 {(y0 + y1) / 2:.4f} 0 --rotation -90 0 0")
    L.append("apply --rotation")
L.append(f"add mesh cone --name Stinger --vertices 6 --radius1 {r(0.318) * 0.9:.4f} --radius2 0 --depth 0.11 "
         f"--location 0 0.373 0 --rotation -90 0 0")
L.append("apply --rotation")
L += ["add mesh uv-sphere --name Head --segments 8 --rings 6 --radius 0.5 --location 0 -0.43 0.01",
      "scale 0.50 0.38 0.44", "apply --scale"]
for s, n in ((-1, "L"), (1, "R")):
    L.append(f"add mesh cylinder --name Eye{n} --vertices 8 --radius 0.065 --depth 0.06 --location {s * 0.115} -0.615 0.0 --rotation 90 0 0")
    L.append("apply --rotation")
    a, b = np.array([s * 0.06, -0.52, 0.18]), np.array([s * 0.2, -0.66, 0.33])
    d = b - a; ln = float(np.linalg.norm(d)); e = align_z(d)
    L.append(f"add mesh cube --name Stalk{n} --size 1 --location {(a[0] + b[0]) / 2:.4f} {(a[1] + b[1]) / 2:.4f} {(a[2] + b[2]) / 2:.4f}")
    L.append(f"scale 0.075 0.075 {ln + 0.04:.4f}")
    L.append("apply --scale")
    L.append(f"set rotation {e[0]:.2f} {e[1]:.2f} {e[2]:.2f}")
    L.append(f"add mesh ico-sphere --name Ball{n} --subdivisions 1 --radius 0.07 --location {b[0]:.4f} {b[1]:.4f} {b[2]:.4f}")
# wings: a hexagonal plate 0.3 wide, 0.64 long (local Y), its root end narrowed, then turned so its
# long axis runs from the root (0.10, -0.20, 0.20) up, out and back to the tip (0.40, 0.20, 0.60)
for s, n in ((-1, "L"), (1, "R")):
    root = np.array([s * 0.10, -0.20, 0.20]); tip = np.array([s * 0.44, 0.12, 0.74])
    d = tip - root; d /= np.linalg.norm(d)
    v = np.array([s * 1.0, 1.0, 1.0]); nn = v - v.dot(d) * d; nn /= np.linalg.norm(nn)
    w = np.cross(d, nn); e = euler_from(np.stack([w, d, nn], 1))
    c = (root + tip) / 2
    L += [f"add mesh cylinder --name Wing{n} --vertices 6 --radius 0.5 --depth 0.045 --location 0 0 0 --rotation 0 0 30",
          "apply --rotation", "scale 0.50 0.64 1", "apply --scale", "mode edit",
          "select vert where \"pos.y < -0.1\"", "scale 0.5 1 1", "mode object",
          f"set rotation {e[0]:.2f} {e[1]:.2f} {e[2]:.2f}",
          f"set location {c[0]:.4f} {c[1]:.4f} {c[2]:.4f}"]
L += ["inspect stats"]
open("p1_blockout.txt", "w").write("\n".join(L) + "\n")
print("wrote p1_blockout.txt")
