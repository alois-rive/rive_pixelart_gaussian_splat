# Writes p1_blockout.txt for the knight from the spec's numbers (knight.spec.md, 400 px per metre
# off the FRONT panel): boxes, cylinders and a dome, the sword turned along its measured line
# (hedra's extrinsic XYZ, R = Rz Ry Rx). Run from models/knight: /usr/bin/python3 make_knight.py
import math
import numpy as np

def euler_from(M):
    ry = -math.asin(max(-1, min(1, M[2, 0])))
    rx = math.atan2(M[2, 1], M[2, 2]); rz = math.atan2(M[1, 0], M[0, 0])
    return [math.degrees(a) for a in (rx, ry, rz)]

def align_z(d, side=(1.0, 0, 0)):
    d = np.asarray(d, float); d /= np.linalg.norm(d)
    x = np.asarray(side, float); x = x - x.dot(d) * d; x /= np.linalg.norm(x)
    y = np.cross(d, x)
    return euler_from(np.stack([x, y, d], 1))

def box(name, size, loc):
    return [f"add mesh cube --name {name} --size 1 --location {loc[0]:.3f} {loc[1]:.3f} {loc[2]:.3f}",
            f"scale {size[0]:.3f} {size[1]:.3f} {size[2]:.3f}", "apply --scale"]

L = ["# Knight, phase 1: blockout of every named part at the spec's sizes (knight.spec.md). Up Z, facing",
     "# -Y, origin on the ground between the feet; its right hand (sword) at -X, its left (shield) at +X.",
     "# Generated by make_knight.py.", "new"]
for s, n in ((-1, "R"), (1, "L")):
    L += box(f"Boot{n}", (0.24, 0.32, 0.13), (s * 0.19, -0.04, 0.065))
    L += box(f"Leg{n}", (0.17, 0.19, 0.24), (s * 0.165, 0.0, 0.24))
    L += [f"add mesh ico-sphere --name Pauldron{n} --subdivisions 1 --radius 0.14 --location {s * 0.29:.3f} 0 0.6",
          "scale 1 1 0.85", "apply --scale"]
    L += box(f"Arm{n}", (0.14, 0.15, 0.24), (s * 0.31, 0.0, 0.46))
    L += box(f"Glove{n}", (0.15, 0.16, 0.13), (s * 0.32, -0.03, 0.31))
# torso: an 8-sided barrel, the tabard front and back
L += ["add mesh cylinder --name Torso --vertices 8 --radius 0.25 --depth 0.36 --location 0 0 0.5 --rotation 0 0 22.5",
      "apply --rotation", "scale 1 0.78 1", "apply --scale"]
L += box("TabardF", (0.4, 0.07, 0.44), (0, -0.19, 0.45))
L += box("TabardB", (0.4, 0.07, 0.44), (0, 0.19, 0.45))
# helmet: a 10-sided bucket with a dome on top, a dark visor slit, a crest plume front to back
L += ["add mesh cylinder --name Helm --vertices 10 --radius 0.28 --depth 0.3 --location 0 0 0.77 --rotation 0 0 18",
      "apply --rotation",
      "add mesh cone --name Dome --vertices 10 --radius1 0.28 --radius2 0.14 --depth 0.17 --location 0 0 1.005 --rotation 0 0 18",
      "apply --rotation"]
L += box("Slit", (0.36, 0.06, 0.065), (0, -0.265, 0.81))
L += box("Plume", (0.11, 0.42, 0.16), (0, 0.0, 1.1))
# sword in the right hand, pointing down, forward and out to the tip
a, b = np.array([-0.33, -0.06, 0.3]), np.array([-0.47, -0.40, 0.02])
d = b - a; ln = float(np.linalg.norm(d)); e = align_z(d)
c = (a + b) / 2
L += box("Blade", (0.09, 0.06, ln), (0, 0, 0)) + [f"set rotation {e[0]:.2f} {e[1]:.2f} {e[2]:.2f}",
     f"set location {c[0]:.3f} {c[1]:.3f} {c[2]:.3f}"]
g = a + (d / ln) * 0.03
L += box("Guard", (0.22, 0.07, 0.06), (0, 0, 0)) + [f"set rotation {e[0]:.2f} {e[1]:.2f} {e[2]:.2f}",
     f"set location {g[0]:.3f} {g[1]:.3f} {g[2]:.3f}"]
# shield on the left arm: a 10-sided disc facing out (+X), turned 30 degrees towards the front
L += ["add mesh cylinder --name Shield --vertices 10 --radius 0.22 --depth 0.06 --location 0 0 0 --rotation 0 90 0",
      "apply --rotation", "set rotation 0 0 -30", "set location 0.42 -0.02 0.38"]
L += ["inspect stats"]
open("p1_blockout.txt", "w").write("\n".join(L) + "\n")
print("wrote p1_blockout.txt")
