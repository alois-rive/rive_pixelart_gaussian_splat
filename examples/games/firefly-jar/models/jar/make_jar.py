#!/usr/bin/env python3
"""Writes the jar's hedra command files: p1_blockout.txt (one primitive per named part at the spec's
sizes) and p2_form.txt (materials, joins, flat shading, export). Up Z, facing -Y (the label side),
origin on the ground under the centre. 568 px per metre in the sheet's front panel.
Run from this folder: python3 make_jar.py"""
import math

L = []
def c(s): L.append(s)

def seg(name, a, b, r, verts=6):
    d = [b[i] - a[i] for i in range(3)]
    n = math.sqrt(sum(x * x for x in d))
    dx, dy, dz = (x / n for x in d)
    phi = math.degrees(math.acos(max(-1, min(1, dz))))
    psi = math.degrees(math.atan2(dx, -dy))
    m = [(a[i] + b[i]) / 2 for i in range(3)]
    c(f"add mesh cylinder --name {name} --vertices {verts} --radius {r} --depth {n + r:.3f} "
      f"--location {m[0]:.3f} {m[1]:.3f} {m[2]:.3f} --rotation {phi:.2f} 0 {psi:.2f}")

R8 = 0.25 / math.cos(math.radians(22.5))   # an octagon whose flat faces are 0.25 m from the axis
c("# Firefly jar, phase 1: blockout (jar.spec.md). Generated by make_jar.py. Up Z, facing -Y.")
c("new")
c(f"add mesh cone --name Foot --vertices 8 --radius1 {R8 - 0.03:.3f} --radius2 {R8:.3f} --depth 0.04 --location 0 0 0.02 --rotation 0 0 22.5")
c(f"add mesh cylinder --name Body --vertices 8 --radius {R8:.3f} --depth 0.38 --location 0 0 0.23 --rotation 0 0 22.5")
c(f"add mesh cone --name Shoulder --vertices 8 --radius1 {R8:.3f} --radius2 0.19 --depth 0.1 --location 0 0 0.47 --rotation 0 0 22.5")
c("add mesh cylinder --name Neck --vertices 8 --radius 0.19 --depth 0.08 --location 0 0 0.55 --rotation 0 0 22.5")
c("add mesh cylinder --name Band --vertices 8 --radius 0.215 --depth 0.035 --location 0 0 0.555 --rotation 0 0 22.5")
c("add mesh cone --name Cap --vertices 8 --radius1 0.235 --radius2 0.16 --depth 0.08 --location 0 0 0.61 --rotation 0 0 22.5")
# the cloth's four points hang over the shoulders: front, back and both sides
for k, (x, y) in enumerate(((0, -1), (0, 1), (-1, 0), (1, 0))):
    r = 0.205
    c(f"add mesh cone --name Point{k} --vertices 4 --radius1 0.09 --radius2 0 --depth 0.14 "
      f"--location {x * r:.3f} {y * r:.3f} 0.5 --rotation 180 0 {45 if x == 0 else 0}")
    c("scale 1 0.45 1" if x == 0 else "scale 0.45 1 1")
    c("apply --scale")
# the wire handle: an arch over the cap from one side of the neck to the other, 0.06 m thick
pts = []
for k in range(8):
    t = math.pi * k / 7
    pts.append((-0.228 * math.cos(t), 0.0, 0.56 + 0.26 * math.sin(t)))
for k in range(7):
    seg(f"Wire{k}", pts[k], pts[k + 1], 0.03)
c("add mesh cube --name Label --size 1 --location 0 -0.255 0.22")
c("scale 0.2 0.04 0.2")
c("apply --scale")
c("select all")
c("inspect stats")
open("p1_blockout.txt", "w").write("\n".join(L) + "\n")

P = ["# Firefly jar, phase 2: materials in exact retrocal-8 colours (sRGB 0..1), joined, flat, export.",
     "# Glass #6eb8a8 (glass ramp step 1), Cloth #c6505a (cloth step 2), String #fcffc0 (glass step 2),",
     "# Wire #774448 (wood step 1), Label #ee9c5d (wood step 2).",
     "material new Glass --base-color 0.431 0.722 0.659 --no-slot",
     "material new Cloth --base-color 0.776 0.314 0.353 --no-slot",
     "material new String --base-color 0.988 1.0 0.753 --no-slot",
     "material new Wire --base-color 0.467 0.267 0.282 --no-slot",
     "material new Label --base-color 0.933 0.612 0.365 --no-slot",
     "select Foot Body Shoulder Neck", "material assign Glass",
     "select Cap Point0 Point1 Point2 Point3", "material assign Cloth",
     "select Band", "material assign String",
     "select " + " ".join(f"Wire{k}" for k in range(7)), "material assign Wire",
     "select Label", "material assign Label",
     "select all", "active Body", "join", "rename Body Jar",
     "shade flat", "inspect stats", "export jar.glb"]
open("p2_form.txt", "w").write("\n".join(P) + "\n")
print("wrote p1_blockout.txt p2_form.txt")
