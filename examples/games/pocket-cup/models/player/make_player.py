#!/usr/bin/env python3
"""Writes the footballer's hedra command files from one table of parts (metres, measured off
art/player/sheet.v1.png at 274 px a metre; up Z, facing -Y, origin on the ground under the body).

  p1_blockout.txt   one box per named part (the gated hero, whole)
  p2_form.txt       arms tilted out, materials, join, export player.glb (the gated hero)
  body.txt          the scene's body: the hero without its legs -> player_body.glb (origin on the ground)
  leg.txt           one leg (knee, sock, boot) with its origin at the hip -> player_leg.glb

The scene moves the body and the two legs as three game bones (run cycle, kick, dive)."""
import os

HIP = 0.60          # the legs' pivot (inside the shorts)
# name: (size x, y, z), centre (x, y, z), material
BODY = [
    ("Torso",  (0.41, 0.26, 0.44), (0, 0, 0.93), "Shirt"),
    ("Collar", (0.30, 0.22, 0.05), (0, -0.005, 1.165), "Trim"),
    ("Shorts", (0.44, 0.26, 0.19), (0, 0, 0.615), "Shorts"),
    ("Head",   (0.36, 0.32, 0.29), (0, -0.02, 1.325), "Skin"),
    ("HairTop", (0.39, 0.38, 0.13), (0, 0.0, 1.535), "Hair"),
    ("HairBack", (0.39, 0.09, 0.28), (0, 0.145, 1.33), "Hair"),
    ("EyeR",   (0.05, 0.03, 0.05), (-0.085, -0.19, 1.40), "Eye"),
    ("EyeL",   (0.05, 0.03, 0.05), (0.085, -0.19, 1.40), "Eye"),
]
# arms: sleeve, arm, hand per side (x sign); tilted out 12 degrees about the shoulder afterwards
def arm(side):
    s = 1 if side == "L" else -1
    return [
        ("Sleeve" + side, (0.17, 0.19, 0.20), (s * 0.29, 0, 1.05), "Shirt"),
        ("Arm" + side,    (0.13, 0.15, 0.36), (s * 0.29, 0, 0.80), "Skin"),
        ("Hand" + side,   (0.14, 0.16, 0.11), (s * 0.29, 0, 0.665), "Skin"),
    ]
BAND = ("Band", (0.175, 0.195, 0.07), (0.29, 0, 0.99), "Band")   # the captain's armband, LEFT arm (+X)
LEG = [  # one leg at x = 0 (the scene places two), from the ground up to the hip
    ("Boot", (0.20, 0.30, 0.13), (0, -0.045, 0.065), "Boot"),
    ("Sock", (0.16, 0.19, 0.20), (0, 0, 0.23), "Sock"),
    ("Knee", (0.16, 0.19, HIP - 0.33 + 0.02), (0, 0, (0.33 + HIP + 0.02) / 2), "Skin"),
]
LEGX = 0.117
# the splat fit (p3): discs reach about a radius past every face, so the splat figure comes out
# fatter than the mesh, most in the narrow side view; the scene's parts take the same fit
FIT = (0.96, 0.84, 1.0)
FIT_LINE = "scale %.2f %.2f %.2f" % FIT
COLORS = {  # Sheltzy32, the ramp steps the sheet paints (sRGB 0..1)
    "Shirt": "0.925 0.380 0.290", "Sock": "0.925 0.380 0.290", "Trim": "0.800 0.886 0.882",
    "Shorts": "0.800 0.886 0.882", "Skin": "1.000 0.643 0.408", "Hair": "0.408 0.235 0.204",
    "Boot": "0.220 0.000 0.173", "Eye": "0.133 0.165 0.361", "Band": "1.000 0.855 0.439",
}

def box(name, size, c):
    return [f"add mesh cube --name {name} --size 1 --location {c[0]:.3f} {c[1]:.3f} {c[2]:.3f}",
            f"scale {size[0]:.3f} {size[1]:.3f} {size[2]:.3f}", "apply --scale"]

def tilt_arms(lines, parts):
    # each arm turns 12 degrees outwards about its shoulder (y axis), as in the front view
    for side, s in (("L", 1), ("R", -1)):
        names = [p[0] for p in parts if p[0].endswith(side) and p[0][:-1] in ("Sleeve", "Arm", "Hand")]
        if side == "L" and any(p[0] == "Band" for p in parts):
            names.append("Band")
        lines += ["select " + " ".join(names), f"cursor set {s * 0.26:.3f} 0 1.13",
                  "origin set --to cursor"]
        for n in names:
            lines += [f"select {n}", f"active {n}", f"set rotation 0 {-s * 12} 0", "apply --rotation"]

def materials(lines, used):
    for m in used:
        lines.append(f"material new {m} --base-color {COLORS[m]} --no-slot")

def assign(lines, parts):
    by = {}
    for p in parts:
        by.setdefault(p[3], []).append(p[0])
    for m, names in by.items():
        lines += ["select " + " ".join(names), f"material assign {m}"]

def write(path, lines):
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")

def legs_whole():
    out = []
    for side, s in (("L", 1), ("R", -1)):
        for n, size, c, m in LEG:
            out.append((n + side, size, (s * LEGX, c[1], c[2]), m))
    return out

here = os.path.dirname(os.path.abspath(__file__))
hero = BODY + arm("L") + arm("R") + [BAND] + legs_whole()

p1 = ["# The footballer, phase 1: blockout, one box per named part at the spec's sizes (metres,",
      "# measured off the sheet at 274 px a metre). Up Z, facing -Y, origin on the ground under the body.",
      "# Generated by make_player.py.", "new"]
for n, size, c, m in hero:
    p1 += box(n, size, c)
write(os.path.join(here, "p1_blockout.txt"), p1)

p2 = ["# The footballer, phase 2: the arms tilted out 12 degrees about the shoulders, Sheltzy32",
      "# materials (sRGB of the ramp steps), one object, flat shading, export. Generated by make_player.py."]
tilt_arms(p2, hero)
materials(p2, ["Shirt", "Sock", "Trim", "Shorts", "Skin", "Hair", "Boot", "Eye", "Band"])
assign(p2, hero)
p2 += ["select all", "active Torso", "join", "rename Torso Player", "shade flat", "export player.glb"]
write(os.path.join(here, "p2_form.txt"), p2)

write(os.path.join(here, "p3_splat_fit.txt"), [
    "# The footballer, phase 3: the splat fit. The gated form (p2) unchanged; only slimmed for the",
    "# splats (x %.2f, depth %.2f) so the baked figure keeps the sheet's proportions. Generated by" % FIT[:2],
    "# make_player.py; run with --no-save --to player_fit.rmdl.",
    "select Player", "active Player", FIT_LINE, "apply --scale", "export player_fit.glb"])

# the scene's parts: the body (no legs) and one leg pivoting at the hip
body = BODY + arm("L") + arm("R") + [BAND]
b = ["# The scene's body: the gated footballer without legs (they are their own game bones).",
     "# Generated by make_player.py.", "new"]
for n, size, c, m in body:
    b += box(n, size, c)
tilt_arms(b, body)
materials(b, ["Shirt", "Trim", "Shorts", "Skin", "Hair", "Eye", "Band"])
assign(b, body)
b += ["select all", "active Torso", "join", "rename Torso Body", "cursor set 0 0 0", "origin set --to cursor",
      FIT_LINE, "apply --scale", "shade flat", "export player_body.glb"]
write(os.path.join(here, "body.txt"), b)

l = ["# One leg of the footballer (knee, sock, boot), its origin at the hip (z %.2f): the scene swings" % HIP,
     "# it about that point. Generated by make_player.py.", "new"]
for n, size, c, m in LEG:
    l += box(n, size, c)
materials(l, ["Skin", "Sock", "Boot"])
assign(l, LEG)
l += ["select all", "active Knee", "join", "rename Knee Leg", f"cursor set 0 0 {HIP}", "origin set --to cursor",
      "set location 0 0 0",
      FIT_LINE, "apply --scale", "shade flat", "export player_leg.glb"]
write(os.path.join(here, "leg.txt"), l)
print("wrote p1_blockout.txt p2_form.txt body.txt leg.txt")
