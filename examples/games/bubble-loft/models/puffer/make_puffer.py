# Writes the orb puffer's hedra command files from its spec (puffer.spec.md): p1_blockout.txt (one
# primitive per part at the spec's sizes, materials in the final Sunset 8 colours), p2_form.txt (the
# cup's hollow, hidden caps deleted, flat shading, the export puffer.glb) and p3_splat_fit.txt (run
# with --no-save after p2: the splat fit and the three GLBs the scene moves, each with its origin at its pivot).
# Run from models/puffer: /usr/bin/python3 make_puffer.py
# hedra: up Z, front -Y; origin on the ground under the barrel. The object's own right is -X.
import math

HEX = {"Iron": "464678", "Copper": "ffa936", "Brass": "ffc247", "Petal": "e67595", "Rubber": "9a6390"}
def rgb(h):
    return " ".join(f"{int(h[i:i + 2], 16) / 255:.3f}" for i in (0, 2, 4))
def octo(name, r_flat, z0, z1, m, x=0.0):
    """an upright octagonal prism, flats on the axes; r_flat = half the width across the flats"""
    R = r_flat / math.cos(math.radians(22.5))
    return [f"add mesh cylinder --name {name} --vertices 8 --radius {R:.4f} --depth {z1 - z0:.4f} "
            f"--location {x:.4f} 0 {(z0 + z1) / 2:.4f} --rotation 0 0 22.5", f"material assign {m}"]
def cone(name, rf0, rf1, z0, z1, m):
    c = math.cos(math.radians(22.5))
    return [f"add mesh cone --name {name} --vertices 8 --radius1 {rf0 / c:.4f} --radius2 {rf1 / c:.4f} --depth {z1 - z0:.4f} "
            f"--location 0 0 {(z0 + z1) / 2:.4f} --rotation 0 0 22.5", f"material assign {m}"]

# the spec's numbers (metres)
PLINTH = (0.69, 0.0, 0.33)
DRUM = (0.555, 0.33, 1.12)
LID = (0.555, 0.175, 1.12, 1.33)
BARREL = (0.175, 1.33, 1.97)
MOUTH = (0.175, 0.40, 1.97, 2.22)
PETAL_TOP = 2.42
BULB = (-1.08, 0.79, 0.40)        # centre x, centre z, radius
CUP = (1.07, 0.72, 0.98, 0.29)    # centre x, bottom z, top z, half width across flats
ARM_Z = 0.82

p1 = ["# Orb puffer, phase 1: blockout at the spec's sizes (generated by make_puffer.py).", "new"]
p1 += [f"material new {k} --base-color {rgb(v)} --no-slot" for k, v in HEX.items()]
p1 += octo("Plinth", PLINTH[0], PLINTH[1], PLINTH[2], "Iron")
p1 += octo("Drum", DRUM[0], DRUM[1], DRUM[2], "Copper")
p1 += cone("Lid", LID[0], LID[1], LID[2], LID[3], "Brass")
p1 += octo("Barrel", BARREL[0], BARREL[1], BARREL[2], "Brass")
p1 += cone("Mouth", MOUTH[0], MOUTH[1], MOUTH[2], MOUTH[3], "Petal")
# four petal tips round the rim (front, right, back, left), leaning out
petals = []
for i, a in enumerate((0, 90, 180, 270)):
    ca, sa = math.cos(math.radians(a)), math.sin(math.radians(a))
    rr = 0.33
    x, y = rr * ca, rr * sa
    n = f"Tip{i}"
    petals.append(n)
    h = PETAL_TOP - MOUTH[3] + 0.08
    p1 += [f"add mesh cone --name {n} --vertices 4 --radius1 0.30 --radius2 0 --depth {h:.3f} --location 0 0 {h / 2:.3f}",
           "scale 0.5 1 1", "apply --scale",
           "set rotation 0 16 0", "apply --rotation",           # lean out along +X
           f"set rotation 0 0 {a}", "apply --rotation",
           f"translate {x:.4f} {y:.4f} {MOUTH[3] - 0.08:.4f}", "apply --location", "material assign Petal"]
p1 += ["select Mouth " + " ".join(petals), "active Mouth", "join"]
# the squeeze bulb on the object's own right (-X) and its hose
p1 += [f"add mesh ico-sphere --name Bulb --subdivisions 2 --radius {BULB[2]:.3f} --location {BULB[0]:.3f} 0 {BULB[1]:.3f}",
       "material assign Rubber",
       f"add mesh cylinder --name Hose --vertices 6 --radius 0.075 --depth 0.24 --location -0.62 0 {BULB[1]:.3f} --rotation 0 90 0",
       "material assign Rubber"]
# the cup on the object's own left (+X) and its arm
p1 += octo("Cup", CUP[3], CUP[1], CUP[2], "Brass", CUP[0])
p1 += [f"add mesh cube --name Arm --size 1 --location 0.66 0 {ARM_Z:.3f}", "scale 0.26 0.11 0.11", "apply --scale",
       "material assign Brass"]
open("p1_blockout.txt", "w").write("\n".join(p1) + "\n")

p2 = ["# Orb puffer, phase 2: form (the cup hollowed, hidden caps deleted), flat shading, export.",
      # the cup: inset its top and sink it into a bowl
      "select Cup", "active Cup", "mode edit", 'select face where "normal.z > 0.9"', "inset 0.06",
      "extrude 0 0 -0.26", "delete only-faces",
      'select face where "normal.z < -0.9"', "delete only-faces", "mode object",
      # caps nobody sees: the drum's bottom (on the plinth), the barrel's ends, the lid's bottom
      "select Drum", "active Drum", "mode edit", 'select face where "normal.z < -0.9"', "delete only-faces", "mode object",
      "select Lid", "active Lid", "mode edit", 'select face where "normal.z < -0.9"', "delete only-faces", "mode object",
      "select Barrel", "active Barrel", "mode edit", 'select face where "abs(normal.z) > 0.9"', "delete only-faces", "mode object",
      "select Plinth", "active Plinth", "mode edit", 'select face where "normal.z < -0.9"', "delete only-faces", "mode object",
      "select all", "shade flat", "export puffer.glb"]
open("p2_form.txt", "w").write("\n".join(p2) + "\n")

# phase 3, for the splats only (modeling.md, "When the mesh gate and the splat gate disagree"): every
# disc reaches a radius past its face, so the top view comes out ~10 % too deep (aspect drift 0.105).
# Shrink the depth (Y) of the plinth, the drum and the lid; the gated p2 stays as it is. Run after p2
# with --no-save: it exports puffer_splat.glb (the lookdev bake's) and the parts the scene moves,
# each re-centred on its pivot:
#   puffer_base.glb   plinth, drum, lid, hose, arm, cup (static, origin on the ground)
#   puffer_barrel.glb barrel + mouth: origin at the lid's top (it swings there to aim)
#   puffer_bulb.glb   the bulb: origin at its inner side, where it squashes towards the drum
p3 = ["# Orb puffer, phase 3 (splat fit + the scene's parts, generated by make_puffer.py): run after p2 with --no-save.",
      "select Plinth Drum Lid", "scale 1 0.9 1", "apply --scale",
      "select all", "export puffer_splat.glb",
      "select Plinth Drum Lid Hose Arm Cup", "export puffer_base.glb --selection",
      "select Barrel Mouth", f"translate 0 0 {-BARREL[1]:.3f}", "export puffer_barrel.glb --selection",
      f"translate 0 0 {BARREL[1]:.3f}",
      "select Bulb", f"translate {-(BULB[0] + BULB[2]):.3f} 0 {-BULB[1]:.3f}", "export puffer_bulb.glb --selection"]
open("p3_splat_fit.txt", "w").write("\n".join(p3) + "\n")
