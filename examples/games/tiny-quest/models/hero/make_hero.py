# Writes the hero's hedra command files from the spec (hero.spec.md): p1_blockout.txt (one primitive per
# part at the spec's sizes, materials in the final MarshMellow32 colours) and p2_form.txt (the shield's
# wooden face inset inside its gold rim, the boss, flat shading, the export).
# Run from models/hero: /usr/bin/python3 make_hero.py. hedra: up Z, front -Y; origin on the ground under
# the body's centre (the game turns and hops the hero about it).
def rgb(h):
    return " ".join(f"{int(h[i:i + 2], 16) / 255:.4f}" for i in (1, 3, 5))

C = {"Straw": "#e2b55f", "Band": "#8c504d", "Skin": "#b87a66", "Hair": "#3c3a3f", "Tunic": "#2d80a6",
     "Belt": "#593234", "Legs": "#4b5053", "Blade": "#b2b2b2", "Gold": "#e2b55f", "Shield": "#a1623b",
     "Cape": "#8c504d"}

def box(name, x0, x1, y0, y1, z0, z1, mat):
    return [f"add mesh cube --name {name} --size 1 --location {(x0 + x1) / 2:.4f} {(y0 + y1) / 2:.4f} {(z0 + z1) / 2:.4f}",
            f"scale {x1 - x0:.4f} {y1 - y0:.4f} {z1 - z0:.4f}", "apply --scale", f"material assign {mat}"]

p1 = ["# Hero (the adventurer), phase 1: blockout at the spec's sizes (generated by make_hero.py).", "new"]
p1 += [f"material new {k} --base-color {rgb(v)} --no-slot" for k, v in C.items()]
# boots and legs
for side, sx in (("R", -1), ("L", 1)):
    p1 += box(f"Boot{side}", sx * 0.012, sx * 0.168, -0.135, 0.07, 0.0, 0.095, "Belt") if sx > 0 else \
          box(f"Boot{side}", -0.168, -0.012, -0.135, 0.07, 0.0, 0.095, "Belt")
    p1 += box(f"Leg{side}", (0.03 if sx > 0 else -0.14), (0.14 if sx > 0 else -0.03), -0.06, 0.06, 0.09, 0.18, "Legs")
# tunic: a square frustum 0.36 x 0.30 at the hem to 0.26 x 0.24 at the shoulders
p1 += ["add mesh cone --name Tunic --vertices 4 --radius1 0.2546 --radius2 0.1838 --depth 0.30 --location 0 0 0.32 --rotation 0 0 45",
       "apply --rotation", "scale 1 0.86 1", "apply --scale", "material assign Tunic"]
p1 += ["add mesh cone --name Belt --vertices 4 --radius1 0.2420 --radius2 0.2340 --depth 0.045 --location 0 0 0.255 --rotation 0 0 45",
       "apply --rotation", "scale 1 0.87 1", "apply --scale", "material assign Belt"]
# collar and the cape down the back
p1 += box("Collar", -0.16, 0.16, -0.14, 0.15, 0.43, 0.49, "Cape")
p1 += box("Cape", -0.15, 0.15, 0.115, 0.165, 0.19, 0.47, "Cape")
p1 += ["select Cape", "active Cape", "mode edit", 'select vert where "pos.z < 0.0"', "translate 0 0.10 0", "scale 1.12 1 1", "mode object"]
# arms and hands
p1 += box("ArmR", -0.225, -0.135, -0.05, 0.05, 0.30, 0.46, "Tunic")
p1 += box("ArmL", 0.135, 0.225, -0.05, 0.05, 0.30, 0.46, "Tunic")
p1 += box("HandR", -0.285, -0.185, -0.08, 0.02, 0.22, 0.31, "Skin")
p1 += box("HandL", 0.185, 0.275, -0.07, 0.03, 0.23, 0.31, "Skin")
# head, hair (fringe band under the brim, covering the back of the head), eyes
p1 += box("Head", -0.185, 0.185, -0.17, 0.18, 0.47, 0.71, "Skin")
p1 += box("Hair", -0.205, 0.205, -0.19, 0.205, 0.69, 0.765, "Hair")
p1 += box("HairBack", -0.195, 0.195, 0.15, 0.205, 0.55, 0.70, "Hair")
p1 += box("EyeR", -0.11, -0.055, -0.19, -0.165, 0.58, 0.64, "Hair")
p1 += box("EyeL", 0.055, 0.11, -0.19, -0.165, 0.58, 0.64, "Hair")
# hat: a wide octagonal brim, a low crown with a red band
p1 += ["add mesh cylinder --name Brim --vertices 8 --radius 0.395 --depth 0.05 --location 0 0 0.785 --rotation 0 0 22.5",
       "apply --rotation", "material assign Straw",
       "add mesh cone --name Crown --vertices 8 --radius1 0.19 --radius2 0.168 --depth 0.15 --location 0 0 0.875 --rotation 0 0 22.5",
       "apply --rotation", "material assign Straw",
       "add mesh cylinder --name HatBand --vertices 8 --radius 0.198 --depth 0.045 --location 0 0 0.84 --rotation 0 0 22.5",
       "apply --rotation", "material assign Band"]
# sword in the right hand (image left in the front view): grip, guard, blade, tip
p1 += box("Grip", -0.255, -0.215, -0.05, -0.01, 0.30, 0.38, "Belt")
p1 += box("Guard", -0.315, -0.155, -0.055, -0.005, 0.375, 0.415, "Gold")
p1 += box("BladeR", -0.28, -0.19, -0.047, -0.013, 0.41, 0.63, "Blade")
p1 += ["add mesh cone --name Tip --vertices 4 --radius1 0.0636 --radius2 0.0 --depth 0.07 --location -0.235 -0.03 0.665 --rotation 0 0 45",
       "apply --rotation", "scale 1 0.38 1", "apply --scale", "material assign Blade"]
# round shield on the left forearm, facing out to the left and a little forwards
p1 += ["add mesh cylinder --name Shield --vertices 8 --radius 0.165 --depth 0.05 --location 0.285 -0.12 0.33 --rotation 0 90 -40",
       "apply --rotation", "material assign Gold",
       "add mesh cylinder --name Boss --vertices 8 --radius 0.05 --depth 0.05 --location 0.312 -0.143 0.33 --rotation 0 90 -40",
       "apply --rotation", "material assign Gold"]
open("p1_blockout.txt", "w").write("\n".join(p1) + "\n")

# phase 2: the shield's outward face inset (wood inside a gold rim), flat shading, export
p2 = ["# Hero, phase 2: the shield's wooden face inside its gold rim, flat shading, export (make_hero.py).",
      "select Shield", "active Shield", "mode edit",
      'select face where "normal.x > 0.7 && normal.y < -0.5"', "inset 0.04", "material assign Shield", "mode object",
      "select all", "shade flat", "export hero.glb"]
open("p2_form.txt", "w").write("\n".join(p2) + "\n")
