# Writes the course's hedra command files from course.py, and the course data block of
# ../../scene/game.as (between "// BEGIN COURSE" and "// END COURSE"):
#   greens1-3.txt the felt of the nine greens, a row of holes a file (height fields displaced by `attribute set position`,
#                mowing stripes, tee pads, holes cut for the cups, hazards left open) -> greens1-3.glb
#   borders.txt  the wooden borders, stepped with the felt under them -> borders.glb
#   cups.txt     the nine cups (dark liners) -> cups.glb
#   water.txt    the brook and the crown's pond (ripple-striped water, the far banks), the bridge
#                deck and its side, the cloud gap's pit -> water.glb
#   island.txt   the cloud ground round the greens and the island's lumpy cloud skirt -> island.glb
# Run from models/course: /usr/bin/python3 make_course.py
# hedra is Z up with the front at -Y: world (x, y, z) = hedra (x, -z, y).
