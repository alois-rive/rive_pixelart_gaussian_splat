def col(n):
    h = HEX[n]
    r, g, b = (int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))
    return f"--base-color {r:.4f} {g:.4f} {b:.4f}"


X, Z = "pos.x", "(0 - pos.y)"


def fexpr(kind, a, b, u):
    if kind == C.ONE:
        return "1"
    if kind == C.SMOOTH:
        t = f"clamp(({u} - ({a})) / ({b - a}), 0, 1)"
        return f"({t} * {t} * (3 - 2 * {t}))"
    if kind == C.LIN:
        return f"clamp(({u} - ({a})) / ({b - a}), 0, 1)"
    if kind == C.KICK:
        t = f"(({u} - ({a})) / ({b - a}))"
        return f"({t} * ({t} >= 0) * ({t} <= 1.0001))"
    if kind == C.ARCH:
        t = f"(({u} - ({a})) / {b})"
        return f"max(0, 1 - {t} * {t})"
    if kind == C.BOX:
        return f"(({u} >= {a}) * ({u} <= {b}))"
    raise ValueError(kind)


def hexpr(w):
    parts = []
    for t in w["terms"]:
        if t[0] == C.BUMP:
            parts.append(f"{t[1]} * pow(2.718282, 0 - (({X} - ({t[2]})) * ({X} - ({t[2]})) + ({Z} - ({t[3]})) * ({Z} - ({t[3]})))"
                         f" / {2 * t[4] * t[4]:.4f})")
        else:
            parts.append(f"{t[1]} * {fexpr(t[2], t[3], t[4], X)} * {fexpr(t[5], t[6], t[7], Z)}")
    return " + ".join(parts) if parts else "0"


def inside(r, m=0.0):
    """hedra condition: the element's position inside world rect r (shrunk by m)."""
    return f"({X} > {r[0] + m:.3f} && {X} < {r[2] - m:.3f} && {Z} > {r[1] + m:.3f} && {Z} < {r[3] - m:.3f})"


def bbox(rects):
    return (min(r[0] for r in rects), min(r[1] for r in rects), max(r[2] for r in rects), max(r[3] for r in rects))


def grid(name, r, cell):
    """A grid over world rect r, cells about `cell`, transforms applied (local = world)."""
    W, D = r[2] - r[0], r[3] - r[1]
    nx, nz = max(1, round(W / cell)), max(1, round(D / cell))
    cx, cz = (r[0] + r[2]) / 2, (r[1] + r[3]) / 2
    return (f"add mesh grid --name {name} --size 1 --x-subdivisions {nx} --y-subdivisions {nz} --location 0 0 0\n"
            f"scale {W:.4f} {D:.4f} 1\napply --scale\ntranslate {cx:.4f} {-cz:.4f} 0\napply --location\n")


def strip(name, x0, x1, z, n, bottom, top_expr):
    """A vertical strip facing +z (the camera) along world z from x0 to x1, from y = bottom up to
    y = top_expr (a hedra expression in pos.x and the strip's own z = world z)."""
    out = (f"add mesh grid --name {name} --size 1 --x-subdivisions {n} --y-subdivisions 1 --location 0 0 0\n"
           f"set rotation 90 0 0\napply --rotation\nscale {x1 - x0:.4f} 1 1\napply --scale\n"
           f"translate {(x0 + x1) / 2:.4f} {-z:.4f} 0.5\napply --location\n")
    out += f'attribute set position "vec(pos.x, pos.y, {bottom} + pos.z * ({top_expr} - ({bottom})))"\n'
    return out


def main():
    W = C.world_holes()
    files = {}

    # ---------------------------------------------------------------- greens (three files, a row
    # of holes each: one hedra run over all nine takes long enough to be stopped)
    for part in range(3):
        g = [f"# The felt of holes {3 * part + 1}-{3 * part + 3}, generated by make_course.py from course.py (do not edit).",
             "new",
             f"material new Felt {col('felt')} --no-slot",
             f"material new Stripe {col('stripe')} --no-slot",
             f"material new Tee {col('tee')} --no-slot"]
        names = []
        for w in W[3 * part:3 * part + 3]:
            n = f"Green{w['index'] + 1}"
            names.append(n)
            g.append(f"# hole {w['index'] + 1}: {w['name']}")
            g.append(grid(n, bbox(w["felt"]), 0.1).rstrip())
            g.append("material assign Felt")
            g.append(f'attribute set position "vec(pos.x, pos.y, {C.FELT} + {hexpr(w)})"')
            g.append("mode edit")
            keep = " || ".join(inside(r) for r in w["felt"])
            holes = [inside(r) for r in w["water"] + w["gap"]]
            cx, cz = w["cup"]
            holes.append(f"(({X} - {cx}) * ({X} - {cx}) + ({Z} - {cz}) * ({Z} - {cz}) < {(C.CUP_R - 0.03) ** 2:.4f})")
            g.append(f'select face where "!({keep}) || {" || ".join(holes)}"')
            g.append("delete only-faces")
            g.append(f'select face where "(floor(({X} + 100) / 0.7) % 2) == 0"')
            g.append("material assign Stripe")
            tx, tz = w["tee"]
            g.append(f'select face where "abs({X} - {tx}) < 0.4 && abs({Z} - {tz}) < 0.4"')
            g.append("material assign Tee")
            g.append("mode object")
            g.append("shade flat")
        g.append(f"export greens{part + 1}.glb")
        files[f"greens{part + 1}"] = "\n".join(g) + "\n"

    # ---------------------------------------------------------------- borders
    b = ["# The wooden borders: boxes along every wall, at most 0.8 m long, their tops stepped with the",
         "# felt beside them. Generated by make_course.py from course.py (do not edit).",
         "new",
         f"material new Wood {col('wood')} --no-slot",
         f"material new WoodTop {col('woodtop')} --no-slot"]
    k = 0
    for w in W:
        for line in w["walls"]:
            for (a, c) in zip(line[:-1], line[1:]):
                L = math.hypot(c[0] - a[0], c[1] - a[1])
                n = max(1, math.ceil(L / 0.8))
                ux, uz = (c[0] - a[0]) / L, (c[1] - a[1]) / L
                for i in range(n):
                    s0, s1 = L * i / n, L * (i + 1) / n
                    hs = []
                    for f in (0.0, 0.25, 0.5, 0.75, 1.0):
                        s = s0 + (s1 - s0) * f
                        px, pz = a[0] + ux * s, a[1] + uz * s
                        for o in (-0.18, 0.18):
                            qx, qz = px - uz * o, pz + ux * o
                            if any(C.in_rect(r, qx, qz) for r in w["felt"]):
                                hs.append(C.height(w, qx, qz))
                    top = C.FELT + (max(hs) if hs else 0.0) + C.WALL_UP
                    mx, mz = a[0] + ux * (s0 + s1) / 2, a[1] + uz * (s0 + s1) / 2
                    over = any(C.in_rect(r, mx, mz, 0.15) for r in w["water"] + w["gap"])
                    bot = -0.35 if over else -0.02
                    ext = (C.WALL_HALF if i == 0 else 0.0) + (C.WALL_HALF if i == n - 1 else 0.0)
                    off = (C.WALL_HALF if i == n - 1 else 0.0) - (C.WALL_HALF if i == 0 else 0.0)
                    mx += ux * off / 2
                    mz += uz * off / 2
                    ang = math.degrees(math.atan2(-uz, ux))   # hedra: the box's x along the wall
                    b.append(f"add mesh cube --name B{k} --size 1 --location 0 0 0")
                    b.append(f"scale {s1 - s0 + ext:.4f} {2 * C.WALL_HALF:.4f} {top - bot:.4f}\napply --scale")
                    b.append(f"set rotation 0 0 {ang:.3f}\napply --rotation")
                    b.append(f"translate {mx:.4f} {-mz:.4f} {(top + bot) / 2:.4f}\napply --location")
                    k += 1
        for (x0, z0, x1, z1, hp) in w["plinths"]:
            top = C.FELT + hp
            b.append(f"add mesh cube --name B{k} --size 1 --location {(x0 + x1) / 2:.4f} {-(z0 + z1) / 2:.4f} {(top - 0.02) / 2:.4f}")
            b.append(f"scale {x1 - x0:.4f} {z1 - z0:.4f} {top + 0.02:.4f}\napply --scale\napply --location")
            k += 1
    b.append("select " + " ".join(f"B{i}" for i in range(k)))
    b.append("active B0\njoin\nrename B0 Borders\nmaterial assign Wood\nmode edit")
    b.append('select face where "normal.z > 0.9"\nmaterial assign WoodTop')
    # the camera never turns (yaw 0): faces looking down, north (hedra +y) or straight sideways are never seen
    b.append('select face where "normal.z < -0.9 || normal.y > 0.3 || abs(normal.x) > 0.9"\ndelete only-faces\nmode object\nshade flat\nexport borders.glb')
    files["borders"] = "\n".join(b) + "\n"

    # ---------------------------------------------------------------- cups
    c = ["# The nine cups: dark liners 0.26 m in radius and 0.3 m deep, open at the felt, facing inwards.",
         "# Generated by make_course.py from course.py (do not edit).",
         "new", f"material new Cup {col('pit')} --no-slot"]
    for w in W:
        cx, cz = w["cup"]
        top = C.FELT + C.height(w, cx, cz)
        c.append(f"add mesh cylinder --name Cup{w['index'] + 1} --vertices 12 --radius {C.CUP_R} --depth 0.3 "
                 f"--location {cx:.4f} {-cz:.4f} {top - 0.15 + 0.01:.4f}")
        c.append("apply --location\nmode edit\nselect face where \"normal.z > 0.9\"\ndelete only-faces\nselect all\n"
                 "normals flip\nmode object\nmaterial assign Cup")
    c.append("select " + " ".join(f"Cup{i + 1}" for i in range(9)) + "\nshade flat\nexport cups.glb")
    files["cups"] = "\n".join(c) + "\n"

    # ---------------------------------------------------------------- water, bridge, gap
    wa = ["# The brook (hole 3) and the crown's pond (hole 9): ripple-striped water below the felt and",
          "# their far banks; the bridge's arched deck and its near side; the cloud gap's pit (hole 5).",
          "# Generated by make_course.py from course.py (do not edit).",
          "new", f"material new Water {col('water')} --no-slot", f"material new Ripple {col('ripple')} --no-slot",
          f"material new Bank {col('bank')} --no-slot", f"material new Plank {col('plank')} --no-slot",
          f"material new Seam {col('seam')} --no-slot", f"material new Puff {col('puff')} --no-slot",
          f"material new Cloud {col('cloud')} --no-slot"]
    objs = []
    WY = C.FELT - 0.2
    for w in W:
        he = hexpr(w)
        for i, r in enumerate(w["water"]):
            n = f"Water{w['index'] + 1}_{i}"
            objs.append(n)
            wa.append(grid(n, r, 0.15).rstrip() + f"\ntranslate 0 0 {WY}\napply --location\nmaterial assign Water\nmode edit")
            wa.append(f'select face where "(floor(({Z} + 100) / 0.45) % 3) == 0 && (floor(({X} + 100) / 0.6 + floor(({Z} + 100) / 0.45) * 0.5) % 2) == 0"')
            wa.append("material assign Ripple\nmode object")
            bn = f"Bank{w['index'] + 1}_{i}"
            objs.append(bn)
            wa.append(strip(bn, r[0], r[2], r[1], max(2, round((r[2] - r[0]) / 0.25)), WY - 0.05, f"{C.FELT} + {he}").rstrip())
            wa.append("material assign Bank")
        if "bridge" in w:
            br = w["bridge"]
            n = f"Deck{w['index'] + 1}"
            objs.append(n)
            arch = f"{br[4]} * max(0, 1 - (({X} - ({(br[0] + br[2]) / 2})) / {(br[2] - br[0]) / 2}) * (({X} - ({(br[0] + br[2]) / 2})) / {(br[2] - br[0]) / 2}))"
            wa.append(grid(n, br, 0.1).rstrip())
            wa.append(f'attribute set position "vec(pos.x, pos.y, {C.FELT} + {arch})"')
            wa.append("material assign Plank\nmode edit")
            wa.append(f'select face where "(floor(({X} + 100) / 0.25) % 2) == 0"\nmaterial assign Seam\nmode object')
            sn = f"DeckSide{w['index'] + 1}"
            objs.append(sn)
            wa.append(strip(sn, br[0], br[2], br[3], 16, WY - 0.05, f"{C.FELT} + {arch}").rstrip())
            wa.append("material assign Plank")
        for i, r in enumerate(w["gap"]):
            n = f"GapWall{w['index'] + 1}_{i}"
            objs.append(n)
            wa.append(strip(n, r[0], r[2], r[1], 6, -1.3, f"{C.FELT}").rstrip())
            wa.append("material assign Bank")
            f_ = f"GapFloor{w['index'] + 1}_{i}"
            objs.append(f_)
            wa.append(grid(f_, r, 0.15).rstrip())
            wa.append(f'attribute set position "vec(pos.x, pos.y, -1.25 + 0.12 * sin(pos.x * 5.1) * sin(pos.y * 4.3))"')
            wa.append("material assign Cloud")
    wa.append("select " + " ".join(objs) + "\nshade flat\nexport water.glb")
    files["water"] = "\n".join(wa) + "\n"

    # ---------------------------------------------------------------- island
    A, B, N = C.ISLAND_A, C.ISLAND_B, C.ISLAND_N
    isl = ["# The island: the cloud ground round the greens (gently lumpy, deleted under the felt) and the",
           "# lumpy cloud skirt hanging under its rim (a superellipse |x/19.4|^8 + |z/13.5|^8 = 1 tapering",
           "# down; the faces looking away from the camera deleted). Generated by make_course.py.",
           "new", f"material new Cloud {col('cloud')} --no-slot", f"material new Puff {col('puff')} --no-slot",
           f"material new Skirt {col('cloud')} --no-slot", f"material new SkirtPuff {col('puff')} --no-slot"]
    isl.append(grid("Ground", (-A - 0.4, -B - 0.4, A + 0.4, B + 0.4), 0.2).rstrip())
    isl.append("material assign Cloud")
    isl.append('attribute set position "vec(pos.x, pos.y, 0.035 * sin(pos.x * 1.7 + 0.4) * sin(pos.y * 1.3) + 0.03 * sin(pos.x * 0.6 - pos.y * 0.9))"')
    isl.append("mode edit")
    under = " || ".join(inside(r, 0.12) for w in W for r in w["felt"])
    isl.append(f'select face where "pow(abs(pos.x) / {A * 1.005}, {N}) + pow(abs(pos.y) / {B * 1.005}, {N}) > 1 || {under}"')
    isl.append("delete only-faces")
    isl.append('select face where "sin(pos.x * 0.83 + 1.3) * sin(pos.y * 1.07 - 0.4) + 0.6 * sin(pos.x * 0.31 + pos.y * 0.47) > 0.95"')
    isl.append("material assign Puff\nmode object")
    # the skirt: u around the rim (theta), v down (0 at the rim, 1 at the bottom)
    th = "((pos.x + 0.5) * 6.283185 + 0.0001)"
    v = "(0.5 - pos.y)"
    bul = f"(1 + 0.045 * abs(sin({th} * 23 + {v} * 3)) + 0.03 * abs(sin({th} * 9 - {v} * 5)))"
    k_ = f"((1 - 0.78 * pow({v}, 1.5)) * {bul})"
    xs = f"({A} * cos({th}) / pow(abs(cos({th})) + 0.000001, {1 - 2 / N}) * {k_})"
    ys = f"({B} * sin({th}) / pow(abs(sin({th})) + 0.000001, {1 - 2 / N}) * {k_})"
    zs = f"(0.05 - 4.2 * pow({v}, 1.2) + 0.25 * sin({th} * 17) * {v})"
    isl.append("add mesh grid --name Skirt --size 1 --x-subdivisions 220 --y-subdivisions 7 --location 0 0 0")
    isl.append("material assign Skirt")
    isl.append(f'attribute set position "vec({xs}, {ys}, {zs})"')
    isl.append("mode edit")
    isl.append("select all\nnormals recalculate")
    isl.append('select face where "normal.y > 0.3 || normal.z > 0.5"\ndelete only-faces')
    isl.append('select face where "(floor(pos.z / 0.9 + (pos.x + pos.y + 100) / 2.1) % 3) == 0"\nmaterial assign SkirtPuff')
    isl.append("mode object\nselect Ground Skirt\nshade flat\nexport island.glb")
    files["island"] = "\n".join(isl) + "\n"

    for k, v in files.items():
        open(f"{k}.txt", "w").write(v)
        print(f"wrote {k}.txt ({v.count(chr(10))} lines)")

    write_game_block(W)
    write_bake(W)


