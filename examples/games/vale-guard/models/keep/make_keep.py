# Writes the Boulder Keep's hedra command files (the hero: the cannon tower of Vale Guard):
# p1_blockout.txt (every part at the spec's size, with its material) and p2_form.txt (hidden faces
# removed, flat shading, the export). Run from models/keep: /usr/bin/python3 make_keep.py.
# hedra: up Z, front -Y (the muzzle and the door face -Y); origin on the ground under the drum's centre,
# which is the pivot the game turns the tower about.
import math

HEX = {"stone": "9a9a97", "door": "8d6268", "wood": "c28d75", "brass": "be955c", "banner": "9a4f50"}


def rgb(h):
    return " ".join(f"{int(h[i:i + 2], 16) / 255:.4f}" for i in (0, 2, 4))


def mat(name, col):
    return f"material new {name} --base-color {rgb(HEX[col])} --no-slot"


def box(name, cx, cy, cz, sx, sy, sz, m):
    return [f"add mesh cube --name {name} --size 1 --location {cx:.4f} {cy:.4f} {cz:.4f}",
            f"scale {sx:.4f} {sy:.4f} {sz:.4f}", "apply --scale", f"material assign {m}"]


C8 = 1 / math.cos(math.radians(22.5))   # circumradius per apothem of an octagon

# the spec (metres), measured off the FRONT panel at 361 px per metre
DRUM_W0, DRUM_W1, DRUM_H = 1.00, 0.90, 0.76    # across the faces at the ground and at the top
PAR_W, PAR_H = 0.95, 0.12                       # parapet ring
MER, MER_H = 0.15, 0.11                         # merlons
CAR_W, CAR_L, CAR_Z0, CAR_Z1 = 0.42, 0.40, 0.70, 1.00
BAR_R, BAR_L, BAR_Z, BAR_Y, BAR_TILT = 0.115, 0.72, 1.07, -0.17, 14.0
DOOR_W, DOOR_H = 0.26, 0.44
BAN_W, BAN_H, BAN_Z = 0.19, 0.22, 0.47

if __name__ == "__main__":
    p = ["# Boulder Keep, phase 1: blockout at the spec's sizes (generated by make_keep.py).", "new",
         mat("Stone", "stone"), mat("Door", "door"), mat("Wood", "wood"), mat("Brass", "brass"), mat("Banner", "banner")]
    # the drum: an octagonal frustum, a flat face towards the front (rotated 22.5 degrees)
    r0, r1 = DRUM_W0 / 2 * C8, DRUM_W1 / 2 * C8
    p += [f"add mesh cone --name Drum --vertices 8 --radius1 {r0:.4f} --radius2 {r1:.4f} --depth {DRUM_H} "
          f"--location 0 0 {DRUM_H / 2:.4f} --rotation 0 0 22.5", "apply --rotation", "material assign Stone"]
    # the parapet ring, a little wider than the drum's top
    rp = PAR_W / 2 * C8
    p += [f"add mesh cylinder --name Parapet --vertices 8 --radius {rp:.4f} --depth {PAR_H} "
          f"--location 0 0 {DRUM_H + PAR_H / 2:.4f} --rotation 0 0 22.5", "apply --rotation", "material assign Stone"]
    # eight merlons at the face centres
    ra = PAR_W / 2 - MER / 2 - 0.01
    for k in range(8):
        a = math.radians(45 * k - 90)
        p += box(f"Mer{k}", ra * math.cos(a), ra * math.sin(a), DRUM_H + PAR_H + MER_H / 2, MER, MER, MER_H, "Stone")
        p += [f"set rotation 0 0 {45 * k}", "apply --rotation"]
    # the door and the banner on the front face (proud of it by about a splat)
    p += box("Door", 0, -DRUM_W0 / 2 + 0.005, DOOR_H / 2, DOOR_W, 0.07, DOOR_H, "Door")
    zb = BAN_Z + BAN_H / 2
    yb = -(DRUM_W0 / 2 - (DRUM_W0 - DRUM_W1) / 2 * zb / DRUM_H) - 0.015
    p += box("Banner", 0, yb, zb, BAN_W, 0.06, BAN_H, "Banner")
    # the cannon: a wooden block carriage, an octagonal brass barrel tilted up 14 degrees, a muzzle ring
    p += box("Carriage", 0, 0.02, (CAR_Z0 + CAR_Z1) / 2, CAR_W, CAR_L, CAR_Z1 - CAR_Z0, "Wood")
    p += [f"add mesh cylinder --name Barrel --vertices 8 --radius {BAR_R} --depth {BAR_L} --location 0 0 0",
          "set rotation 90 0 0", "apply --rotation", f"set rotation {-BAR_TILT} 0 0", "apply --rotation",
          f"translate 0 {BAR_Y} {BAR_Z}", "material assign Brass"]
    t = math.radians(BAR_TILT)
    my, mz = BAR_Y - (BAR_L / 2 - 0.04) * math.cos(t), BAR_Z + (BAR_L / 2 - 0.04) * math.sin(t)
    p += [f"add mesh cylinder --name Muzzle --vertices 8 --radius {BAR_R + 0.025:.4f} --depth 0.09 --location 0 0 0",
          "set rotation 90 0 0", "apply --rotation", f"set rotation {-BAR_TILT} 0 0", "apply --rotation",
          f"translate 0 {my:.4f} {mz:.4f}", "material assign Brass"]
    open("p1_blockout.txt", "w").write("\n".join(p) + "\n")

    f = ["# Boulder Keep, phase 2: hidden faces removed (the drum's and the parapet's buried bottoms,",
         "# the drum's top under the parapet), the muzzle's bore, flat shading, the export. make_keep.py."]
    for o in ("Drum", "Parapet", "Door", "Banner", "Carriage"):
        f += [f"select {o}", f"active {o}", "mode edit", 'select face where "normal.z < -0.9"', "delete only-faces", "mode object"]
    f += ["select Drum", "active Drum", "mode edit", 'select face where "normal.z > 0.9"', "delete only-faces", "mode object"]
    # the bore: the muzzle's front cap inset and darkened (door wood reads as the dark hole)
    f += ["select Muzzle", "active Muzzle", "mode edit", 'select face where "normal.y < -0.9"', "inset 0.035",
          "material assign Door", "mode object"]
    f += ["select all", "shade flat", "export keep.glb"]
    open("p2_form.txt", "w").write("\n".join(f) + "\n")
