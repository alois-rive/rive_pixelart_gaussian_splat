# Writes p1_blockout.txt for the Wick Knight from the spec's numbers (hero.spec.md, 258 px per metre
# off the FRONT panel). Up Z, facing -Y, origin on the ground between the feet; the knight's right
# hand (sword) at -X, its left (shield) at +X. Run from models/hero: /usr/bin/python3 make_hero.py
SHOULDER_R = (-0.40, 0.0, 0.90)   # the sword arm's pivot (hedra coordinates); game.as: ARM_R
SHOULDER_L = (0.40, 0.0, 0.90)    # the shield arm's pivot; game.as: ARM_L


def box(name, size, loc):
    return [f"add mesh cube --name {name} --size 1 --location {loc[0]:.3f} {loc[1]:.3f} {loc[2]:.3f}",
            f"scale {size[0]:.3f} {size[1]:.3f} {size[2]:.3f}", "apply --scale"]


L = ["# Wick Knight, phase 1: blockout of every named part at the spec's sizes (hero.spec.md).",
     "# Generated by make_hero.py.", "new"]
for s, n in ((-1, "R"), (1, "L")):
    L += box(f"Boot{n}", (0.32, 0.46, 0.17), (s * 0.23, -0.08, 0.085))
    L += box(f"Leg{n}", (0.25, 0.26, 0.34), (s * 0.22, 0.0, 0.32))
    L += [f"add mesh ico-sphere --name Pauldron{n} --subdivisions 1 --radius 0.21 --location {s * 0.37:.3f} 0 0.92",
          "scale 1 1 0.85", "apply --scale"]
    L += box(f"Arm{n}", (0.18, 0.2, 0.26), (s * 0.43, 0.0, 0.72))
# torso: an 8-sided barrel, wider at the chest; a waist ring; the cape down the back
L += ["add mesh cone --name Torso --vertices 8 --radius1 0.29 --radius2 0.34 --depth 0.5 --location 0 0 0.71 --rotation 0 0 22.5",
      "apply --rotation", "scale 1 0.84 1", "apply --scale",
      "add mesh cylinder --name Waist --vertices 8 --radius 0.3 --depth 0.12 --location 0 0 0.47 --rotation 0 0 22.5",
      "apply --rotation", "scale 1 0.86 1", "apply --scale"]
L += box("Cape", (0.62, 0.07, 0.74), (0, 0, 0)) + ["set rotation 14 0 0", "set location 0 0.33 0.6"]
# helm: an 8-sided bucket narrowing a little to its flat top, the T visor, the flame crest
L += ["add mesh cone --name Helm --vertices 8 --radius1 0.3 --radius2 0.26 --depth 0.48 --location 0 0 1.2 --rotation 0 0 22.5",
      "apply --rotation"]
L += box("VisorH", (0.3, 0.07, 0.075), (0, -0.27, 1.27))
L += box("VisorV", (0.085, 0.07, 0.16), (0, -0.27, 1.165))
L += ["add mesh cone --name CrestLo --vertices 4 --radius1 0.025 --radius2 0.11 --depth 0.12 --location 0 0 1.5",
      "scale 1 0.55 1", "apply --scale",
      "add mesh cone --name CrestHi --vertices 4 --radius1 0.11 --radius2 0 --depth 0.24 --location 0 0 1.68",
      "scale 1 0.55 1", "apply --scale"]
# the sword arm: a fist at hip height, the sword pointing straight up beside the helm
L += box("FistR", (0.2, 0.22, 0.2), (-0.5, -0.04, 0.57))
L += box("Guard", (0.27, 0.09, 0.07), (-0.5, -0.04, 0.705))
L += box("Blade", (0.13, 0.055, 0.6), (-0.5, -0.04, 1.04))
L += ["add mesh cone --name Tip --vertices 4 --radius1 0.092 --radius2 0 --depth 0.14 --location -0.5 -0.04 1.41 --rotation 0 0 45",
      "apply --rotation", "scale 1 0.42 1", "apply --scale"]
# the shield arm: a fist behind a 12-sided buckler facing out (+X)
L += box("FistL", (0.2, 0.22, 0.2), (0.5, -0.06, 0.6))
L += ["add mesh cylinder --name Shield --vertices 12 --radius 0.33 --depth 0.1 --location 0 0 0 --rotation 0 90 0",
      "apply --rotation", "set location 0.6 -0.07 0.64"]
L += ["inspect stats"]
open("p1_blockout.txt", "w").write("\n".join(L) + "\n")

P3 = ["# Wick Knight, phase 3: the three game parts for the scene (never saved: run with --no-save).",
      "# Each arm gets its origin at its shoulder and is moved to the world origin, so its GLB's",
      "# geometry is relative to the pivot the game turns it about. Generated by make_hero.py."]
P3 += ["select HeroBody", "export hero_body.glb --selection"]
for name, sh, out in (("SwordArm", SHOULDER_R, "hero_armr.glb"), ("ShieldArm", SHOULDER_L, "hero_arml.glb")):
    P3 += [f"select {name}", f"active {name}", f"cursor set {sh[0]} {sh[1]} {sh[2]}", "origin set --to cursor",
           "set location 0 0 0", f"export {out} --selection"]
open("p3_parts.txt", "w").write("\n".join(P3) + "\n")
print("wrote p1_blockout.txt, p3_parts.txt")
