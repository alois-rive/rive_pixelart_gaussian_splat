# Writes the rocket's hedra command files: p1_blockout.txt (one primitive per part, at the spec's
# sizes) and p2_form.txt (materials in hept32 colours, the window, flat shading, export).
# Run from models/rocket: /usr/bin/python3 make_rocket.py. Up Z, facing -Y; sizes: rocket.spec.md.
import math

def circ(flat, n=8):
    """circumradius of an n-gon whose flats are `flat` from its centre"""
    return flat / math.cos(math.pi / n)

L = ["# Rocket, phase 1: one primitive per part at the spec's sizes. Generated by make_rocket.py.", "new",
     "# fuselage: an eight-sided barrel, flats facing the views: 0.52 wide at z 0.22, 0.64 at z 0.8, 0.5 at z 1.05",
     f"add mesh cone --name BodyLow --vertices 8 --radius1 {circ(0.26):.4f} --radius2 {circ(0.32):.4f} --depth 0.58 --location 0 0 0.51 --rotation 0 0 22.5",
     f"add mesh cone --name BodyHigh --vertices 8 --radius1 {circ(0.32):.4f} --radius2 {circ(0.25):.4f} --depth 0.25 --location 0 0 0.925 --rotation 0 0 22.5",
     "# nose cone: z 1.05 .. 1.40",
     f"add mesh cone --name Nose --vertices 8 --radius1 {circ(0.255):.4f} --radius2 0 --depth 0.35 --location 0 0 1.225 --rotation 0 0 22.5",
     "# the band just below the window: 0.07 tall at z 0.535, a little proud of the body",
     f"add mesh cylinder --name Band --vertices 8 --radius {circ(0.315):.4f} --depth 0.07 --location 0 0 0.535 --rotation 0 0 22.5",
     "# nozzle: a short bell under the fuselage, z 0.05 .. 0.22",
     "add mesh cone --name Nozzle --vertices 8 --radius1 0.17 --radius2 0.12 --depth 0.17 --location 0 0 0.135"]
# fins: a slab 0.14 thick from r 0.23 (the body surface: roots buried deeper poke their discs through the hull) to r 0.48, z 0 .. 0.46 at the body; its outer
# top corner pulled down to z 0.22 (the sweep). Built along +X, then turned to +X, +Y, -X, -Y.
for k, (name, ang) in enumerate([("FinR", 0), ("FinB", 90), ("FinL", 180), ("FinF", 270)]):
    L += [f"# fin {name}",
          "add mesh cube --name %s --size 1 --location 0 0 0" % name,
          "scale 0.25 0.14 0.46", "apply --scale",
          f"active {name}", "mode edit", 'select vert where "pos.x > 0 && pos.z > 0"', "translate 0 0 -0.24",
          "select all", "translate 0.355 0 0.23", "mode object",
          f"set rotation 0 0 {ang}", "apply --rotation"]
open("p1_blockout.txt", "w").write("\n".join(L) + "\n")

P2 = """# Rocket, phase 2: materials (hept32, sRGB 0..1 of the ramp steps), the porthole on the front
# (-Y), flat shading, export. Generated by make_rocket.py.
material new Hull --base-color 1.0 1.0 1.0 --no-slot
material new Trim --base-color 0.855 0.141 0.141 --no-slot
material new Glass --base-color 0.369 0.914 0.914 --no-slot
material new Rim --base-color 0.545 0.592 0.714 --no-slot
material new Nozzle --base-color 0.208 0.212 0.345 --no-slot
select BodyLow BodyHigh
material assign Hull
select Nose FinR FinB FinL FinF
material assign Trim
material new Band --base-color 0.855 0.141 0.141 --no-slot
select Band
material assign Band
select Nozzle
material assign Nozzle
# the porthole: a ten-sided rim 0.30 across standing 0.05 off the front flat (y -0.31 at z 0.77), the glass
# 0.20 across a little prouder still
add mesh cylinder --name Rim --vertices 10 --radius 0.15 --depth 0.08 --location 0 0 0
set rotation 90 0 0
apply --rotation
set location 0 -0.335 0.77
material assign Rim
add mesh cylinder --name Glass --vertices 10 --radius 0.105 --depth 0.08 --location 0 0 0
set rotation 90 0 0
apply --rotation
set location 0 -0.355 0.77
material assign Glass
# caps hidden inside the body bake splats nobody sees: delete them
active BodyLow
mode edit
select face where "normal.z > 0.9"
delete only-faces
mode object
active BodyHigh
mode edit
select face where "normal.z < -0.9"
delete only-faces
mode object
active Nose
mode edit
select face where "normal.z < -0.9"
delete only-faces
mode object
select all
shade flat
export rocket.glb
"""
open("p2_form.txt", "w").write(P2)
