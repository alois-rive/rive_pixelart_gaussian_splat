# Writes the air hockey table's hedra command files and its rink texture, all from one table of
# measurements (the spec, table.spec.md):
#   p1_blockout.txt   one box per part at the spec's sizes (starts with `new`)
#   p2_form.txt       materials in SLSO-CLR17, the rink texture on the playing surface, hidden faces
#                     deleted, the coin plate inset, join, flat shading, export table.glb
#   textures/rink.png the playing surface: teal, a pale centre line and circle, mint goal arcs
# Run from models/table: /usr/bin/python3 make_table.py
# Up Z, front -Y (hedra); X is the table's length. glTF = (x, z, -y).
import math, os
from PIL import Image

L, W = 4.70, 2.45          # body and rail footprint
RAIL = 0.19                # rail width (top view)
RAIL_TOP = 1.21            # rails' top
CAP_BOT = 1.065            # pink cap from here up; purple base below
BASE_BOT = 0.97
SURF = 1.06                # playing surface height
BODY_BOT = 0.49
LEG = 0.29                 # legs: square, inset 0.24 from the ends, 0.16 from the sides
LEG_X = L / 2 - 0.24 - LEG / 2
LEG_Y = W / 2 - 0.16 - LEG / 2
MOUTH = 0.38               # goal mouth half width
POCKET_OUT = 0.16          # pocket: sticks out of each end
POCKET_TOP, POCKET_BOT = 1.04, 0.76
COIN_W, COIN_OUT, COIN_TOP, COIN_BOT = 0.55, 0.10, 0.95, 0.62
IX, IY = L / 2 - RAIL, W / 2 - RAIL     # the playing surface's half extents: 2.16 x 1.035

HEX = {"teal": "2aa4aa", "ice": "c1e5ea", "mint": "41de95", "pink": "ea619d", "purple": "8f3da7",
       "slate": "3e415f", "ink": "2e2c3b", "steel": "55607d", "yellow": "f3c220"}
def rgb(n):
    h = HEX[n]; return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))
def col(n):
    r, g, b = (c / 255 for c in rgb(n)); return f"--base-color {r:.4f} {g:.4f} {b:.4f}"

def box(name, x0, x1, y0, y1, z0, z1):
    return (f"add mesh cube --name {name} --size 1 --location {(x0 + x1) / 2:.4f} {(y0 + y1) / 2:.4f} {(z0 + z1) / 2:.4f}\n"
            f"scale {x1 - x0:.4f} {y1 - y0:.4f} {z1 - z0:.4f}\napply --scale\n")

p1 = ["# Air hockey table, phase 1: blockout. One box per part at the spec's sizes (table.spec.md).",
      "# Generated by make_table.py. Up Z, front -Y (the coin box side), X the length.", "new"]
p1.append(box("Surface", -IX, IX, -IY, IY, SURF - 0.06, SURF))
p1.append(box("Body", -L / 2, L / 2, -W / 2, W / 2, BODY_BOT, BASE_BOT))
# long rails (front -Y and back +Y), two layers
for s, nm in ((-1, "F"), (1, "B")):
    y0, y1 = (s * W / 2, s * (W / 2 - RAIL)) if s < 0 else (W / 2 - RAIL, W / 2)
    y0, y1 = min(y0, y1), max(y0, y1)
    p1.append(box(f"Base{nm}", -L / 2, L / 2, y0, y1, BASE_BOT, CAP_BOT))
    p1.append(box(f"Cap{nm}", -L / 2, L / 2, y0, y1, CAP_BOT, RAIL_TOP))
# end rails: two segments per end, either side of the goal mouth
for sx, ex in ((-1, "L"), (1, "R")):
    x0, x1 = (-L / 2, -L / 2 + RAIL) if sx < 0 else (L / 2 - RAIL, L / 2)
    for sy, ey in ((-1, "F"), (1, "B")):
        y0, y1 = (-(W / 2 - RAIL), -MOUTH) if sy < 0 else (MOUTH, W / 2 - RAIL)
        p1.append(box(f"Base{ex}{ey}", x0, x1, y0, y1, BASE_BOT, CAP_BOT))
        p1.append(box(f"Cap{ex}{ey}", x0, x1, y0, y1, CAP_BOT, RAIL_TOP))
    # the goal pocket: under the mouth, sticking out of the end
    px0, px1 = (-L / 2 - POCKET_OUT, -IX + 0.02) if sx < 0 else (IX - 0.02, L / 2 + POCKET_OUT)
    p1.append(box(f"Pocket{ex}", px0, px1, -MOUTH, MOUTH, POCKET_BOT, POCKET_TOP))
for i, (sx, sy) in enumerate(((-1, -1), (1, -1), (-1, 1), (1, 1))):
    cx, cy = sx * LEG_X, sy * LEG_Y
    p1.append(box(f"Leg{i}", cx - LEG / 2, cx + LEG / 2, cy - LEG / 2, cy + LEG / 2, 0, BODY_BOT))
p1.append(box("Coin", -COIN_W / 2, COIN_W / 2, -W / 2 - COIN_OUT, -W / 2, COIN_BOT, COIN_TOP))

rails = "BaseF CapF BaseB CapB " + " ".join(f"Base{a}{b} Cap{a}{b}" for a in "LR" for b in "FB")
legs = " ".join(f"Leg{i}" for i in range(4))
caps = "CapF CapB " + " ".join(f"Cap{a}{b}" for a in "LR" for b in "FB")
bases = "BaseF BaseB " + " ".join(f"Base{a}{b}" for a in "LR" for b in "FB")

def edit(obj, *cmds):
    return f"select {obj}\nactive {obj}\nmode edit\n" + "\n".join(cmds) + "\nmode object\n"

p2 = ["# Air hockey table, phase 2: materials (exact SLSO-CLR17 sRGB), the rink texture on the playing",
      "# surface, hidden faces deleted (bottoms, faces buried in the body or under the rails), the coin",
      "# plate inset, join, flat shading, export. Run after p1_blockout.txt. Generated by make_table.py.",
      "material new Rink --base-color 1 1 1 --no-slot",
      "material texture Rink base-color textures/rink.png",
      f"material new Cap {col('pink')} --no-slot",
      f"material new Rail {col('purple')} --no-slot",
      f"material new Body {col('slate')} --no-slot",
      f"material new Pocket {col('ink')} --no-slot",
      f"material new Leg {col('steel')} --no-slot",
      f"material new Coin {col('yellow')} --no-slot"]
p2.append(edit("Surface", 'select face where "normal.z < 0.9"', "delete only-faces", "select all",
               "uv project-from-view top --scale-to-bounds"))
p2.append("select Surface\nmaterial assign Rink\n")
p2.append(f"select {caps}\nmaterial assign Cap\n")
p2.append(f"select {bases}\nmaterial assign Rail\n")
p2.append("select Body Coin\nmaterial assign Body\n")
p2.append("select PocketL PocketR\nmaterial assign Pocket\n")
p2.append(f"select {legs}\nmaterial assign Leg\n")
# the body's top is under the surface and rails, its bottom never seen
p2.append(edit("Body", 'select face where "abs(normal.z) > 0.9"', "delete only-faces"))
for i in range(4):
    p2.append(edit(f"Leg{i}", 'select face where "abs(normal.z) > 0.9"', "delete only-faces"))
for o in bases.split():
    p2.append(edit(o, 'select face where "abs(normal.z) > 0.9"', "delete only-faces"))
for o in caps.split():
    p2.append(edit(o, 'select face where "normal.z < -0.9"', "delete only-faces"))
for o in ("PocketL", "PocketR"):
    p2.append(edit(o, 'select face where "normal.z < -0.9"', "delete only-faces"))
p2.append(edit("Coin", 'select face where "normal.y < -0.9"', "inset 0.09", "material assign Coin",
               'select face where "normal.y > 0.9"', "delete only-faces"))
p2.append(f"select Surface Body {rails} PocketL PocketR {legs} Coin\nactive Body\njoin\nrename Body Table\n")
p2.append("shade flat\nexport table.glb\n")

with open("p1_blockout.txt", "w") as f:
    f.write("\n".join(p1))
with open("p2_form.txt", "w") as f:
    f.write("\n".join(p2))

# ---------------------------------------------------------------- the rink texture
# 96 x 46 texels over 4.32 x 2.07 m (0.045 m a texel, about one splat): lines 2 texels wide (0.09 m,
# wider than the sheet's 0.06 so they survive the splats). Image x = table x (left to right),
# image y = top view's down = hedra -Y... projected from the top: image up is +Y (the back).
TW, TH = 96, 46
img = Image.new("RGB", (TW, TH), rgb("teal"))
pxl = img.load()
for j in range(TH):
    for i in range(TW):
        x = -IX + (i + 0.5) / TW * 2 * IX
        y = IY - (j + 0.5) / TH * 2 * IY
        d = math.hypot(x, y)
        c = None
        if abs(x) < 0.045:
            c = "ice"                                   # centre line
        if abs(d - 0.48) < 0.045:
            c = "ice"                                   # centre circle (1.0 m across at its outside)
        dg = math.hypot(abs(x) - IX, y)
        if abs(dg - 0.62) < 0.045 and abs(x) < IX:
            c = "mint"                                  # goal arcs
        if c:
            pxl[i, j] = rgb(c)
os.makedirs("textures", exist_ok=True)
img.save("textures/rink.png")
print("wrote p1_blockout.txt, p2_form.txt, textures/rink.png")
