#!/usr/bin/env python3
"""Writes the dragon's hedra command files: p1_blockout.txt (one primitive per named part, at the
spec's sizes), p2_form.txt (materials, joins into Body and Head, flat shading, export) and
p3_split.txt (the two game parts: dragon_body.glb and dragon_head.glb, the head's origin at the
neck pivot). Up Z, facing -Y, origin on the ground under the body. The dragon's own left is +X (the
tail curls round on that side, as in the sheet). Run from this folder: python3 make_dragon.py"""
import math, os
WING = [float(v) for v in os.environ.get('WING', '-30,-18,36').split(',')]

L = []
def c(s): L.append(s)

def seg(name, a, b, r1, r2, verts=6):
    """A tapered cylinder (cone frustum) from point a to point b."""
    d = [b[i] - a[i] for i in range(3)]
    n = math.sqrt(sum(x * x for x in d))
    dx, dy, dz = (x / n for x in d)
    phi = math.degrees(math.acos(max(-1, min(1, dz))))
    psi = math.degrees(math.atan2(dx, -dy))
    m = [(a[i] + b[i]) / 2 for i in range(3)]
    c(f"add mesh cone --name {name} --vertices {verts} --radius1 {r1} --radius2 {r2} --depth {n:.3f} "
      f"--location {m[0]:.3f} {m[1]:.3f} {m[2]:.3f} --rotation {phi:.2f} 0 {psi:.2f}")

def blob(name, loc, size, seg_=8, rings=6):
    c(f"add mesh uv-sphere --name {name} --segments {seg_} --rings {rings} --radius 0.5 --location {loc[0]} {loc[1]} {loc[2]}")
    c(f"scale {size[0]} {size[1]} {size[2]}")
    c("apply --scale")

def spike(name, loc, r, depth, rot):
    c(f"add mesh cone --name {name} --vertices 4 --radius1 {r} --radius2 0 --depth {depth} "
      f"--location {loc[0]} {loc[1]} {loc[2]} --rotation {rot[0]} {rot[1]} {rot[2]}")

c("# Dragon, phase 1: blockout of every named part at the spec's sizes (dragon.spec.md, 213 px per metre")
c("# in the sheet's front panel). Generated by make_dragon.py. Up Z, facing -Y, origin on the ground.")
c("new")
blob("Body", (0, 0.08, 0.63), (1.3, 1.2, 1.22))
c("add mesh cylinder --name Seat --vertices 8 --radius 0.5 --depth 0.2 --location 0 0.12 0.1")
c("scale 1.1 1.0 1")
c("apply --scale")
BK = [float(v) for v in os.environ.get("BACK", "1.4,0.9,0.7,0.4,1.05").split(",")]
blob("Back", (0, BK[3], BK[4]), (BK[0], BK[1], BK[2]))
blob("Belly", (0, -0.36, 0.64), (0.8, 0.42, 1.12))
for s, x in (("L", 0.5), ("R", -0.5)):
    blob(f"Leg{s}", (x * 1.08, -0.16, 0.26), (0.46, 0.7, 0.52))
    c(f"add mesh cylinder --name Foot{s} --vertices 6 --radius 0.5 --depth 0.12 --location {x * 1.08} -0.4 0.06")
    c("scale 0.42 0.46 1")
    c("apply --scale")
    for k, o in enumerate((-0.11, 0, 0.11)):
        spike(f"Toe{s}{k}", (x * 1.08 + o, -0.66, 0.05), 0.05, 0.14, (90, 0, 0))
    blob(f"Arm{s}", (x * 0.62, -0.5, 0.92), (0.2, 0.22, 0.34), 6, 4)
    for k, o in enumerate((-0.05, 0.05)):
        spike(f"Claw{s}{k}", (x * 0.62 + o, -0.6, 0.76), 0.035, 0.1, (180, 0, 0))
blob("Head", (0, -0.18, 1.62), (0.8, 0.86, 0.66))
c("add mesh cube --name Snout --size 1 --location 0 -0.66 1.5")
c("scale 0.46 0.4 0.32")
c("apply --scale")
for s, x in (("L", 0.21), ("R", -0.21)):
    blob(f"Eye{s}", (x, -0.52, 1.74), (0.17, 0.12, 0.2), 6, 4)
    blob(f"Nostril{s}", (x * 0.45, -0.86, 1.56), (0.07, 0.04, 0.06), 4, 3)
    spike(f"Horn{s}", (x * 1.2, -0.04, 2.02), 0.1, 0.38, (-18, 0, 0))
# the spikes down the neck and back, pointing up and back
for k, (y, z) in enumerate(((0.28, 1.45), (0.5, 1.18), (0.62, 0.9))):
    spike(f"Spike{k}", (0, y, z), 0.07, 0.2, (-55, 0, 0))
# wings: a pink membrane slab with a mint arm along its top edge. Each is leaned back about its long
# axis (its face looks forward and up, as both the front and the top views show it), its tip raised,
# and swept back. R = Rz(sweep) Ry(raise) Rx(lean), hedra's extrinsic XYZ.
def rot(v, ax, ay, az):
    x, y, z = v
    a, b, g = (math.radians(t) for t in (ax, ay, az))
    y, z = y * math.cos(a) - z * math.sin(a), y * math.sin(a) + z * math.cos(a)
    x, z = x * math.cos(b) + z * math.sin(b), -x * math.sin(b) + z * math.cos(b)
    x, y = x * math.cos(g) - y * math.sin(g), x * math.sin(g) + y * math.cos(g)
    return (x, y, z)
for s, sx in (("L", 1), ("R", -1)):
    ang = (WING[0], WING[1] * sx, WING[2] * sx)
    root = (0.34 * sx, 0.25, 1.12)
    def at(local):
        o = rot((local[0] * sx, local[1], local[2]), *ang)
        return tuple(round(root[i] + o[i], 3) for i in range(3))
    m = at((0.66, 0, -0.05))
    c(f"add mesh cube --name Wing{s} --size 1 --location {m[0]} {m[1]} {m[2]}")
    c("scale 1.36 0.06 0.72")
    c("apply --scale")
    c(f"set rotation {ang[0]} {ang[1]} {ang[2]}")
    m = at((0.7, 0.0, 0.3))
    c(f"add mesh cube --name WingArm{s} --size 1 --location {m[0]} {m[1]} {m[2]}")
    c("scale 1.44 0.13 0.14")
    c("apply --scale")
    c(f"set rotation {ang[0]} {ang[1]} {ang[2]}")
    for k, u in enumerate((0.34, 0.82, 1.28)):
        m = at((u, 0, -0.38))
        spike(f"WingClaw{s}{k}", m, 0.05, 0.16, (180 + ang[0] * 0.5, 0, 0))
# the tail: out of the back, round the dragon's left (+X) side, ending in a spade by its left foot
TY = float(os.environ.get('TAILY', '0.8'))
pts = [(0.0, 0.5, 0.2), (0.25, TY, 0.14), (0.72, TY - 0.13, 0.12), (0.92, 0.3, 0.1), (0.86, -0.2, 0.08)]
rad = [0.2, 0.16, 0.13, 0.1, 0.08]
for k in range(len(pts) - 1):
    seg(f"Tail{k}", pts[k], pts[k + 1], rad[k], rad[k + 1])
spike("Spade", (0.84, -0.36, 0.12), 0.12, 0.24, (90, 0, 8))
c("select all")
c("inspect stats")
open("p1_blockout.txt", "w").write("\n".join(L) + "\n")

P = []
def p(s): P.append(s)
p("# Dragon, phase 2: materials in exact Blessing colours (sRGB 0..1), joined into the two game parts")
p("# (Body: everything below the neck, Head: head, snout, eyes, nostrils, horns), flat shading, export.")
p("# Scale #96fbc7 (scale ramp step 1), Blush #ffb3cb (blush ramp step 1), Horn #f7ffae, Eye #74569b.")
p("material new Scale --base-color 0.588 0.984 0.780 --no-slot")
p("material new Blush --base-color 1.0 0.702 0.796 --no-slot")
p("material new Horn --base-color 0.969 1.0 0.682 --no-slot")
p("material new Eye --base-color 0.455 0.337 0.608 --no-slot")
mint = ["Body", "Seat", "Back", "LegL", "LegR", "FootL", "FootR", "ArmL", "ArmR", "WingArmL", "WingArmR", "Head", "Snout"] + [f"Tail{k}" for k in range(4)]
pink = ["Belly", "WingL", "WingR"]
yellow = ([f"Toe{s}{k}" for s in "LR" for k in range(3)] + [f"Claw{s}{k}" for s in "LR" for k in range(2)]
          + ["HornL", "HornR", "Spade"] + [f"Spike{k}" for k in range(3)] + [f"WingClaw{s}{k}" for s in "LR" for k in range(3)])
eye = ["EyeL", "EyeR", "NostrilL", "NostrilR"]
for mat, names in (("Scale", mint), ("Blush", pink), ("Horn", yellow), ("Eye", eye)):
    p("select " + " ".join(names))
    p(f"material assign {mat}")
head = ["Head", "Snout", "EyeL", "EyeR", "NostrilL", "NostrilR", "HornL", "HornR"]
body = [n for n in mint + pink + yellow + eye if n not in head]
p("select " + " ".join(head))
p("active Head")
p("join")
p("select " + " ".join(body))
p("active Body")
p("join")
p("# the head turns about the neck (0, -0.05, 1.3)")
p("cursor set 0 -0.05 1.3")
p("select Head")
p("origin set --to cursor")
p("select all")
p("shade flat")
p("inspect stats")
p("export dragon.glb")
open("p2_form.txt", "w").write("\n".join(P) + "\n")

S = ["# Dragon, phase 3: the game parts. Run after p1 + p2 on a fresh model, once per part (build.sh).",
     "# body: delete the head; head: delete the body and move the head's origin (the neck) to 0 0 0."]
open("p3_body.txt", "w").write("\n".join(S + ["select Head", "delete", "export dragon_body.glb"]) + "\n")
open("p3_head.txt", "w").write("\n".join(S + ["select Body", "delete", "select Head", "set location 0 0 0",
                                              "export dragon_head.glb"]) + "\n")
print("wrote p1_blockout.txt p2_form.txt p3_body.txt p3_head.txt")
