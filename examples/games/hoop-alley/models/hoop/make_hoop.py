# Writes the hero hoop's hedra command files and its two drawn textures:
#   p1_blockout.txt  every named part as a primitive at the spec's sizes (measured off sheet.v1)
#   p2_form.txt      materials (exact DinoKnight 16 steps), the board's painted faces, the net's diamonds,
#                    hidden faces deleted; exports hoop.glb (everything: the gates and lookdev),
#                    hoop_body.glb (board, rim, bracket: the game's `hoop` bone)
#   net.txt          the chain net as three bands, each with its origin at its own top centre (the
#                    hinge), exported as net0.glb .. net2.glb (the game's swinging `net0`..`net2` bones)
# Run from models/hoop: /usr/bin/python3 make_hoop.py. Hedra is up Z, the rim towards -Y (the shooter);
# the origin is the rim's centre. World (GLB): x = x, y = z, z = -y.
from PIL import Image

HEX = {"white": "f1f1ea", "navy": "304271", "orange": "ea7730", "red": "cd3d3d", "grey": "95928f",
       "slate": "535867", "dark": "292732"}
def rgb(n):
    h = HEX[n]
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))
def col(n):
    return "--base-color " + " ".join(f"{c / 255:.4f}" for c in rgb(n))
def box(name, x0, x1, y0, y1, z0, z1):
    return [f"add mesh cube --name {name} --size 1 --location {(x0 + x1) / 2:.4f} {(y0 + y1) / 2:.4f} {(z0 + z1) / 2:.4f}",
            f"scale {x1 - x0:.4f} {y1 - y0:.4f} {z1 - z0:.4f}", "apply --scale"]
def write(name, lines):
    open(name, "w").write("\n".join(lines) + "\n")

# ---------------------------------------------------------------- the numbers (spec)
RR, TUBE = 0.335, 0.045                  # rim: ring radius, tube radius (outer 0.38)
BX, BY0, BY1, BZ0, BZ1 = 0.9, 0.43, 0.54, -0.22, 0.91   # board
AX, AZ = (-0.40, 0.40), (0.03, 0.46)     # the four arms' centres
AY1 = 1.23                               # arms end at the wall plate (0.69 m, right panel)
PX, PY1, PZ0, PZ1 = 0.53, 1.38, -0.10, 0.62
NET_TOP, NET_BOT, NR0, NR1 = -0.045, -0.53, 0.33, 0.215
BANDS = 3

# ---------------------------------------------------------------- textures (palette-exact)
# the board's front: 26 x 16 texels (0.069 m), a navy border one texel wide, an orange open square
# (0.76 x 0.51 m, line one texel) whose bottom sits just above the rim; the back: the border only
W, H = 26, 16
def board(front):
    im = Image.new("RGB", (W, H), rgb("white"))
    p = im.load()
    for x in range(W):
        p[x, 0] = p[x, H - 1] = rgb("navy")
    for y in range(H):
        p[0, y] = p[W - 1, y] = rgb("navy")
    if front:
        x0, x1, y0, y1 = 8, 17, 5, 12          # image rows from the top: 0.91 - 0.069 * row
        for x in range(x0, x1 + 1):
            p[x, y0] = p[x, y1] = rgb("orange")
        for y in range(y0, y1 + 1):
            p[x0, y] = p[x1, y] = rgb("orange")
    return im
board(True).save("textures/board_front.png")
board(False).transpose(Image.FLIP_LEFT_RIGHT).save("textures/board_back.png")
# the net: 24 x 6 texels round each band, grey with darker diagonal chains crossing in diamonds
net = Image.new("RGB", (24, 6), rgb("grey"))
p = net.load()
for y in range(6):
    for x in range(24):
        if (x + y) % 6 == 0 or (x - y) % 6 == 0:
            p[x, y] = rgb("slate")
net.save("textures/net.png")

# ---------------------------------------------------------------- phase 1: blockout
def band_geo(k):
    zt = NET_TOP + (NET_BOT - NET_TOP) * k / BANDS
    zb = NET_TOP + (NET_BOT - NET_TOP) * (k + 1) / BANDS
    rt = NR0 + (NR1 - NR0) * k / BANDS
    rb = NR0 + (NR1 - NR0) * (k + 1) / BANDS
    return zt, zb, rt, rb

L = ["# Hoop (hero), phase 1: every named part at the spec's sizes, metres off sheet.v1 (281 px a metre in",
     "# the front panel). Up Z, the rim towards -Y; origin at the rim's centre. Generated by make_hoop.py.", "new"]
L += box("Board", -BX, BX, BY0, BY1, BZ0, BZ1)
for i, ax in enumerate(AX):
    for j, az in enumerate(AZ):
        L += box(f"Arm{i}{j}", ax - 0.05, ax + 0.05, BY1, AY1, az - 0.05, az + 0.05)
L += box("Plate", -PX, PX, AY1, PY1, PZ0, PZ1)
L += [f"add mesh torus --name Rim --major-radius {RR} --minor-radius {TUBE} --major-segments 12 --minor-segments 4 --location 0 0 0"]
L += box("Clip", -0.1, 0.1, RR - 0.04, BY0, -0.04, 0.09)
for k in range(BANDS):
    zt, zb, rt, rb = band_geo(k)
    L += [f"add mesh cone --name Net{k} --vertices 12 --radius1 {rb:.4f} --radius2 {rt:.4f} --depth {zt - zb:.4f} "
          f"--cap-fill none --location 0 0 {(zt + zb) / 2:.4f}"]
write("p1_blockout.txt", L)

# ---------------------------------------------------------------- phase 2: form and surfacing
M = ["# Hoop (hero), phase 2: DinoKnight 16 materials (sRGB 0..1 of the ramp steps), the board's painted",
     "# faces (textures/board_front.png, board_back.png), the net's chain diamonds (textures/net.png),",
     "# hidden faces deleted (the arms' ends inside the board and the plate). Generated by make_hoop.py.",
     "material new Board " + col("white") + " --no-slot",
     "material new BoardFront --base-color 1 1 1 --no-slot",
     "material new BoardBack --base-color 1 1 1 --no-slot",
     "material new Rim " + col("red") + " --no-slot",
     "material new Steel " + col("slate") + " --no-slot",
     "material new Net --base-color 1 1 1 --no-slot",
     "select Board", "material assign Board", "active Board", "mode edit",
     "select face where \"normal.y < -0.9\"", "uv project-from-view front --scale-to-bounds", "material assign BoardFront",
     "select face where \"normal.y > 0.9\"", "uv project-from-view back --scale-to-bounds", "material assign BoardBack",
     "mode object",
     "material texture BoardFront base-color textures/board_front.png",
     "material texture BoardBack base-color textures/board_back.png",
     "select Rim Clip", "material assign Rim",
     "select Plate Arm00 Arm01 Arm10 Arm11", "material assign Steel"]
for a in ("Arm00", "Arm01", "Arm10", "Arm11"):
    M += [f"select {a}", f"active {a}", "mode edit", "select face where \"normal.y > 0.9 || normal.y < -0.9\"", "delete face", "mode object"]
for k in range(BANDS):
    M += [f"select Net{k}", f"active Net{k}", "mode edit", "select all", "uv cylinder-project", "mode object",
          "material assign Net"]
M += ["material texture Net base-color textures/net.png",
      "select all", "shade flat", "export hoop.glb",
      "select Board Rim Clip Plate Arm00 Arm01 Arm10 Arm11", "export hoop_body.glb --selection"]
write("p2_form.txt", M)

# ---------------------------------------------------------------- the net bands for the game
N = ["# The chain net as three bands for the game (bones net0..net2): band k is built with its top centre",
     "# (its hinge) at the origin, so the game hangs each from the one above. Generated by make_hoop.py.", "new",
     "material new Net --base-color 1 1 1 --no-slot"]
for k in range(BANDS):
    zt, zb, rt, rb = band_geo(k)
    N += [f"add mesh cone --name Net{k} --vertices 12 --radius1 {rb:.4f} --radius2 {rt:.4f} --depth {zt - zb:.4f} "
          f"--cap-fill none --location 0 0 {-(zt - zb) / 2:.4f}",
          "apply --location", f"active Net{k}", "mode edit", "select all", "uv cylinder-project", "mode object",
          "material assign Net"]
N += ["material texture Net base-color textures/net.png", "select all", "shade flat"]
for k in range(BANDS):
    N += [f"select Net{k}", f"export net{k}.glb --selection"]
write("net.txt", N)
print("wrote p1_blockout.txt p2_form.txt net.txt + textures")
