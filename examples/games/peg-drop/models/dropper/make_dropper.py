# Writes the dropper's hedra command files from the spec (dropper.spec.md): p1_blockout.txt (one
# primitive per part at the spec's sizes, materials in the final Pear36 colours) and p2_form.txt
# (bevelled body, flat shading, the export). Run from models/dropper: /usr/bin/python3 make_dropper.py
# hedra: up Z, front -Y; origin on the ground under the chute (the coin leaves from there).
import math

C = {"Brass": "0.949 0.651 0.369", "Copper": "0.922 0.337 0.294", "CopperIn": "0.451 0.153 0.361",
     "Gold": "1.000 0.894 0.471", "Dark": "0.549 0.247 0.365", "Steel": "0.761 0.761 0.820"}

p1 = ["# Dropper, phase 1: blockout at the spec's sizes (generated by make_dropper.py).", "new"]
p1 += [f"material new {k} --base-color {v} --no-slot" for k, v in C.items()]
p1 += [
    # chute: an octagonal tube, flat to the front, from the ground into the body
    "add mesh cylinder --name Chute --vertices 8 --radius 0.152 --depth 0.27 --location 0 0 0.135 --rotation 0 0 22.5",
    "material assign Dark",
    # body: a brass box 0.84 x 0.65 x 0.55
    "add mesh cube --name Body --size 1 --location 0 0 0.5", "scale 0.84 0.65 0.55", "apply --scale",
    "material assign Brass",
    # hopper: an octagonal funnel, 0.82 across its rim (flats), 0.51 at its foot, 0.27 tall
    "add mesh cone --name Hopper --vertices 8 --radius1 0.276 --radius2 0.444 --depth 0.27 --location 0 0 0.91 --rotation 0 0 22.5",
    "material assign Copper",
    # the coin standing in it, face to the front
    "add mesh cylinder --name Coin --vertices 12 --radius 0.235 --depth 0.08 --location 0 0 1.015 --rotation 90 0 0",
    "material assign Gold",
    # the front gear: a disc and eight teeth, 0.09 proud
    "add mesh cylinder --name Gear --vertices 8 --radius 0.175 --depth 0.09 --location 0 -0.37 0.503 --rotation 90 22.5 0",
    "material assign Dark",
]
teeth = []
for i in range(8):
    a = math.radians(i * 45)
    x, z = 0.205 * math.cos(a), 0.503 + 0.205 * math.sin(a)
    n = f"Tooth{i}"
    teeth.append(n)
    p1 += [f"add mesh cube --name {n} --size 1 --location {x:.4f} -0.37 {z:.4f}", "scale 0.1 0.09 0.1", "apply --scale",
           f"set rotation 0 {-i * 45} 0", "apply --rotation", "material assign Dark"]
p1 += [
    # the wind-up key on the object's own right (-X): a stem and a bow of two lobes, flat to the front
    "add mesh cube --name Stem --size 1 --location -0.47 0 0.535", "scale 0.13 0.07 0.07", "apply --scale",
    "material assign Steel",
    "add mesh cylinder --name LobeTop --vertices 8 --radius 0.107 --depth 0.12 --location -0.623 0 0.643 --rotation 90 22.5 0",
    "material assign Steel",
    "add mesh cylinder --name LobeBot --vertices 8 --radius 0.107 --depth 0.12 --location -0.623 0 0.427 --rotation 90 22.5 0",
    "material assign Steel",
    "add mesh cube --name Bridge --size 1 --location -0.6 0 0.535", "scale 0.12 0.12 0.16", "apply --scale",
    "material assign Steel",
    "select " + " ".join(["Gear"] + teeth), "active Gear", "join",
    "select Stem LobeTop LobeBot Bridge", "active Stem", "join", "rename Stem Key",
]
open("p1_blockout.txt", "w").write("\n".join(p1) + "\n")

p2 = ["# Dropper, phase 2: form (bevelled body corners, the hopper's inside), flat shading, export.",
      # bevel every edge of the body (the sheet's chamfered corners in all three views)
      "select Body", "active Body", "mode edit", "select all", "bevel 0.07", "mode object",
      # the hopper's top cap is its dark inside
      "select Hopper", "active Hopper", "mode edit", 'select face where "normal.z > 0.9"', "material assign CopperIn",
      # its bottom cap is hidden inside the body: no splats there
      'select face where "normal.z < -0.9"', "delete only-faces", "mode object",
      # the chute's top cap is inside the body
      "select Chute", "active Chute", "mode edit", 'select face where "normal.z > 0.9"', "delete only-faces", "mode object",
      "select all", "shade flat", "export dropper.glb"]
open("p2_form.txt", "w").write("\n".join(p2) + "\n")

# phase 3, for the splats only (modeling.md, "When the mesh gate and the splat gate disagree"): every disc
# reaches a radius past its face, so the side and top views come out ~0.1 m too deep and the edge-on
# coin's tip erodes. Shrink the depth (Y) of the hopper and the body, keep the gear on the face, and
# thicken the coin and the key. Run with --no-save after p2; exports dropper_splat.glb (the bake's).
p3 = ["# Dropper, phase 3 (splat fit, generated by make_dropper.py): run after p2 with --no-save.",
      "select Hopper", "scale 1 0.86 1", "apply --scale",
      "select Body", "scale 1 0.86 1", "apply --scale",
      "select Gear", "translate 0 0.045 0",
      "select Coin", "scale 1 1.5 1", "translate 0 0 0.03",
      "select Key", "scale 1 1.4 1",
      "select all", "export dropper_splat.glb"]
open("p3_splat_fit.txt", "w").write("\n".join(p3) + "\n")
