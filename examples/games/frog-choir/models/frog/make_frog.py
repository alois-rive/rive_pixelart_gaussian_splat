# Writes the frog's hedra command files from the spec's numbers (frog.spec.md):
#   p1_blockout.txt  every named part at its size (578 px per metre off the FRONT panel)
#   p2_form.txt      materials in Eggy 15 (exact sRGB of the ramp steps), flat shading, export frog.glb (the gated hero)
#   p3_parts.txt     (run with --no-save) the game's parts: the throat sac (its own bone, pivot at the chin)
#                    and the body in the choir's five skin colours: frog_green/red/gold/blue/violet.glb
# Up Z, facing -Y, origin on the ground under the body. Run from models/frog: /usr/bin/python3 make_frog.py

def rgb(h):
    return " ".join(f"{int(h[i:i + 2], 16) / 255:.4f}" for i in (0, 2, 4))

P = dict(
    body=((0, 0.04, 0.27), (0.32, 0.38, 0.30)),      # centre, half extents
    head=((0, -0.13, 0.50), (0.29, 0.23, 0.13)),
    belly=((0, -0.19, 0.27), (0.21, 0.20, 0.25)),
    eye_r=0.095, eye=(0.175, -0.135, 0.625),
    haunch=((0.31, 0.12, 0.20), (0.15, 0.27, 0.20)),
)
L = ["# Frog, phase 1: blockout of every named part at the spec's sizes (frog.spec.md, 578 px per metre",
     "# off the FRONT panel). Up Z, facing -Y, origin on the ground under the body. Generated by make_frog.py.",
     "new"]

def ellipsoid(name, c, s, seg=8, rings=6):
    return [f"add mesh uv-sphere --name {name} --segments {seg} --rings {rings} --radius 1 --location {c[0]} {c[1]} {c[2]}",
            f"scale {s[0]} {s[1]} {s[2]}", "apply --scale"]

L += ellipsoid("Body", *P["body"])
L += ellipsoid("Head", *P["head"])
L += ellipsoid("Belly", *P["belly"])
for sx, n in ((-1, "L"), (1, "R")):
    ex, ey, ez = P["eye"]
    L += [f"add mesh uv-sphere --name Eye{n} --segments 8 --rings 6 --radius {P['eye_r']} --location {sx * ex} {ey} {ez}"]
    # the yellow iris: a lens on the eye's front, and the slit pupil across it
    L += [f"add mesh uv-sphere --name Iris{n} --segments 8 --rings 6 --radius 0.075 --location {sx * ex} {ey - 0.045} {ez + 0.005}",
          "scale 1 0.7 1", "apply --scale"]
    L += [f"add mesh cube --name Pupil{n} --size 1 --location {sx * ex} {ey - 0.1} {ez + 0.005}",
          "scale 0.10 0.03 0.035", "apply --scale"]
    hc, hs = P["haunch"]
    L += ellipsoid(f"Haunch{n}", (sx * hc[0], hc[1], hc[2]), hs, 8, 5)
    L += [f"add mesh cube --name Arm{n} --size 1 --location {sx * 0.19} -0.25 0.16",
          "scale 0.11 0.11 0.30", "apply --scale", "set rotation -10 0 0", "apply --rotation"]
    L += [f"add mesh cube --name Hand{n} --size 1 --location {sx * 0.21} -0.31 0.03",
          "scale 0.18 0.14 0.06", "apply --scale"]
    L += [f"add mesh cube --name Foot{n} --size 1 --location {sx * 0.37} -0.24 0.03",
          "scale 0.15 0.15 0.06", "apply --scale", f"set rotation 0 0 {sx * -10}", "apply --rotation"]
L += ["inspect stats"]
open("p1_blockout.txt", "w").write("\n".join(L) + "\n")

SKIN = "3c9b87"
p2 = f"""# Frog, phase 2: materials in Eggy 15 (exact sRGB of the ramp steps), joins, flat shading, export.
# Run after p1_blockout.txt. Generated by make_frog.py.
material new Skin --base-color {rgb(SKIN)} --no-slot
material new Belly --base-color {rgb('ddd4cb')} --no-slot
material new Eye --base-color {rgb('f9d955')} --no-slot
material new Pupil --base-color {rgb('0e0c1b')} --no-slot
select Body Head EyeL EyeR HaunchL HaunchR ArmL ArmR HandL HandR FootL FootR
material assign Skin
select Belly
material assign Belly
select IrisL IrisR
material assign Eye
select PupilL PupilR
material assign Pupil
select Body Head Belly EyeL EyeR IrisL IrisR PupilL PupilR HaunchL HaunchR ArmL ArmR HandL HandR FootL FootR
active Body
join
rename Body Frog
shade flat
inspect stats
export frog.glb
"""
open("p2_form.txt", "w").write(p2)

# the choir's skins: each frog's painted (lit) step of its own ramp (art/palette.json)
VAR = {"green": "3c9b87", "red": "ca1e0f", "gold": "ea9d18", "blue": "2bcff2", "violet": "c41be3"}
p3 = ["# Frog, phase 3 (run with --no-save, after p2_form.txt): the game's parts. The throat sac: an",
      "# ellipsoid under the chin, its origin at the chin (the point it inflates from), set at the world",
      "# origin so the bake places the pivot where the scene entry says. Then the body in five skins.",
      "# Generated by make_frog.py.",
      f"material new Sac --base-color {rgb('f9d955')} --no-slot",
      "add mesh uv-sphere --name Sac --segments 8 --rings 6 --radius 1 --location 0 -0.34 0.28",
      "scale 0.2 0.17 0.16", "apply --scale",
      "material assign Sac", "shade flat",
      "cursor set 0 -0.24 0.36", "origin set --to cursor", "set location 0 0 0",
      "export sac.glb --selection"]
for n, h in VAR.items():
    p3 += [f"material set Skin base-color {rgb(h)}", "select Frog", f"export frog_{n}.glb --selection"]
open("p3_parts.txt", "w").write("\n".join(p3) + "\n")
print("wrote p1_blockout.txt, p2_form.txt, p3_parts.txt")
