# Writes the lamplighter's hedra command files: p1_blockout.txt (one primitive per part, at the
# spec's sizes) and p2_form.txt (materials in exact Rosy 42 colours, joins, flat shading, export).
# Run from models/lamplighter: /usr/bin/python3 make_lamplighter.py
# hedra: up Z, the figure faces -Y; its right hand (the pole) at -X. Sizes: lamplighter.spec.md.
import math, os

HERE = os.path.dirname(os.path.abspath(__file__))

def srgb(h):
    h = h.lstrip("#")
    return " ".join(f"{int(h[i:i + 2], 16) / 255:.4f}" for i in (0, 2, 4))

def bar(name, a, b, r, verts=6):
    """a cylinder of radius r from point a to point b (Euler XYZ: Rx(-asin dy), then Ry(atan2(dx, dz)))"""
    d = [b[i] - a[i] for i in range(3)]
    n = math.sqrt(sum(v * v for v in d))
    dx, dy, dz = (v / n for v in d)
    rx = -math.degrees(math.asin(dy))
    ry = math.degrees(math.atan2(dx, dz))
    c = [(a[i] + b[i]) / 2 for i in range(3)]
    return [f"add mesh cylinder --name {name} --vertices {verts} --radius {r} --depth {n + r:.4f} "
            f"--location {c[0]:.4f} {c[1]:.4f} {c[2]:.4f} --rotation {rx:.2f} {ry:.2f} 0", "apply --rotation"]

def box(name, sx, sy, sz, x, y, z, rot=None):
    L = [f"add mesh cube --name {name} --size 1 --location {x:.4f} {y:.4f} {z:.4f}",
         f"scale {sx} {sy} {sz}", "apply --scale"]
    if rot:
        L += [f"set rotation {rot[0]} {rot[1]} {rot[2]}", "apply --rotation"]
    return L

PX, PY = -0.268, -0.03          # the pole, in the right hand
LX, LY = -0.43, -0.17           # the lantern hangs here (outward and forward of the pole)

p1 = ["# Lamplighter, phase 1: blockout. One primitive per part at the spec's sizes (metres, from the",
      "# sheet's front panel at 315 px a metre; depths from the right panel). Generated by make_lamplighter.py.",
      "new"]
# boots and legs
for s, nm in ((-1, "R"), (1, "L")):
    p1 += box(f"Boot{nm}", 0.19, 0.27, 0.10, s * 0.14, -0.04, 0.05)
    p1 += box(f"Leg{nm}", 0.15, 0.17, 0.12, s * 0.13, 0.0, 0.15)
# the coat: an 8-sided A-line frustum, hem 0.52 x 0.47, shoulders 0.41 x 0.33
p1 += ["add mesh cone --name Coat --vertices 8 --radius1 0.275 --radius2 0.215 --depth 0.54 --location 0 0 0.435 --rotation 0 0 22.5",
       "apply --rotation", "scale 1 0.86 1", "apply --scale",
       "add mesh cylinder --name Belt --vertices 8 --radius 0.252 --depth 0.07 --location 0 0 0.453 --rotation 0 0 22.5",
       "apply --rotation", "scale 1 0.88 1", "apply --scale"]
# buttons on the coat's front
p1 += [f"add mesh cylinder --name Button0 --vertices 6 --radius 0.045 --depth 0.04 --location 0 -0.205 0.60 --rotation 90 0 0",
       "apply --rotation",
       f"add mesh cylinder --name Button1 --vertices 6 --radius 0.045 --depth 0.04 --location 0 -0.23 0.33 --rotation 90 0 0",
       "apply --rotation"]
# scarf: a ring round the neck and one end down the chest on the figure's left (+X)
p1 += ["add mesh cylinder --name Scarf --vertices 8 --radius 0.19 --depth 0.13 --location 0 -0.02 0.735 --rotation 0 0 22.5",
       "apply --rotation", "scale 1 0.9 1", "apply --scale"]
p1 += box("ScarfEnd", 0.13, 0.06, 0.26, 0.13, -0.19, 0.57, (-8, 0, 0))
# head and eyes
p1 += ["add mesh cylinder --name Head --vertices 8 --radius 0.168 --depth 0.25 --location 0 -0.03 0.885 --rotation 0 0 22.5",
       "apply --rotation"]
p1 += box("EyeR", 0.05, 0.03, 0.06, -0.065, -0.19, 0.875)
p1 += box("EyeL", 0.05, 0.03, 0.06, 0.065, -0.19, 0.875)
# the hat: a wide 12-sided brim sloping up to an 8-sided crown, tilted back 10 degrees about its
# middle (in the right panel the brim's front is 0.04 m higher than its back: the face shows under it)
# the brim is 0.686 m across in the front panel but 0.638 m deep in the right one; the top panel (oblique) draws it deeper: 0.96 splits them
p1 += ["add mesh cylinder --name BrimEdge --vertices 12 --radius 0.343 --depth 0.05 --location 0 -0.02 0.86",
       "scale 1 0.96 1", "apply --scale",
       "add mesh cone --name Brim --vertices 12 --radius1 0.343 --radius2 0.19 --depth 0.17 --location 0 -0.02 0.965",
       "scale 1 0.96 1", "apply --scale",
       "add mesh cone --name Crown --vertices 8 --radius1 0.172 --radius2 0.155 --depth 0.24 --location 0 -0.02 1.105 --rotation 0 0 22.5",
       "apply --rotation",
       "cursor set 0 -0.02 0.9", "select BrimEdge Brim Crown", "rotate x -10 --pivot cursor", "apply --rotation",
       "cursor set 0 0 0"]
# arms: the right one bent to the pole, the left one hanging
p1 += bar("SleeveR", (-0.17, -0.02, 0.67), (-0.25, -0.03, 0.60), 0.075, 6)
p1 += box("GloveR", 0.15, 0.13, 0.17, PX, PY, 0.595)
p1 += bar("SleeveL", (0.19, 0.0, 0.67), (0.31, 0.0, 0.47), 0.075, 6)
p1 += box("GloveL", 0.13, 0.13, 0.17, 0.32, 0.0, 0.365)
# the pole and its hook
p1 += bar("Pole", (PX, PY, 0.0), (PX, PY, 1.36), 0.04, 6)
p1 += bar("Hook0", (PX, PY, 1.36), (-0.33, -0.085, 1.445), 0.035, 6)
p1 += bar("Hook1", (-0.33, -0.085, 1.445), (LX, LY, 1.42), 0.035, 6)
p1 += bar("Hook2", (LX, LY, 1.42), (LX, LY, 1.33), 0.03, 6)
# the lantern: a pyramid cap, glass body, corner posts, a cross of mullions, a base plate
p1 += [f"add mesh cone --name LampCap --vertices 4 --radius1 0.18 --radius2 0.03 --depth 0.11 --location {LX} {LY} 1.275 --rotation 0 0 45",
       "apply --rotation"]
# glass a little larger than drawn and thin corner posts, no mullions: at the splat spacing the
# frame's discs spread over the panes and swallowed them
p1 += box("LampGlass", 0.21, 0.21, 0.18, LX, LY, 1.135)
for i, (dx, dy) in enumerate(((-1, -1), (1, -1), (1, 1), (-1, 1))):
    p1 += box(f"LampPost{i}", 0.035, 0.035, 0.18, LX + dx * 0.11, LY + dy * 0.11, 1.135)
p1 += box("LampBase", 0.24, 0.24, 0.035, LX, LY, 1.035)
p1 += ["select all", "shade flat"]
open(os.path.join(HERE, "p1_blockout.txt"), "w").write("\n".join(p1) + "\n")

C = {"Coat": "#cf752b", "Belt": "#7d3833", "Dark": "#3b2027", "Hat": "#52333f", "Face": "#ffc2a1", "Eye": "#21181b",
     "Scarf": "#4fa4b8", "Pole": "#8f4d57", "Glass": "#ffee83"}
p2 = ["# Lamplighter, phase 2: materials (exact Rosy 42 colours; the glass emissive, so it bakes unlit),",
      "# hidden faces dropped, everything joined into one Lamplighter, flat shading, export.",
      "# Generated by make_lamplighter.py."]
for m, h in C.items():
    p2.append(f"material new {m} --base-color {srgb(h)} --no-slot" + (f" --emission {srgb(h)}" if m == "Glass" else ""))
assign = {"Coat": ["Coat", "SleeveR", "SleeveL"], "Belt": ["Belt", "Button0", "Button1"],
          "Dark": ["BootR", "BootL", "LegR", "LegL", "GloveR", "GloveL", "LampCap",
                   "LampPost0", "LampPost1", "LampPost2", "LampPost3", "LampBase"],
          "Hat": ["BrimEdge", "Brim", "Crown"],
          "Face": ["Head"], "Eye": ["EyeR", "EyeL"], "Scarf": ["Scarf", "ScarfEnd"],
          "Pole": ["Pole", "Hook0", "Hook1", "Hook2"], "Glass": ["LampGlass"]}
for m, objs in assign.items():
    for o in objs:
        p2 += [f"select {o}", f"active {o}", f"material assign {m}"]
# the soles and the pole's foot sit on the ground: nobody sees them
for o in ["BootR", "BootL", "Pole"]:
    p2 += [f"select {o}", f"active {o}", "mode edit", 'select face where "normal.z < -0.9"', "delete only-faces", "mode object"]
everything = [o for objs in assign.values() for o in objs]
p2 += ["select " + " ".join(everything), "active Coat", "join", "rename Coat Lamplighter",
       "select all", "shade flat", "export lamplighter.glb"]
open(os.path.join(HERE, "p2_form.txt"), "w").write("\n".join(p2) + "\n")
print("wrote p1_blockout.txt p2_form.txt")
