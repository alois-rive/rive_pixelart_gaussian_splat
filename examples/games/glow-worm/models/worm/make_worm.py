# Writes the worm's hedra command files from the spec's numbers (worm.spec.md): p1_blockout.txt
# (the head as a faceted ellipsoid, eyes, mouth, feelers; four beads as stacks of 8-sided frustum
# rings along the body), p2_form.txt (materials, the head's and beads' slate undersides, joins into
# five parts, flat shading, export worm.glb: the gated hero), p3_splat_fit.txt (fits the mesh to
# the splats: the bench and the scene bake it) and p4_parts.txt (run with --no-save:
# the game's parts, head.glb and bead.glb, each on its own stippled pool of light, pivot on the floor
# under its centre). Up Z, facing -Y (the head at -Y, the tail at +Y). Run from models/worm:
# /usr/bin/python3 make_worm.py
import math
import numpy as np

def euler_from(M):
    ry = -math.asin(max(-1, min(1, M[2, 0])))
    rx = math.atan2(M[2, 1], M[2, 2]); rz = math.atan2(M[1, 0], M[0, 0])
    return [math.degrees(a) for a in (rx, ry, rz)]

def align_z(d):
    """a rotation (hedra extrinsic XYZ) taking local +Z onto d"""
    d = np.asarray(d, float); d /= np.linalg.norm(d)
    x = np.cross([0, 0, 1.0], d) if abs(d[2]) < 0.99 else np.array([1.0, 0, 0])
    if np.linalg.norm(x) < 1e-6: x = np.array([1.0, 0, 0])
    x /= np.linalg.norm(x); y = np.cross(d, x)
    return euler_from(np.stack([x, y, d], 1))

# --- the spec (metres): 431 px per metre off the FRONT and RIGHT panels, lengths x 0.93 (see spec)
HEAD = dict(w=0.492, l=0.358, h=0.394, y=0.0, z=0.200)
#        width, height, length, centre y, centre z
BEADS = [(0.41, 0.39, 0.300, 0.329, 0.194),
         (0.36, 0.36, 0.270, 0.614, 0.190),
         (0.30, 0.31, 0.233, 0.866, 0.183),
         (0.235, 0.255, 0.190, 1.077, 0.178)]
EYE_X, EYE_Z, EYE_R = 0.128, 0.232, 0.064
FEELER_ROOT = (0.10, 0.0, 0.37)
FEELER_TIP = (0.162, -0.12, 0.53)
BALL_R = 0.066
# a bead: five rings front to back (fraction of its length, radius factor): chamfer, pale, band, pale, chamfer
RINGS = [(0.17, 0.70, 1.0), (0.21, 1.0, 1.0), (0.24, 1.0, 1.0), (0.21, 1.0, 1.0), (0.17, 1.0, 0.70)]

L = ["# Worm, phase 1: blockout of every named part at the spec's sizes (worm.spec.md, 431 px per metre",
     "# off the FRONT and RIGHT panels). Up Z, facing -Y, the ground at z 0. Generated by make_worm.py.",
     "new",
     f"add mesh uv-sphere --name Head --segments 10 --rings 7 --radius 0.5 --location 0 {HEAD['y']} {HEAD['z']}",
     f"scale {HEAD['w']} {HEAD['l']} {HEAD['h']}", "apply --scale"]
for s, n in ((-1, "L"), (1, "R")):
    L += [f"add mesh cylinder --name Eye{n} --vertices 8 --radius {EYE_R} --depth 0.06 "
          f"--location {s * EYE_X} -0.150 {EYE_Z} --rotation 90 0 0", "apply --rotation"]
    a, b = np.array([s * FEELER_ROOT[0], FEELER_ROOT[1], FEELER_ROOT[2]]), np.array([s * FEELER_TIP[0], FEELER_TIP[1], FEELER_TIP[2]])
    d = b - a; ln = float(np.linalg.norm(d)); e = align_z(d); c = (a + b) / 2
    L += [f"add mesh cube --name Stalk{n} --size 1 --location {c[0]:.4f} {c[1]:.4f} {c[2]:.4f}",
          f"scale 0.07 0.07 {ln + 0.03:.4f}", "apply --scale", f"set rotation {e[0]:.2f} {e[1]:.2f} {e[2]:.2f}",
          "apply --rotation",
          f"add mesh ico-sphere --name Ball{n} --subdivisions 1 --radius {BALL_R} --location {b[0]:.4f} {b[1]:.4f} {b[2]:.4f}"]
L += ["add mesh cube --name Mouth --size 1 --location 0 -0.162 0.116", "scale 0.12 0.045 0.036", "apply --scale"]
for i, (w, h, ln, yc, zc) in enumerate(BEADS):
    y = yc - ln / 2
    for j, (f, r0, r1) in enumerate(RINGS):
        dl = f * ln
        L += [f"add mesh cone --name B{i}R{j} --vertices 8 --radius1 {h / 2 * r0:.4f} --radius2 {h / 2 * r1:.4f} "
              f"--depth {dl:.4f} --location 0 {y + dl / 2:.4f} {zc} --rotation -90 22.5 0",
              "apply --rotation", f"scale {w / h:.4f} 1 1", "apply --scale"]
        y += dl
L += ["inspect stats"]
open("p1_blockout.txt", "w").write("\n".join(L) + "\n")

# ---------------------------------------------------------------- p2: materials, joins, export
P = ["# Worm, phase 2: materials in Cold Light (exact sRGB), the slate bands (each bead's middle ring)",
     "# and undersides, the inner ring caps deleted (hidden inside the beads), joins into five parts",
     "# (Head, Bead0..Bead3), flat shading, export worm.glb. Run after p1_blockout.txt. Generated by make_worm.py.",
     "material new Glow --base-color 0.6980 0.8353 0.8196 --no-slot",
     "material new Band --base-color 0.2667 0.3020 0.5176 --no-slot",
     "material new Eye --base-color 0.0314 0.0000 0.1216 --no-slot",
     # hedra's join keeps every part's slots (a material twice = two primitives), so the parts are
     # joined first and painted after, by geometry: seed faces, then `select linked`
     "material new Seed --base-color 1 1 1 --no-slot"]
for i in range(len(BEADS)):
    rings = [f"B{i}R{j}" for j in range(len(RINGS))]
    for j, r in enumerate(rings):
        # caps between rings are inside the bead: only the outer chamfers keep a cap (a smaller end)
        P += ["select " + r, "active " + r, "mode edit"]
        if j == 0:
            P += ['select face where "normal.y > 0.9"']
        elif j == len(RINGS) - 1:
            P += ['select face where "normal.y < -0.9"']
        else:
            P += ['select face where "abs(normal.y) > 0.9"']
        P += ["delete only-faces", "mode object"]
    # joined into the middle ring (its origin is the bead's centre): the band is the ring at local y 0
    P += ["select " + " ".join(rings), f"active {rings[2]}", "join", f"rename {rings[2]} Bead{i}",
          "mode edit", "select all", "merge --by-distance 0.001", "material assign Glow",
          f'select face where "abs(pos.y) < {0.15 * BEADS[i][2]:.4f} || normal.z < -0.6"', "material assign Band", "mode object"]
# the head (origin at the head's centre, z 0.2): pale, slate underside, dark eyes and mouth (the faces
# in front of the head's surface, y < -0.172, and their islands), slate stalks, pale balls
P += ["select Head EyeL EyeR StalkL StalkR BallL BallR Mouth", "active Head", "join",
      "mode edit", "select all", "material assign Glow",
      'select face where "normal.z < -0.55"', "material assign Band",
      'select face where "pos.y < -0.172"', "select linked", "material assign Eye",
      'select face where "pos.z > 0.205 && pos.z < 0.25"', "select linked", "material assign Band",
      'select face where "pos.z > 0.36"', "select linked", "material assign Glow",
      "mode object", "material remove Seed",
      "select all", "shade flat", "inspect stats", "export worm.glb"]
open("p2_form.txt", "w").write("\n".join(P) + "\n")


# ---------------------------------------------------------------- p3: fit for the splats
# The splats grow about one radius past every edge, which makes the long, low worm read stubbier
# from the side (splat aspect drift 0.20 on the gated p2 mesh). This phase only fits the mesh to the
# splats: the feeler tips 2 cm lower, the body 6 % longer. The scene and the bench bake this.
STRETCH = 1.06
F = ["# Worm, phase 3: splat fit (run after p2_form.txt; see worm.spec.md). The feeler tips sink 2 cm,",
     "# the whole worm stretches 6 % along its length about the head's centre. Generated by make_worm.py.",
     "select Head", "active Head", "mode edit", 'select vert where "pos.z > 0.25"', "translate 0 0 -0.02",
     "mode object", "select all", "cursor set 0 0 0", f"scale 1 {STRETCH} 1 --pivot cursor", "apply --scale",
     "inspect stats", "export worm.glb"]
open("p3_splat_fit.txt", "w").write("\n".join(F) + "\n")

# ---------------------------------------------------------------- p4: the game's parts
Q = ["# Worm, phase 4 (run with --no-save after p3_splat_fit.txt): the game's parts. head.glb: the head on a",
     "# stippled pool of light 0.56 m in radius; bead.glb: the first (largest) bead on a pool 0.40 m in",
     "# radius. Each part's origin on the floor under its centre (the game's pivot), moved to the world",
     "# origin. The pool: ../env/halo.png, alpha-masked (make_env.py). Generated by make_worm.py.",
     "material new Halo --base-color 1 1 1 --emission 0.2667 0.3020 0.5176 --no-slot",
     "material texture Halo base-color ../env/halo.png", "material set Halo alpha-mode mask",
     "material set Halo alpha-cutoff 0.5",
     "select Head", "cursor set 0 0 0", "origin set --to cursor", "set location 0 0 0",
     "add mesh circle --name HeadPool --vertices 16 --radius 0.56 --cap-fill ngon --location 0 0 0.03",
     "material assign Halo", "mode edit", "select all", "uv project-from-view top --scale-to-bounds", "mode object",
     "select HeadPool Head", "active Head", "join", "select Head", "shade flat", "export head.glb --selection",
     f"select Bead0", f"cursor set 0 {BEADS[0][3] * STRETCH:.4f} 0", "origin set --to cursor", "set location 0 0 0",
     "add mesh circle --name BeadPool --vertices 16 --radius 0.40 --cap-fill ngon --location 0 0 0.03",
     "material assign Halo", "mode edit", "select all", "uv project-from-view top --scale-to-bounds", "mode object",
     "select BeadPool Bead0", "active Bead0", "join", "select Bead0", "shade flat", "export bead.glb --selection"]
open("p4_parts.txt", "w").write("\n".join(Q) + "\n")
print("wrote p1_blockout.txt p2_form.txt p3_splat_fit.txt p4_parts.txt")
