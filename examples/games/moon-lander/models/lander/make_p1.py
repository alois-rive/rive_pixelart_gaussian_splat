# Writes p1_blockout.txt for the lander: the legs are struts between computed points, so their
# rotations are generated. Run from models/lander: /usr/bin/python3 make_p1.py. Up Z, facing -Y; the
# lander's own right is -X (the image's left in FRONT). Sizes: lander.spec.md.
import math
L = ["# Lander, phase 1: one primitive per part at the spec's sizes. Generated by make_p1.py.", "new",
     "# descent stage: an octagon 1.4 m across its flats (flats facing the views), z 0.5..0.96",
     "add mesh cylinder --name Descent --vertices 8 --radius 0.758 --depth 0.46 --location 0 0 0.73 --rotation 0 0 22.5",
     "# cabin: a box 1.04 x 1.1, z 0.96..1.42, under a frustum to 0.76 x 0.82 at z 1.65",
     "add mesh cube --name Cabin --size 1 --location 0 0 1.19", "scale 1.04 1.1 0.46", "apply --scale",
     "add mesh cube --name Roof --size 1 --location 0 0 1.535", "scale 1.04 1.1 0.23", "apply --scale",
     "active Roof", "mode edit", 'select vert where "pos.z > 0"', "scale 0.73 0.75 1", "mode object",
     "# nozzle: a bell under the centre, z 0.17..0.5",
     "add mesh cone --name Nozzle --vertices 8 --radius1 0.23 --radius2 0.15 --depth 0.33 --location 0 0 0.335",
     "# dish antenna on the lander's right (-X), a little back: mast z 1.62..1.82, dish to 1.98, tilted out",
     "add mesh cylinder --name Mast --vertices 6 --radius 0.07 --depth 0.22 --location -0.35 0.1 1.73",
     "add mesh cone --name Dish --vertices 8 --radius1 0.07 --radius2 0.2 --depth 0.13 --location -0.37 0.1 1.88 --rotation 0 -18 0"]
for sx, sy, n in [(1, 1, "BL"), (-1, 1, "BR"), (1, -1, "FL"), (-1, -1, "FR")]:
    top = (0.52 * sx, 0.52 * sy, 0.66)
    pad = (0.88 * sx, 0.88 * sy, 0.06)
    d = [top[i] - pad[i] for i in range(3)]
    ln = math.sqrt(sum(c * c for c in d))
    th = math.degrees(math.acos(d[2] / ln))
    ph = math.degrees(math.atan2(d[1], d[0]))
    mid = [(top[i] + pad[i]) / 2 for i in range(3)]
    L += [f"# leg {n}: from the descent stage's corner ({top[0]:.2f}, {top[1]:.2f}, {top[2]:.2f}) to its pad",
          f"add mesh cube --name Leg{n} --size 1 --location {mid[0]:.3f} {mid[1]:.3f} {mid[2]:.3f}",
          f"scale 0.13 0.13 {ln + 0.08:.3f}", "apply --scale", f"set rotation 0 {th:.2f} {ph:.2f}",
          f"add mesh cylinder --name Pad{n} --vertices 8 --radius 0.17 --depth 0.06 --location {pad[0]:.3f} {pad[1]:.3f} 0.03"]
open("p1_blockout.txt", "w").write("\n".join(L) + "\n")
