# Writes the chute's hedra command files from the spec's numbers (chute.spec.md, 202 px per metre off
# the FRONT panel of ../../art/chute/sheet.v1.png):
#   p1_blockout.txt  one primitive per named part at the spec's sizes
#   p2_form.txt      materials, the open funnel, the sign's inset rings, flat shading, export chute.glb
#   p3_parts.txt     (run with --no-save) the game's parts: chute_body.glb (no disc), and the disc alone
#                    with its origin at its centre in three colours: sign_red/green/cream.glb
# Up Z, facing -Y, origin on the ground under the hopper's centre. Run from models/chute:
# /usr/bin/python3 make_chute.py
HEX = {"navy": "1f244b", "plum": "654053", "brick": "a8605d", "tan": "d1a67e", "cream": "f6e79c",
       "pale": "b6cf8e", "green": "60ae7b", "teal": "3c6b64"}
C = {k: " ".join(f"{int(v[i:i + 2], 16) / 255:.4f}" for i in (0, 2, 4)) for k, v in HEX.items()}

LEG, LEGX, LEGTOP = 0.134, 0.40, 0.86          # legs: square section, centres at +-LEGX, height
HOP_Z0, HOP_Z1 = 0.69, 1.42                     # funnel: outlet height, mouth height
TOP_W, TOP_D, BOT_W, BOT_D = 1.46, 1.38, 0.66, 0.66
RIM_W, RIM_D, RIM_H, RIM_T = 1.50, 1.42, 0.134, 0.08
POST, POST_Y = 0.13, 0.70
DISC_R, DISC_T, DISC_Y, DISC_Z = 0.315, 0.085, 0.75, 1.98

p1 = ["# Chute, phase 1: blockout of every named part at the spec's sizes (chute.spec.md).",
      "# Up Z, facing -Y, origin on the ground under the hopper. Generated by make_chute.py.", "new"]
for i, (sx, sy) in enumerate([(-1, -1), (1, -1), (-1, 1), (1, 1)]):
    p1 += [f"add mesh cube --name Leg{i} --size 1 --location {sx * LEGX} {sy * LEGX} {LEGTOP / 2:.3f}",
           f"scale {LEG} {LEG} {LEGTOP}", "apply --scale"]
# funnel: a box whose bottom verts are pulled in to the outlet
p1 += [f"add mesh cube --name Hopper --size 1 --location 0 0 {(HOP_Z0 + HOP_Z1) / 2:.3f}",
       f"scale {TOP_W} {TOP_D} {HOP_Z1 - HOP_Z0:.3f}", "apply --scale", "active Hopper", "mode edit",
       'select vert where "pos.z < 0"', f"scale {BOT_W / TOP_W:.4f} {BOT_D / TOP_D:.4f} 1", "mode object"]
# rim: four boards round the mouth
zc = HOP_Z1 + RIM_H / 2
p1 += [f"add mesh cube --name RimF --size 1 --location 0 {-(RIM_D - RIM_T) / 2:.3f} {zc:.3f}", f"scale {RIM_W} {RIM_T} {RIM_H}", "apply --scale",
       f"add mesh cube --name RimB --size 1 --location 0 {(RIM_D - RIM_T) / 2:.3f} {zc:.3f}", f"scale {RIM_W} {RIM_T} {RIM_H}", "apply --scale",
       f"add mesh cube --name RimL --size 1 --location {-(RIM_W - RIM_T) / 2:.3f} 0 {zc:.3f}", f"scale {RIM_T} {RIM_D - 2 * RIM_T:.3f} {RIM_H}", "apply --scale",
       f"add mesh cube --name RimR --size 1 --location {(RIM_W - RIM_T) / 2:.3f} 0 {zc:.3f}", f"scale {RIM_T} {RIM_D - 2 * RIM_T:.3f} {RIM_H}", "apply --scale"]
# sign post and disc (the disc faces -Y, the front)
pz0 = HOP_Z1 + RIM_H
p1 += [f"add mesh cube --name Post --size 1 --location 0 {POST_Y} {(pz0 + DISC_Z - DISC_R + 0.04) / 2:.3f}",
       f"scale {POST} {POST} {DISC_Z - DISC_R + 0.04 - pz0:.3f}", "apply --scale",
       f"add mesh cylinder --name Disc --vertices 12 --radius {DISC_R} --depth {DISC_T} --location 0 {DISC_Y} {DISC_Z} --rotation 90 0 0",
       "apply --rotation"]
# mail sack: a squashed icosphere, a tie, a frilled top
p1 += ["add mesh uv-sphere --name Sack --segments 8 --rings 6 --radius 0.32 --location 0 0 0.25",
       "scale 1 1 0.8", "apply --scale",
       "add mesh cylinder --name Tie --vertices 8 --radius 0.13 --depth 0.07 --location 0 0 0.5",
       "add mesh cone --name Frill --vertices 6 --radius1 0.1 --radius2 0.19 --depth 0.11 --location 0 0 0.585",
       "inspect stats"]
open("p1_blockout.txt", "w").write("\n".join(p1) + "\n")

p2 = ["# Chute, phase 2: materials (Paper 8, exact), the funnel opened at the top (two-sided in the bake",
      "# so its inside shows), the sign's cream ring and centre inset on its front face, the sack's",
      "# buried bottom removed, flat shading, export. Generated by make_chute.py.",
      f"material new Wood --base-color {C['plum']} --no-slot",
      f"material new Rim --base-color {C['tan']} --no-slot",
      f"material new Sack --base-color {C['tan']} --no-slot",
      f"material new Cord --base-color {C['plum']} --no-slot",
      f"material new Sign --base-color {C['brick']} --no-slot",
      f"material new Ring --base-color {C['cream']} --no-slot",
      "select Leg0 Leg1 Leg2 Leg3 Hopper Post", "material assign Wood",
      "select RimF RimB RimL RimR", "material assign Rim",
      "select Sack Frill", "material assign Sack",
      "select Tie", "material assign Cord",
      # the funnel: open at the top
      "select Hopper", "active Hopper", "mode edit", 'select face where "normal.z > 0.9"', "delete only-faces", "mode object",
      # legs: the tops are inside the funnel
      ]
for i in range(4):
    p2 += [f"select Leg{i}", f"active Leg{i}", "mode edit", 'select face where "normal.z > 0.9 || normal.z < -0.9"',
           "delete only-faces", "mode object"]
p2 += ["select Disc", "active Disc", "material assign Sign", "mode edit",
       'select face where "normal.y < -0.9"', "material assign Ring", "inset 0.05", "material assign Sign",
       f"inset {DISC_R - 0.05 - 0.135:.3f}", "material assign Ring", "mode object",
       "select Sack", "active Sack", "mode edit", 'select face where "pos.z < -0.21"', "delete only-faces", "mode object",
       "select all", "shade flat", "inspect stats", "export chute.glb"]
open("p2_form.txt", "w").write("\n".join(p2) + "\n")

p3 = ["# Chute, phase 3 (run with --no-save): the game's parts. chute_body.glb is everything but the disc",
      "# (the static chutes); the disc alone, origin at its centre and moved to the origin, is",
      "# sign_red.glb, then recoloured: sign_green.glb (green, cream rings), sign_cream.glb (cream,",
      "# plum ring). The game flips and swaps the discs between the chutes. Generated by make_chute.py.",
      "select Leg0 Leg1 Leg2 Leg3 Hopper Post RimF RimB RimL RimR Sack Tie Frill",
      "export chute_body.glb --selection",
      f"cursor set 0 {DISC_Y} {DISC_Z}", "select Disc", "active Disc", "origin set --to cursor", "set location 0 0 0",
      # the game's signs are solid discs with only the thin outer ring: a cream centre made the red and
      # the cream signs both read as bullseyes at the scene's texel
      "mode edit", 'select face where "normal.y < -0.9 && abs(pos.x) < 0.05 && abs(pos.z) < 0.05"',
      "material assign Sign", "mode object",
      "export sign_red.glb --selection",
      f"material set Sign base-color {C['green']}", "export sign_green.glb --selection",
      f"material set Sign base-color {C['cream']}", f"material set Ring base-color {C['plum']}",
      "export sign_cream.glb --selection"]
open("p3_parts.txt", "w").write("\n".join(p3) + "\n")
print("wrote p1_blockout.txt, p2_form.txt, p3_parts.txt")
