# Writes the sun mirror's hedra command files from the spec's numbers (mirror.spec.md):
# p1_blockout.txt (one primitive per part) and p2_form.txt (materials, the recessed face, the boss,
# hidden faces removed, flat shading, export mirror_p2.glb, the gated form) and p3_splat_fit.txt (exports mirror.glb). Run from models/mirror:
#   /usr/bin/python3 make_mirror.py
# Up Z, the mirror's face towards -Y (hedra's front); origin on the ground under the pivot.
import math

PX = 348.0                      # sheet pixels per metre (front panel: yoke 331 px = 0.95 m)
def m(px): return round(px / PX, 3)

BASE_R = 0.83 / 2 / math.cos(math.radians(22.5))   # octagon, flat to flat 0.83
STEP_R = 0.56 / 2 / math.cos(math.radians(22.5))
BASE_H, STEP_H = 0.167, 0.126
POST_W, POST_TOP = 0.16, 0.497
BAR_H = 0.092
ARM_W, ARM_TOP = 0.09, 1.12
YOKE_W = 0.95
MIR_W, MIR_T, MIR_Z = 0.70, 0.095, 0.974
MIR_R = MIR_W / 2 / math.cos(math.radians(22.5))

def octo(name, r, depth, z):
    # an octagonal prism with flats facing +-X and +-Y
    return (f"add mesh cylinder --name {name} --vertices 8 --radius {r:.4f} --depth {depth:.4f} --location 0 0 {z:.4f}\n"
            f"set rotation 0 0 22.5\napply --rotation\n")

ax = YOKE_W / 2 - ARM_W / 2
arm_h = ARM_TOP - POST_TOP
p1 = f"""# Sun mirror, phase 1: blockout, one primitive per named part at the spec's sizes.
# Generated by make_mirror.py. Up Z, the face towards -Y.
new
{octo('Base', BASE_R, BASE_H, BASE_H / 2)}{octo('Step', STEP_R, STEP_H, BASE_H + STEP_H / 2)}add mesh cube --name Post --size 1 --location 0 0 {(BASE_H + STEP_H + POST_TOP) / 2:.4f}
scale {POST_W} {POST_W} {POST_TOP - BASE_H - STEP_H:.4f}
apply --scale
add mesh cube --name Bar --size 1 --location 0 0 {POST_TOP + BAR_H / 2:.4f}
scale {YOKE_W} {ARM_W} {BAR_H}
apply --scale
add mesh cube --name ArmL --size 1 --location {-ax:.4f} 0 {POST_TOP + arm_h / 2:.4f}
scale {ARM_W} {ARM_W} {arm_h:.4f}
apply --scale
add mesh cube --name ArmR --size 1 --location {ax:.4f} 0 {POST_TOP + arm_h / 2:.4f}
scale {ARM_W} {ARM_W} {arm_h:.4f}
apply --scale
add mesh cylinder --name Mirror --vertices 8 --radius {MIR_R:.4f} --depth {MIR_T} --location 0 0 0
set rotation 0 0 22.5
apply --rotation
set rotation 90 0 0
apply --rotation
set location 0 0 {MIR_Z}
apply --location
add mesh cylinder --name Pins --vertices 6 --radius 0.035 --depth {YOKE_W - 2 * ARM_W + 0.02:.3f} --location 0 0 0
set rotation 0 90 0
apply --rotation
set location 0 0 {MIR_Z}
apply --location
"""

p2 = f"""# Sun mirror, phase 2: materials (exact Sunset Red sRGB of the ramp steps), the face recessed inside
# a rim (inset), the back boss, hidden faces removed, flat shading, export. Run after p1_blockout.txt.
material new Face --base-color 0.9333 0.1412 0.2392 --no-slot
material new Rim --base-color 0.6863 0.1529 0.2784 --no-slot
material new Back --base-color 0.4196 0.1373 0.2549 --no-slot
material new Stone --base-color 0.1569 0.1020 0.1765 --no-slot
material new StoneTop --base-color 0.4196 0.1373 0.2549 --no-slot
select Base Step Post
material assign Stone
select Bar ArmL ArmR Pins
material assign Rim
select Mirror
material assign Rim
active Mirror
mode edit
select face where "normal.y < -0.9"
inset 0.06
material assign Face
select face where "normal.y > 0.9"
material assign Back
mode object
add mesh cylinder --name Boss --vertices 8 --radius 0.1 --depth 0.05 --location 0 0 0
set rotation 90 0 0
apply --rotation
set location 0 {MIR_T / 2 + 0.02:.4f} {MIR_Z}
apply --location
material assign Back
# the pedestal's top faces in the lighter stone; their bottoms sit on the ground: delete them
active Base
mode edit
select face where "normal.z > 0.9"
material assign StoneTop
select face where "normal.z < -0.9"
delete only-faces
mode object
active Step
mode edit
select face where "normal.z > 0.9"
material assign StoneTop
select face where "normal.z < -0.9"
delete only-faces
mode object
active Post
mode edit
select face where "normal.z < -0.9"
delete only-faces
mode object
select Base Step Post Bar ArmL ArmR Mirror Pins Boss
active Base
join
rename Base SunMirror
shade flat
export mirror_p2.glb
"""
open("p1_blockout.txt", "w").write(p1)
open("p2_form.txt", "w").write(p2)
print("wrote p1_blockout.txt, p2_form.txt")

# Phase 3 (splat fit): the splat gate's right view (edge-on) is a thin column the splats widen by a
# disc radius on each side, so the column's parts are made thinner front to back for the splats
# only: the mirror slab, the yoke arms and the crossbar to 0.62 of their depth (about one spacing
# less). It runs on the saved p2 model and exports mirror.glb, the model the game bakes.
p3 = """# Sun mirror, phase 3: splat fit (see make_mirror.py). Thins the edge-on column front to back.
# Run after p2_form.txt.
select SunMirror
active SunMirror
mode edit
select vert where "pos.z > 0.5 || (pos.z > 0.49 && abs(pos.x) > 0.09)"
scale 1 0.62 1 --pivot cursor
mode object
shade flat
export mirror.glb
"""
open("p3_splat_fit.txt", "w").write(p3)
print("wrote p3_splat_fit.txt")
