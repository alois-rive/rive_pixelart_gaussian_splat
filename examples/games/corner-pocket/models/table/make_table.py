# Writes the pub pool table's hedra command files, all from one table of measurements (the spec,
# table.spec.md, measured off art/table/sheet.v1.png at 222 px per metre):
#   p1_blockout.txt   one primitive per part at the spec's sizes (starts with `new`)
#   p2_form.txt       materials in exact Chromatic16 colours, the lamp shade's sloped sides, hidden
#                     faces deleted, the table and the lamp joined into two objects, flat shading,
#                     export table.glb (the hero, gated), table_body.glb and lamp.glb (the scene's
#                     two pieces: the lamp's origin moved to its cords' top, the pivot it swings on)
# Run from models/table: /usr/bin/python3 make_table.py
# Up Z, front -Y (hedra); X is the table's length. glTF = (x, z, -y).

HEX = {"green": "20ac00", "brown": "a05000", "maroon": "800018", "black": "000000", "peach": "ffc080"}


def col(n):
    h = HEX[n]
    r, g, b = (int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))
    return f"--base-color {r:.4f} {g:.4f} {b:.4f}"


# ---------------------------------------------------------------- measurements (metres)
OX, OY = 1.16, 0.66        # rails' outer half extents: 2.32 x 1.32
IX, IY = 1.00, 0.50        # cushion noses (the game's LX, LZ): the felt inside is 2.0 x 1.0
RAIL_TOP, RAIL_BOT = 0.75, 0.61
FELT = 0.71                # the playing surface
APRON_BOT = 0.38
APRON_IN = 0.01            # the apron sits 1 cm inside the rails' outline
LEG = 0.20                 # square legs, inset 0.06 from the outline
LEG_X, LEG_Y = OX - 0.06 - LEG / 2, OY - 0.06 - LEG / 2
POCKET_R = 0.07            # pocket cups: 8-sided, 2 cm proud of the rails
POCKET_TOP, POCKET_BOT = 0.77, 0.60
POCKETS = [(-1.0, -0.5), (0.0, -0.53), (1.0, -0.5), (-1.0, 0.5), (0.0, 0.53), (1.0, 0.5)]
# lamp: a sloped shade 1.33 x 0.44 at its bottom, 1.16 x 0.30 at its top, a glowing strip under it,
# two cords up to 1.94 at x +-0.38
SH_BOT, SH_TOP = 1.25, 1.49
SH_BW, SH_BD = 1.33, 0.44
SH_TW, SH_TD = 1.16, 0.30
GLOW_BOT = 1.19          # the glow strip: the shade's full footprint, 6 cm deep (the sheet's 3 cm, deepened
                         # so it shows under the shade from the game's high camera)
CORD_TOP, CORD_X, CORD_W = 1.94, 0.38, 0.03


def box(name, x0, x1, y0, y1, z0, z1):
    return (f"add mesh cube --name {name} --size 1 --location {(x0 + x1) / 2:.4f} {(y0 + y1) / 2:.4f} {(z0 + z1) / 2:.4f}\n"
            f"scale {x1 - x0:.4f} {y1 - y0:.4f} {z1 - z0:.4f}\napply --scale\n")


p1 = ["# Pub pool table and its lamp, phase 1: blockout. One primitive per part at the spec's sizes",
      "# (table.spec.md). Generated by make_table.py. Up Z, front -Y, X the table's length.", "new"]
p1.append(box("Felt", -IX - 0.02, IX + 0.02, -IY - 0.02, IY + 0.02, FELT - 0.04, FELT))
p1.append(box("RailF", -OX, OX, -OY, -IY, RAIL_BOT, RAIL_TOP))
p1.append(box("RailB", -OX, OX, IY, OY, RAIL_BOT, RAIL_TOP))
p1.append(box("RailL", -OX, -IX, -IY, IY, RAIL_BOT, RAIL_TOP))
p1.append(box("RailR", IX, OX, -IY, IY, RAIL_BOT, RAIL_TOP))
p1.append(box("Apron", -OX + APRON_IN, OX - APRON_IN, -OY + APRON_IN, OY - APRON_IN, APRON_BOT, RAIL_BOT))
for i, (sx, sy) in enumerate(((-1, -1), (1, -1), (-1, 1), (1, 1))):
    cx, cy = sx * LEG_X, sy * LEG_Y
    p1.append(box(f"Leg{i}", cx - LEG / 2, cx + LEG / 2, cy - LEG / 2, cy + LEG / 2, 0, APRON_BOT))
for i, (px, py) in enumerate(POCKETS):
    p1.append(f"add mesh cylinder --name Pocket{i} --vertices 8 --radius {POCKET_R} --depth {POCKET_TOP - POCKET_BOT:.3f} "
              f"--location {px:.3f} {py:.3f} {(POCKET_TOP + POCKET_BOT) / 2:.4f}\n")
p1.append(box("Shade", -SH_BW / 2, SH_BW / 2, -SH_BD / 2, SH_BD / 2, SH_BOT, SH_TOP))
p1.append(box("Glow", -SH_BW / 2 + 0.005, SH_BW / 2 - 0.005, -SH_BD / 2 + 0.005, SH_BD / 2 - 0.005, GLOW_BOT, SH_BOT))
for s, nm in ((-1, "CordL"), (1, "CordR")):
    x = s * CORD_X
    p1.append(box(nm, x - CORD_W / 2, x + CORD_W / 2, -CORD_W / 2, CORD_W / 2, SH_TOP, CORD_TOP))

legs = " ".join(f"Leg{i}" for i in range(4))
pockets = " ".join(f"Pocket{i}" for i in range(6))
rails = "RailF RailB RailL RailR"


def edit(obj, *cmds):
    return f"select {obj}\nactive {obj}\nmode edit\n" + "\n".join(cmds) + "\nmode object\n"


p2 = ["# Pub pool table and its lamp, phase 2: materials (exact Chromatic16 sRGB), the shade's sloped",
      "# sides, the rails' inner faces as cushions, hidden faces deleted, the table and the lamp joined",
      "# into two objects, export. Run after p1_blockout.txt. Generated by make_table.py.",
      f"material new Felt {col('green')} --no-slot",
      f"material new Cushion {col('green')} --no-slot",
      f"material new Rail {col('brown')} --no-slot",
      f"material new Apron {col('maroon')} --no-slot",
      f"material new Leg {col('brown')} --no-slot",
      f"material new Pocket {col('black')} --no-slot",
      f"material new Shade {col('green')} --no-slot",
      f"material new ShadeTop {col('green')} --no-slot",
      f"material new Glow {col('peach')} --no-slot",
      f"material new Cord {col('black')} --no-slot"]
p2.append("select Felt\nmaterial assign Felt\n")
p2.append(edit("Felt", 'select face where "normal.z < 0.9"', "delete only-faces"))
p2.append(f"select {rails}\nmaterial assign Rail\n")
# each rail: bottom deleted (the apron is under it), the face towards the felt is the cushion
for o, cond in (("RailF", "normal.y > 0.9"), ("RailB", "normal.y < -0.9"), ("RailL", "normal.x > 0.9"),
                ("RailR", "normal.x < -0.9")):
    p2.append(edit(o, 'select face where "normal.z < -0.9"', "delete only-faces",
                   f'select face where "{cond}"', "material assign Cushion"))
p2.append("select Apron\nmaterial assign Apron\n")
p2.append(edit("Apron", 'select face where "abs(normal.z) > 0.9"', "delete only-faces"))
p2.append(f"select {legs}\nmaterial assign Leg\n")
for i in range(4):
    p2.append(edit(f"Leg{i}", 'select face where "abs(normal.z) > 0.9"', "delete only-faces"))
p2.append(f"select {pockets}\nmaterial assign Pocket\n")
for i in range(6):
    p2.append(edit(f"Pocket{i}", 'select face where "normal.z < -0.9"', "delete only-faces"))
# the shade: its top face shrunk to 1.16 x 0.30 (sloped sides) and its own material (the same green: the
# scene darkens it so the shade reads as a solid seen from above), its bottom over the glow deleted
p2.append("select Shade\nmaterial assign Shade\n")
p2.append(edit("Shade", 'select face where "normal.z > 0.9"', f"scale {SH_TW / SH_BW:.4f} {SH_TD / SH_BD:.4f} 1",
               "material assign ShadeTop",
               'select face where "normal.z < -0.9"', "delete only-faces"))
p2.append("select Glow\nmaterial assign Glow\n")
p2.append(edit("Glow", 'select face where "normal.z > 0.9"', "delete only-faces"))
p2.append("select CordL CordR\nmaterial assign Cord\n")
p2.append(edit("CordL", 'select face where "abs(normal.z) > 0.9"', "delete only-faces"))
p2.append(edit("CordR", 'select face where "abs(normal.z) > 0.9"', "delete only-faces"))
p2.append(f"select Felt {rails} Apron {legs} {pockets}\nactive Apron\njoin\nrename Apron Table\n")
p2.append("select Shade Glow CordL CordR\nactive Shade\njoin\nrename Shade Lamp\n")
p2.append("select all\nshade flat\nexport table.glb\n")
# the scene's pieces: the table alone, and the lamp with its origin at the cords' top (its pivot)
p2.append("select Table\nexport table_body.glb --selection\n")
p2.append(f"select Lamp\ncursor set 0 0 {CORD_TOP}\norigin set --to cursor\nset location 0 0 0\n"
          "export lamp.glb --selection\n"
          f"set location 0 0 {CORD_TOP}\n")

with open("p1_blockout.txt", "w") as f:
    f.write("\n".join(p1))
with open("p2_form.txt", "w") as f:
    f.write("\n".join(p2))
print("wrote p1_blockout.txt, p2_form.txt")
