# Writes the kettle cart's hedra command files from its spec (cart.spec.md): p1_blockout.txt (one
# primitive per part at the spec's sizes, materials in the final Cretaceous-16 colours), p2_form.txt
# (the band, the slats, the lid, the chimney cap, hidden faces, flat shading, the export cart.glb) and
# the game parts p3_body.txt (cart_body.glb: everything but the wheels) and p3_wheel.txt
# (cart_wheel.glb: one axle's pair of wheels, its origin on the axle).
# hedra: up Z, front (the boiler) towards -Y; origin on the ground under the middle of the body.
# Run from models/cart: /usr/bin/python3 make_cart.py
C = {"Red": "0.486 0.271 0.271", "Slate": "0.271 0.294 0.294", "Cream": "0.737 0.718 0.647",
     "Wood": "0.620 0.502 0.361", "Slat": "0.404 0.322 0.224"}

WY = 0.62      # the axles, +-Y
WZ = 0.228     # wheel radius = axle height
WX = 0.426     # wheel centres, +-X
BOIL_Y = -0.58
CRATE_Y = 0.48


def cube(name, c, s, mat):
    return [f"add mesh cube --name {name} --size 1 --location {c[0]:.4f} {c[1]:.4f} {c[2]:.4f}",
            f"scale {s[0]:.4f} {s[1]:.4f} {s[2]:.4f}", "apply --scale", f"material assign {mat}"]


def octo(name, x, y, z, r, depth, mat, axis="z"):
    """an eight-sided prism, flats on the axes; r is the apothem (half the width across the flats)"""
    rc = r / 0.92388
    L = [f"add mesh cylinder --name {name} --vertices 8 --radius {rc:.4f} --depth {depth:.4f} --location 0 0 0",
         "set rotation 0 0 22.5", "apply --rotation"]
    if axis == "x":
        L += ["set rotation 0 90 0", "apply --rotation"]
    elif axis == "y":
        L += ["set rotation 90 0 0", "apply --rotation"]
    L += [f"set location {x:.4f} {y:.4f} {z:.4f}", "apply --location", f"material assign {mat}"]
    return L


p1 = ["# Kettle cart, phase 1: blockout at the spec's sizes (generated by make_cart.py).", "new"]
p1 += [f"material new {k} --base-color {v} --no-slot" for k, v in C.items()]
# the body: a red box 0.74 x 1.85 x 0.28, 0.2 above the ground
p1 += cube("Body", (0, 0, 0.34), (0.74, 1.85, 0.28), "Red")
# four wheels: octagons 0.456 across, 0.12 thick, outside the body
wheels = []
for sy, ny in ((-1, "F"), (1, "R")):
    for sx, nx in ((-1, "L"), (1, "R")):
        n = f"Wheel{ny}{nx}"
        wheels.append(n)
        p1 += octo(n, sx * WX, sy * WY, WZ, WZ * 0.98, 0.12, "Slate", axis="x")
# the boiler: an octagonal drum 0.61 across the flats, from the body's top to 0.95
p1 += octo("Boiler", 0, BOIL_Y, 0.715, 0.305, 0.47, "Slate")
# the chimney stack
p1 += octo("Stack", 0, BOIL_Y, 1.13, 0.085, 0.26, "Slate")
# the headlamp: a cream octagon on the boiler's front, low
p1 += octo("Lamp", 0, BOIL_Y - 0.305 - 0.045, 0.6, 0.08, 0.09, "Cream", axis="y")
# the crate: 0.65 wide, 0.69 long, 0.51 tall
p1 += cube("Crate", (0, CRATE_Y, 0.735), (0.65, 0.69, 0.51), "Wood")
open("p1_blockout.txt", "w").write("\n".join(p1) + "\n")

p2 = ["# Kettle cart, phase 2: form (generated by make_cart.py): the band, the lid, the chimney cap, the slats,",
      "# the hub caps; hidden faces deleted; flat shading; the export."]
# the cream band round the boiler's middle, a little proud
p2 += octo("Band", 0, BOIL_Y, 0.765, 0.322, 0.07, "Cream")
# the lid: an octagonal frustum from the drum to 0.2 across the flats
p2 += [f"add mesh cone --name Lid --vertices 8 --radius1 {0.305 / 0.92388:.4f} --radius2 {0.2 / 0.92388:.4f} --depth 0.07 --location 0 0 0",
       "set rotation 0 0 22.5", "apply --rotation", f"set location 0 {BOIL_Y} 0.985", "apply --location", "material assign Slate"]
# the chimney's flared cap
p2 += [f"add mesh cone --name Flare --vertices 8 --radius1 {0.085 / 0.92388:.4f} --radius2 {0.14 / 0.92388:.4f} --depth 0.07 --location 0 0 0",
       "set rotation 0 0 22.5", "apply --rotation", f"set location 0 {BOIL_Y} 1.295", "apply --location", "material assign Slate"]
p2 += octo("Cap", 0, BOIL_Y, 1.345, 0.14, 0.03, "Slate")
# the crate's two darker slats, wrapped round it
for k, z in enumerate((0.65, 0.84)):
    p2 += cube(f"Slat{k}", (0, CRATE_Y, z), (0.68, 0.72, 0.075), "Slat")
# hub caps: cream octagons on the outer faces of the wheels
hubs = []
for sy, ny in ((-1, "F"), (1, "R")):
    for sx, nx in ((-1, "L"), (1, "R")):
        n = f"Hub{ny}{nx}"
        hubs.append(n)
        p2 += octo(n, sx * (WX + 0.075), sy * WY, WZ, 0.075, 0.04, "Cream", axis="x")
# hidden faces: the body's bottom stays (seen when the cart tumbles); the stack's bottom inside the lid
p2 += ["select Stack", "active Stack", "mode edit", "select face where \"normal.z < -0.5\"", "delete face", "mode object"]
p2 += ["select Boiler", "active Boiler", "mode edit", "select face where \"normal.z < -0.5\"", "delete face", "mode object"]
p2 += ["select Crate", "active Crate", "mode edit", "select face where \"normal.z < -0.5\"", "delete face", "mode object"]
p2 += ["select all", "shade flat", "export cart.glb"]
open("p2_form.txt", "w").write("\n".join(p2) + "\n")

# game parts (run on a fresh replay of p1 + p2)
body = ["# Kettle cart, phase 3: the body alone (everything but the wheels and their hub caps)."]
body += ["select " + " ".join(wheels + hubs), "delete", "export cart_body.glb"]
open("p3_body.txt", "w").write("\n".join(body) + "\n")
wheel = ["# Kettle cart, phase 3: the front axle's two wheels and hub caps, the axle moved to the origin."]
keep = ["WheelFL", "WheelFR", "HubFL", "HubFR"]
drop = [n for n in ["Body", "Boiler", "Stack", "Lamp", "Crate", "Band", "Lid", "Flare", "Cap", "Slat0", "Slat1"] + wheels + hubs if n not in keep]
wheel += ["select " + " ".join(drop), "delete", "select " + " ".join(keep), "active WheelFL", "join",
          "apply --location", f"select WheelFL", f"set location 0 {WY} {-WZ}", "apply --location", "export cart_wheel.glb"]
open("p3_wheel.txt", "w").write("\n".join(wheel) + "\n")
print("wrote p1_blockout.txt p2_form.txt p3_body.txt p3_wheel.txt")
