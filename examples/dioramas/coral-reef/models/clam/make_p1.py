# Writes p1_blockout.txt for the clam: the zig-zag teeth need a long selection expression
# (vertices at the five "peak" angles of a 10-sided ring), easier generated than typed.
import math
def near(angles, ys, tol=0.1, f="pos"):
    r = f"sqrt({f}.x*{f}.x + {f}.y*{f}.y/{ys*ys:.4f})"
    out = []
    for a in angles:
        c, s = math.cos(math.radians(a)), math.sin(math.radians(a))
        out.append(f"(abs({f}.x/{r} - ({c:.3f})) < {tol} && abs({f}.y/{ys}/{r} - ({s:.3f})) < {tol})")
    return "(" + " || ".join(out) + ")"
PEAKS = [54, 126, 198, 270, 342]
GROOVES = [0, 72, 144, 216, 288]       # side faces between ring verts face 36k degrees: every other one a groove          # ring verts sit at 18 + 36k degrees; 270 is the front centre
L = f"""# Giant clam, phase 1: blockout with its materials (the interior is coloured before its extrude, the
# ribs before the lift: exact BLK AQU4 colours).  Up Z, facing -Y, hinge at the back (+Y). Generated by make_p1.py.
# Lower shell: a 10-sided bowl 2.0 x 1.64 x 0.5, bottom ring at 0.7, hollowed (mantle inside), five
# zig-zag teeth on the rim. Upper shell: the same bowl turned over, the same tapered bowl upside down
# (its dome poked into a low fan), lifted 30 degrees about the hinge (0, 0.82, 0.5).
new
material new Shell --base-color 0.0 0.725 0.745 --no-slot
material new Groove --base-color 0.0 0.373 0.549 --no-slot
material new Mantle --base-color 0.0 0.169 0.349 --no-slot
material new Pearl --base-color 0.624 0.957 0.898 --emission 0.624 0.957 0.898 --no-slot
add mesh cylinder --name Lower --vertices 10 --radius 1.05 --depth 0.5 --location 0 0 0 --rotation 0 0 18
apply --rotation
scale 1 0.82 1
apply --scale
material assign Shell
mode edit
select face where "abs(normal.z) < 0.9 && {near(GROOVES, 1.0, 0.15, 'normal')}"
material assign Groove
select face where "normal.z < -0.9"
scale 0.7 0.7 1
poke
select vert where "pos.z < -0.2 && abs(pos.x) < 0.01 && abs(pos.y) < 0.01"
translate 0 0 -0.06
select face where "normal.z > 0.9"
inset 0.09
material assign Mantle
extrude 0 0 -0.32
select face where "abs(normal.z) < 0.9 && normal.x*pos.x + normal.y*pos.y < 0"
material assign Mantle
select vert where "pos.z > 0.2 && {near(PEAKS, 0.82)}"
translate 0 0 0.12
mode object
set location 0 0 0.25
apply --location
add mesh cylinder --name Upper --vertices 10 --radius 1.05 --depth 0.45 --location 0 0 0 --rotation 0 0 18
apply --rotation
scale 1 0.8 1
apply --scale
material assign Shell
mode edit
select face where "abs(normal.z) < 0.9 && {near(GROOVES, 1.0, 0.15, 'normal')}"
material assign Groove
# the dome (outer face, up while closed): narrowed and poked into a low fan
select face where "normal.z > 0.9"
scale 0.7 0.7 1
poke
select vert where "pos.z > 0.2 && abs(pos.x) < 0.01 && abs(pos.y) < 0.01"
translate 0 0.15 0.08
# the rim (down while closed): hollowed, teeth pointing down
select face where "normal.z < -0.9"
inset 0.09
material assign Groove
extrude 0 0 0.28
select face where "abs(normal.z) < 0.9 && normal.x*pos.x + normal.y*pos.y < 0"
material assign Groove
select vert where "pos.z < -0.2 && {near(PEAKS, 0.8)}"
translate 0 0 -0.12
mode object
# hinge: the upper shell's back edge on the lower one's back edge, then lifted about it
set location 0 0 0.725
apply --location
cursor set 0 0.82 0.5
origin set --to cursor
set rotation -30 0 0
apply --rotation
add mesh ico-sphere --name Pearl --subdivisions 2 --radius 0.21 --location 0 -0.05 0.62
material assign Pearl
"""
open("p1_blockout.txt", "w").write(L)
